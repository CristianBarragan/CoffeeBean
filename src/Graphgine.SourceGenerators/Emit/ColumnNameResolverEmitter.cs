using System;
using System.Collections.Immutable;
using System.Linq;
using System.Text;
using Graphgine.SourceGenerators.Model;

namespace Graphgine.SourceGenerators.Emit;

internal static class ColumnNameResolverEmitter
{
    public static string Emit(
    ImmutableArray<MappingClassInfo> mappings)
{
    var sb = new StringBuilder();

    sb.AppendLine("#nullable enable");
    sb.AppendLine("// <auto-generated/>");
    sb.AppendLine("using System;");
    sb.AppendLine("using Graphgine.Execution;");
    sb.AppendLine();

    sb.AppendLine("namespace Graphgine.Execution");
    sb.AppendLine("{");

    sb.AppendLine("public static class ColumnNameResolver");
    sb.AppendLine("{");

    sb.AppendLine(
        "    public static string Resolve(");
    sb.AppendLine(
        "        ushort storageEntityId,");
    sb.AppendLine(
        "        ushort columnId)");
    sb.AppendLine("    {");

    sb.AppendLine("        return (storageEntityId, columnId) switch");
    sb.AppendLine("        {");


    var entities =
        mappings
            .SelectMany(x => x.Definition.Entities)
            .Where(x => x.EntityType != null)
            .Select(x => x.EntityType!.Name)
            .Distinct()
            .OrderBy(x => x);


    foreach (var entity in entities)
    {
        var columns =
            mappings
                .SelectMany(x => x.FieldMaps)
                .Where(x =>
                    string.Equals(
                        x.DestinationEntity,
                        entity,
                        StringComparison.OrdinalIgnoreCase))
                .Select(x => x.DestinationName)
                .Distinct(StringComparer.OrdinalIgnoreCase)
                .OrderBy(x => x)
                .ToList();


        // ColumnId emitter always reserves 0 for Id
        sb.AppendLine(
            $"            (StorageEntityId.{entity}, 0) => \"Id\",");


        ushort id = 1;

        foreach (var column in columns)
        {
            if (string.Equals(
                    column,
                    "Id",
                    StringComparison.OrdinalIgnoreCase))
            {
                continue;
            }


            sb.AppendLine(
                $"            (StorageEntityId.{entity}, {id}) => \"{Escape(column)}\",");

            id++;
        }
    }


    sb.AppendLine(
        "            _ => throw new ArgumentException(");

    sb.AppendLine(
        "                $\"Unknown StorageEntityId {storageEntityId}, ColumnId {columnId}\")");


    sb.AppendLine("        };");
    sb.AppendLine("    }");

    sb.AppendLine("}");

    sb.AppendLine("}");

    return sb.ToString();
}
    
    private static string Escape(string value)
    {
        return value.Replace("\\", "\\\\")
            .Replace("\"", "\\\"");
    }
}