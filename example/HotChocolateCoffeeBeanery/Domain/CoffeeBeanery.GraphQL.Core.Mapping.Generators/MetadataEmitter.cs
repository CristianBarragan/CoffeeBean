    public static string Emit(
        ImmutableArray<MappingClassInfo> allMappings,
        ImmutableHashSet<INamedTypeSymbol> rootEntityTypes,
        List<FluentEntityNavigationConvention.EntityForeignKeyGraph.Edge> entityGraph)
    {
        var models = allMappings
            .Where(m => m.IsModel)
            .GroupBy(m => m.ModelType.Name, System.StringComparer.OrdinalIgnoreCase)
            .Select(g => g.First())
            .OrderBy(m => m.ModelType.Name, System.StringComparer.Ordinal)
            .ToList();

        var navResults = models.ToDictionary(
            m => m.ModelType.Name,
            m => EntityNavigationConvention.Resolve(m, allMappings, entityGraph, rootEntityTypes),
            System.StringComparer.Ordinal);

        foreach (var m in models)
        {
            if (m.CteUpdateMeta.Count > 0)
                continue;

            var navResult = EntityNavigationConvention.Resolve(
                m,
                allMappings,
                entityGraph,
                rootEntityTypes);

            PopulateCteUpdateMeta(m, navResult);
        }

        var entityTypes = allMappings
            .SelectMany(m => m.Definition.Entities)
            .Where(x => x.EntityType is not null)
            .Select(x => x.EntityType!)
            .GroupBy(
                e => e.Name,
                StringComparer.Ordinal)
            .Select(g => g.First())
            .OrderBy(
                e => e.Name,
                StringComparer.Ordinal)
            .ToList();

        var entitySchemaLookup = allMappings
            .SelectMany(m => m.Definition.Entities
                .Where(x => x.EntityType != null)
                .Select(x => new
                {
                    Entity = x.EntityType!.Name,
                    Schema = m.Schema
                }))
            .Where(x => !string.IsNullOrEmpty(x.Schema))
            .GroupBy(
                x => x.Entity,
                StringComparer.Ordinal)
            .ToDictionary(
                g => g.Key,
                g => g.First().Schema,
                StringComparer.Ordinal);

        var sb = new StringBuilder();

        sb.AppendLine("// <auto-generated/>");
        sb.AppendLine("#nullable enable");
        sb.AppendLine("using System;");
        sb.AppendLine();

        sb.AppendLine("namespace CoffeeBeanery.GraphQL.Core.Runtime");
        sb.AppendLine("{");

        sb.AppendLine("    public static class EntityMeta");
        sb.AppendLine("    {");

        EmitModelNameArray(sb, models);
        EmitTableArray(sb, models);
        EmitSchemaArray(sb, models);
        EmitColumnNameArray(sb, models);
        EmitFieldNameArray(sb, models);
        EmitFieldToColumnArray(sb, models);
        EmitFieldMappingsArray(sb, models);
        EmitConflictColumnsArray(sb, models);
        EmitCteResolutionsArray(sb, models);

        EmitEntitySchemaArray(
            sb,
            entityTypes,
            entitySchemaLookup,
            models);

        EmitEntityTableArray(
            sb,
            entityTypes);

        EmitEntityColumnNameArray(
            sb,
            entityTypes,
            allMappings);

        sb.AppendLine("    }");

        EmitEnumConversions(sb, models);

        sb.AppendLine("}");
        sb.AppendLine();

        EmitModelIdConstants(sb, models);

        EmitGeneratedEntityMetaProvider(sb);

        EmitGeneratedPlannerRegistry(sb);

        return sb.ToString();
    }

    private static void EmitFieldToColumnArray(
        StringBuilder sb,
        List<MappingClassInfo> models)
    {
        sb.AppendLine(
            $"        public static readonly ushort[][] FieldToColumn = new ushort[{models.Count}][]");

        sb.AppendLine("        {");

        foreach (var m in models)
        {
            var mappings = PlannerEmitter.ComputeFieldMappingsEagerPublic(
                m,
                PlannerEmitter.IsCompositeInfo(m));

            if (mappings.Count == 0)
            {
                sb.AppendLine(
                    "            System.Array.Empty<ushort>(),");
                continue;
            }

            var ids = new List<ushort>();

            foreach (var fm in mappings)
            {
                var entity = m.Definition.Entities
                    .FirstOrDefault(e =>
                        e.EntityType != null &&
                        string.Equals(
                            e.EntityType.Name,
                            fm.EntityTypeName,
                            StringComparison.Ordinal));

                if (entity?.EntityType == null)
                {
                    ids.Add(ushort.MaxValue);
                    continue;
                }

                var columns = IdEmitter.GetScalarProperties(
                    entity.EntityType);
                
                var index = columns.FindIndex(c =>
                    string.Equals(
                        c.Name,
                        fm.ColumnName,
                        StringComparison.OrdinalIgnoreCase));

                ids.Add(
                    index < 0
                        ? ushort.MaxValue
                        : (ushort)index);
            }

            sb.AppendLine(
                $"            new ushort[] {{ {string.Join(", ", ids)} }},");
        }

        sb.AppendLine("        };");
        sb.AppendLine();
    }
    
    private static void EmitEnumConversions(
        StringBuilder sb,
        List<MappingClassInfo> models)
    {
        var enumFields = models
            .SelectMany(m => m.FieldMaps
                .Where(f => f.FromEnum != null && f.FromEnum.Count > 0)
                .Select(f => (Model: m, Field: f)))
            .ToList();

        sb.AppendLine("    public static class EnumConversions");
        sb.AppendLine("    {");

        sb.AppendLine(
            "        // Converts a model enum name string to its integer string value.");

        sb.AppendLine(
            "        // Returns null if the field has no enum conversion or the name is unknown.");

        sb.AppendLine(
            "        public static string? TryConvert(ushort storageEntityId, ushort columnId, string value)");

        sb.AppendLine("        {");

        sb.AppendLine(
            "            var normalizedValue = value.Trim().ToUpperInvariant();");
        sb.AppendLine("            switch (storageEntityId)");
        sb.AppendLine("            {");

        foreach (var group in enumFields.GroupBy(
                     x => x.Field.DestinationEntity,
                     StringComparer.Ordinal))
        {
            var entityName = group.Key;

            sb.AppendLine(
                $"                case StorageEntityId.{entityName}:");

            sb.AppendLine("                    switch (columnId)");
            sb.AppendLine("                    {");

            foreach (var (_, field) in group)
            {
                sb.AppendLine(
                    $"                        case (ushort)ColumnId.{entityName}.{field.DestinationName}:");

                sb.AppendLine("                            return normalizedValue switch");
                sb.AppendLine("                            {");

                foreach (var kvp in field.FromEnum!)
                {
                    sb.AppendLine(
                        $"                                \"{kvp.Key.Trim().ToUpperInvariant()}\" => \"{kvp.Value}\",");
                }

                sb.AppendLine(
                    "                                _ => null");

                sb.AppendLine("                            };");
            }

            sb.AppendLine("                    }");
            sb.AppendLine("                    break;");
        }

        sb.AppendLine("            }");

        sb.AppendLine("            return null;");
        sb.AppendLine("        }");

        sb.AppendLine("    }");
        sb.AppendLine();
    }


    private static ushort ResolveStorageEntityId(
        List<MappingClassInfo> models,
        object destinationEntity)
    {
        if (destinationEntity is ushort id)
            return id;

        var name = destinationEntity.ToString();

        var entities = models
            .SelectMany(m => m.Definition.Entities)
            .Where(x => x.EntityType != null)
            .Select(x => x.EntityType!)
            .GroupBy(
                x => x.Name,
                StringComparer.Ordinal)
            .Select(g => g.First())
            .OrderBy(
                x => x.Name,
                StringComparer.Ordinal)
            .ToList();

        var index = entities.FindIndex(e => string.Equals(
            e.Name,
            name,
            StringComparison.Ordinal));

        if (index < 0)
        {
            throw new InvalidOperationException(
                $"Cannot resolve storage entity id for '{name}'");
        }

        return (ushort)index;
    }

