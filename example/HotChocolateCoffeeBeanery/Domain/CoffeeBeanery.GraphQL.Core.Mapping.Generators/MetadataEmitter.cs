    private static void EmitModelNameArray(
        StringBuilder sb,
        List<MappingClassInfo> models)
    {
        sb.AppendLine(
            $"        public static readonly string[][] ModelName = new string[{models.Count}][]");

        sb.AppendLine("        {");

        foreach (var m in models)
        {
            var names = new List<string>
            {
                m.ModelType.Name
            };

            names.AddRange(
                m.CteUpdateMeta
                    .Select(x => x.NavigationAlias)
                    .Distinct());

            sb.AppendLine(
                $"            new string[] {{ {string.Join(", ", names.Select(x => $"\"{x}\""))} }},");
        }

        sb.AppendLine("        };");

        sb.AppendLine();
    }


    private static string ToCamel(string name)
    {
        if (string.IsNullOrEmpty(name))
            return name;

        return char.ToLowerInvariant(name[0])
               + name.Substring(1);
    }

    private static void EmitTableArray(
        StringBuilder sb,
        List<MappingClassInfo> models)
    {
        sb.AppendLine(
            $"        public static readonly string[][] Table = new string[{models.Count}][]");

        sb.AppendLine("        {");

        foreach (var m in models)
        {
            string dbTable;

            if (IsComposite(m))
            {
                var primaryEntity =
                    m.Definition.Entities.FirstOrDefault(k => k.IsPrimary)
                    ?? throw new InvalidOperationException(
                        $"Composite model '{m.ModelType.Name}' has no entry marked isPrimary: true.");

                dbTable =
                    primaryEntity.EntityType?.Name
                    ?? throw new InvalidOperationException(
                        $"Composite model '{m.ModelType.Name}' has no resolved primary EntityType.");
            }
            else
            {
                dbTable =
                    m.EntityType?.Name
                    ?? throw new InvalidOperationException(
                        $"Simple model '{m.ModelType.Name}' has no EntityType.");
            }

            var navAliases = m.CteUpdateMeta
                .Select(c => c.NavigationAlias)
                .Distinct()
                .ToList();

            if (navAliases.Count == 0)
            {
                sb.AppendLine(
                    $"            new string[] {{ \"{dbTable}\" }},");
            }
            else
            {
                sb.AppendLine(
                    $"            new string[] {{ \"{dbTable}\", {string.Join(", ", navAliases.Select(a => $"\"{a}\""))} }},");
            }
        }

        sb.AppendLine("        };");
        sb.AppendLine();
    }


    private static void EmitColumnNameArray(
        StringBuilder sb,
        List<MappingClassInfo> models)
    {
        sb.AppendLine(
            $"        public static readonly string[][] ColumnName = new string[{models.Count}][]");

        sb.AppendLine("        {");

        foreach (var m in models)
        {
            INamedTypeSymbol typeForColumns;

            if (IsComposite(m))
            {
                var primaryEntity =
                    m.Definition.Entities.FirstOrDefault(k => k.IsPrimary);

                typeForColumns =
                    primaryEntity?.EntityType
                    ?? throw new InvalidOperationException(
                        $"Composite model '{m.ModelType.Name}' has no primary EntityType.");
            }
            else
            {
                typeForColumns =
                    m.EntityType
                    ?? throw new InvalidOperationException(
                        $"Simple model '{m.ModelType.Name}' has no EntityType.");
            }

            var cols =
                IdEmitter.GetScalarProperties(
                    typeForColumns);

            sb.AppendLine(
                $"            new string[{cols.Count}]");

            sb.AppendLine("            {");

            foreach (var c in cols)
            {
                sb.AppendLine(
                    $"                \"{c.Name}\",");
            }

            sb.AppendLine("            },");
        }

        sb.AppendLine("        };");
        sb.AppendLine();
    }


    private static bool IsComposite(
        MappingClassInfo info)
    {
        return info.Definition.Entities
            .Where(x => x.EntityType != null)
            .Select(x => x.EntityType!.Name)
            .Distinct(StringComparer.Ordinal)
            .Count() > 1;
    }


