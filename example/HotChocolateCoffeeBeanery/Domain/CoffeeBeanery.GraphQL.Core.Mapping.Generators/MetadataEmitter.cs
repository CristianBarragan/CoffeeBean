    }

private static void EmitConflictColumnsArray(
    StringBuilder sb,
    List<MappingClassInfo> models)
{
    sb.AppendLine(
        $"        public static readonly string[][] ConflictColumns = new string[{models.Count}][]");

    sb.AppendLine(
        "        {");


    foreach (var m in models)
    {
        var keys = m.UpsertKeys
            .Where(k => !string.IsNullOrWhiteSpace(k.Key))
            .Select(k => k.Key)
            .Distinct(StringComparer.OrdinalIgnoreCase)
            .ToList();



        if (keys.Count == 0)
        {
            keys = m.Definition.Entities
                .Where(k =>
                    k.IsPrimary &&
                    !string.IsNullOrWhiteSpace(k.ToColumn))
                .Select(k => k.ToColumn!)
                .Distinct(StringComparer.OrdinalIgnoreCase)
                .ToList();
        }



        if (keys.Count == 0 && PlannerEmitter.IsCompositeInfo(m))
        {
            keys = PlannerEmitter
                .ComputeFieldMappingsEagerPublic(
                    m,
                    composite: true)
                .Where(f =>
                    m.Definition.Entities.Any(e =>
                        e.IsPrimary &&
                        string.Equals(
                            e.EntityType?.Name,
                            f.EntityTypeName,
                            StringComparison.Ordinal) &&
                        string.Equals(
                            e.ToColumn,
                            f.ColumnName,
                            StringComparison.OrdinalIgnoreCase)))
                .Select(f => f.ColumnName)
                .Distinct(StringComparer.OrdinalIgnoreCase)
                .ToList();
        }



        if (keys.Count == 0)
        {
            sb.AppendLine(
                "            System.Array.Empty<string>(),");
        }
        else
        {
            sb.AppendLine(
                $"            new string[] {{ {string.Join(", ", keys.Select(k => $"\"{k}\""))} }},");
        }
    }


    sb.AppendLine(
        "        };");

    sb.AppendLine();
}

private static void EmitCteResolutionsArray(
    StringBuilder sb,
    List<MappingClassInfo> models)
{
    sb.AppendLine(
        $"        public static readonly global::CoffeeBeanery.GraphQL.Core.Runtime.CteResolutionSpec[][] CteResolutions = new global::CoffeeBeanery.GraphQL.Core.Runtime.CteResolutionSpec[{models.Count}][]");

    sb.AppendLine(
        "        {");


    foreach (var m in models)
    {
        if (m.CteUpdateMeta.Count == 0)
        {
            sb.AppendLine(
                "            System.Array.Empty<global::CoffeeBeanery.GraphQL.Core.Runtime.CteResolutionSpec>(),");

            continue;
        }


        var primaryEntity =
            m.Definition.Entities
                .FirstOrDefault(e => e.IsPrimary)
                ?.EntityType;


        var entityColumns =
            primaryEntity == null
                ? new Dictionary<string, ushort>(
                    StringComparer.OrdinalIgnoreCase)
                :
                IdEmitter.GetScalarProperties(primaryEntity)
                    .Select((c, i) =>
                        new
                        {
                            Name = c.Name,
                            Index = (ushort)i
                        })
                    .ToDictionary(
                        x => x.Name,
                        x => x.Index,
                        StringComparer.OrdinalIgnoreCase);



        sb.AppendLine(
            "            new global::CoffeeBeanery.GraphQL.Core.Runtime.CteResolutionSpec[]");

        sb.AppendLine(
            "            {");


        foreach (var cte in m.CteUpdateMeta)
        {
            entityColumns.TryGetValue(
                cte.OwningPrimaryKeyColumn,
                out var pkColumnId);



            var tableAlias =
                cte.NavigationAlias +
                cte.RelatedEntityTypeName;



            sb.AppendLine(
                "                new global::CoffeeBeanery.GraphQL.Core.Runtime.CteResolutionSpec(");


            sb.AppendLine(
                $"                    \"{cte.NavigationAlias}\",");


            sb.AppendLine(
                $"                    \"{cte.ForeignKeyColumn}\",");


            sb.AppendLine(
                $"                    \"{cte.OwningPrimaryKeyColumn}\",");


            sb.AppendLine(
                $"                    {pkColumnId},");


            sb.AppendLine(
                $"                    \"{tableAlias}\",");


            sb.AppendLine(
                $"                    \"{cte.RelatedSurrogateIdColumn}\",");


            sb.AppendLine(
                $"                    \"{cte.RelatedNaturalKeyColumn}\"");


            sb.AppendLine(
                "                ),");
        }


        sb.AppendLine(
            "            },");
    }


    sb.AppendLine(
        "        };");

    sb.AppendLine();
}

