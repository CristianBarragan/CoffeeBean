    internal static class PlannerEmitter
    {
        public static string Emit(
            ImmutableArray<MappingClassInfo> allMappings,
            ImmutableHashSet<INamedTypeSymbol> rootEntityTypes,
            ImmutableDictionary<(INamedTypeSymbol, string), string> fluentInverseNav)
        {
            var models = allMappings
                .Where(m => m.IsModel)
                .OrderBy(m => m.ModelType.Name, System.StringComparer.Ordinal)
                .ToList();

            var navResults = models.ToDictionary(
                m => m.ModelType.Name,
                m => EntityNavigationConvention.Resolve(m, rootEntityTypes, fluentInverseNav),
                System.StringComparer.Ordinal);

            var sb = new StringBuilder();
            sb.AppendLine("#nullable enable");
            sb.AppendLine("// <auto-generated/>");
            
            sb.AppendLine("using System.Collections.Immutable;");
            sb.AppendLine("using CoffeeBeanery.GraphQL.Core.Runtime;");
            sb.AppendLine();
            sb.AppendLine("namespace CoffeeBeanery.GraphQL.Core.Runtime");
            sb.AppendLine("{");

            foreach (var model in models)
            {
                var navResult = navResults.TryGetValue(model.ModelType.Name, out var r) ? r : null;
                EmitPlanner(sb, model, allMappings, models, navResult);
            }

            EmitRegistry(sb, models);

            sb.AppendLine("}");
            return sb.ToString();
        }

        internal static bool IsCompositeInfo(MappingClassInfo info)
        {
            var list = info.ModelToEntityList;
            if (list.Count > 1) return true;

            // Fallback for ModelToEntity path
            string? firstName = null;
            foreach (var k in info.ModelToEntity)
            {
                var name = k.EntityType?.Name;
                if (name is null) continue;
                if (firstName is null) firstName = name;
                else if (!string.Equals(firstName, name, System.StringComparison.Ordinal)) return true;
            }
            return false;
        }

        private static void EmitPlanner(
            StringBuilder sb,
            MappingClassInfo info,
            ImmutableArray<MappingClassInfo> allMappings,
            List<MappingClassInfo> models,
            NavigationResolutionResult? navResult)
        {
            sb.AppendLine($"    public static class {info.ModelType.Name}Planner");
            sb.AppendLine("    {");
        
            var composite = IsCompositeInfo(info);
        
            EmitBuildQuery(sb, info, allMappings, navResult, composite);
            EmitBuildMutation(sb, info, allMappings, models, navResult, composite);
        
            sb.AppendLine("    }");
            sb.AppendLine();
        }

        private static void EmitBuildQuery(
            StringBuilder sb,
            MappingClassInfo info,
            ImmutableArray<MappingClassInfo> allMappings,
            NavigationResolutionResult? navResult,
            bool composite)
        {
            string GetEntityPkProperty(INamedTypeSymbol? entity)
            {
                if (entity == null) return "Id";
                var mappedInfo = allMappings.FirstOrDefault(m => 
                    m.Definition.PrimaryKey != null && 
                    m.Definition.PrimaryKey.Any(pk => SymbolEqualityComparer.Default.Equals(pk.Entity, entity)));
                if (mappedInfo != null)
                {
                    return mappedInfo.Definition.PrimaryKey.First(pk => SymbolEqualityComparer.Default.Equals(pk.Entity, entity)).ColumnKey;
                }
                if (entity.GetMembers().OfType<IPropertySymbol>().Any(p => string.Equals(p.Name, "Id", System.StringComparison.Ordinal))) return "Id";
                var conventionalKey = entity.Name + "Key";
                return entity.GetMembers().OfType<IPropertySymbol>().Any(p => string.Equals(p.Name, conventionalKey, System.StringComparison.Ordinal)) ? conventionalKey : "Id";
            }

            sb.AppendLine("        public static void Build(in SelectionIR node, ref QueryPlanBuilder builder)");
            sb.AppendLine("        {");

            // Pre-calculate secondary links so they are accessible to the childLinks filter below
            var secondaryLinks = info.Definition.Entities
                .Where(k => !k.IsPrimary && k.EntityType != null && k.AliasProperty != null)
                .ToList();

            if (composite)
            {
                var primaryLink = info.Definition.Entities.FirstOrDefault(k => k.IsPrimary);
                var primaryEntityType = primaryLink?.EntityType
                    ?? throw new InvalidOperationException($"Composite model {info.ModelType.Name} has no primary storage entity.");

                var primaryFields = ComputeFieldMappingsEagerPublic(info, composite: true)
                    .Where(f => string.Equals(f.EntityTypeName, primaryEntityType.Name, System.StringComparison.Ordinal))
                    .ToList();

                if (primaryFields.Count > 0)
                {
                    sb.AppendLine("            foreach (var scalar in node.Scalars)");
                    sb.AppendLine("            {");
                    sb.AppendLine("                switch (scalar.FieldId)");
                    sb.AppendLine("                {");

                    foreach (var fm in primaryFields)
                    {
                        sb.AppendLine($"                    case FieldId.{info.ModelType.Name}.{fm.FieldName}:");
                        sb.AppendLine($"                        builder.AddRootColumn(");
                        sb.AppendLine($"                            EntityId.{info.ModelType.Name},");
                        sb.AppendLine($"                            StorageEntityId.{fm.EntityTypeName},");
                        sb.AppendLine($"                            ColumnId.{fm.EntityTypeName}.{fm.ColumnName},");
                        sb.AppendLine($"                            node.OutputAlias, scalar.OutputAlias);");
                        sb.AppendLine("                        break;");
                    }

                    sb.AppendLine("                }");
                    sb.AppendLine("            }");
                    sb.AppendLine();
                }

                if (secondaryLinks.Count > 0)
                {
                    sb.AppendLine("            foreach (var fkChild in node.Children)");
                    sb.AppendLine("            {");

                    foreach (var link in secondaryLinks)
                    {
                        var relatedEntityType = link.EntityType!;
                        var alias             = link.AliasProperty!;
                        var fkColumn          = alias + "Id";

                        var relatedModel = allMappings.FirstOrDefault(m =>
                            m.IsModel &&
                            string.Equals(m.EntityType?.Name, relatedEntityType.Name, System.StringComparison.Ordinal));
                        if (relatedModel is null) continue;

                        string relatedEntityPk = GetEntityPkProperty(relatedEntityType);

                        sb.AppendLine($"                if (string.Equals(fkChild.OutputAlias, \"{alias}\", System.StringComparison.OrdinalIgnoreCase))");
                        sb.AppendLine("                {");
                        sb.AppendLine("                    builder.AddJoin(");
                        sb.AppendLine($"                        EntityId.{info.ModelType.Name},");
                        sb.AppendLine($"                        StorageEntityId.{primaryEntityType.Name},");
                        sb.AppendLine($"                        EntityId.{relatedModel.ModelType.Name},");
                        sb.AppendLine($"                        StorageEntityId.{relatedEntityType.Name},");
                        sb.AppendLine($"                        ColumnId.{primaryEntityType.Name}.{fkColumn},");
                        sb.AppendLine($"                        ColumnId.{relatedEntityType.Name}.{relatedEntityPk},");
                        sb.AppendLine("                        JoinKind.Left, fkChild.OutputAlias);");
                        sb.AppendLine();
                        sb.AppendLine("                    foreach (var subScalar in fkChild.Scalars)");
                        sb.AppendLine("                    {");
                        sb.AppendLine("                        switch (subScalar.FieldId)");
                        sb.AppendLine("                        {");

                        foreach (var prop in IdEmitter.GetScalarProperties(relatedEntityType))
                        {
                            var modelFieldName = relatedModel.FieldMaps
                                .FirstOrDefault(f => !f.IsGenerated && string.Equals(f.DestinationName, prop.Name, System.StringComparison.OrdinalIgnoreCase))
                                ?.SourceName
                                ?? prop.Name;

                            bool fieldExistsOnModel = relatedModel.ModelType.GetMembers().OfType<IPropertySymbol>().Any(p => string.Equals(p.Name, modelFieldName, System.StringComparison.Ordinal));
                            if (!fieldExistsOnModel) continue;

                            sb.AppendLine($"                            case FieldId.{relatedModel.ModelType.Name}.{modelFieldName}:");
                            sb.AppendLine("                                builder.AddColumn(");
                            sb.AppendLine($"                                    EntityId.{relatedModel.ModelType.Name},");
                            sb.AppendLine($"                                    StorageEntityId.{relatedEntityType.Name},");
                            sb.AppendLine($"                                    ColumnId.{relatedEntityType.Name}.{prop.Name},");
                            sb.AppendLine("                                    fkChild.OutputAlias, subScalar.OutputAlias);");
                            sb.AppendLine("                                break;");
                        }

                        sb.AppendLine("                        }");
                        sb.AppendLine("                    }");
                        sb.AppendLine();
                        sb.AppendLine("                    var childrenOnly = new SelectionIR(");
                        sb.AppendLine($"                        EntityId.{relatedModel.ModelType.Name},");
                        sb.AppendLine("                        fkChild.OutputAlias,");
                        sb.AppendLine("                        fkChild.IsConditional,");
                        sb.AppendLine("                        ImmutableArray<ScalarSelection>.Empty,");
                        sb.AppendLine("                        fkChild.Children);");
                        sb.AppendLine($"                    {relatedModel.ModelType.Name}Planner.Build(childrenOnly, ref builder);");
                        sb.AppendLine("                }");
                    }

                    sb.AppendLine("            }");
                    sb.AppendLine();
                }

                var childLinks = ComputeChildLinks(info, allMappings, navResult)
                    .Where(l =>
                    {
                        var childInfo = allMappings.FirstOrDefault(m => string.Equals(m.ModelType.Name, l.ChildModelName, System.StringComparison.Ordinal));
                        if (childInfo == null || IsCompositeInfo(childInfo)) return false;
                        
                        // Exclude links already handled by secondary links mapping loop
                        if (secondaryLinks.Any(sl => string.Equals(sl.AliasProperty, l.NavigationName, System.StringComparison.OrdinalIgnoreCase)))
                        {
                            return false;
                        }
                        return true;
                    })
                    .ToList();

                EmitChildJoinDispatch(sb, info, childLinks);
            }
            else
            {
                var fieldMappings = ComputeFieldMappingsEagerPublic(info, composite: false);

                if (fieldMappings.Count > 0)
                {
                    sb.AppendLine("            foreach (var scalar in node.Scalars)");
                    sb.AppendLine("            {");
                    sb.AppendLine("                switch (scalar.FieldId)");
                    sb.AppendLine("                {");

                    foreach (var fm in fieldMappings)
                    {
                        sb.AppendLine($"                    case FieldId.{info.ModelType.Name}.{fm.FieldName}:");
                        sb.AppendLine($"                        builder.AddRootColumn(");
                        sb.AppendLine($"                            EntityId.{info.ModelType.Name},");
                        sb.AppendLine($"                            StorageEntityId.{fm.EntityTypeName},");
                        sb.AppendLine($"                            ColumnId.{fm.EntityTypeName}.{fm.ColumnName},");
                        sb.AppendLine($"                            node.OutputAlias, scalar.OutputAlias);");
                        sb.AppendLine("                        break;");
                    }

                    sb.AppendLine("                }");
                    sb.AppendLine("            }");
                    sb.AppendLine();
                }

                var childLinks = ComputeChildLinks(info, allMappings, navResult)
                    .Where(l =>
                    {
                        var childInfo = allMappings.FirstOrDefault(m => string.Equals(m.ModelType.Name, l.ChildModelName, System.StringComparison.Ordinal));
                        return childInfo != null && !IsCompositeInfo(childInfo);
                    })
                    .ToList();

                EmitChildJoinDispatch(sb, info, childLinks);
            }

            sb.AppendLine("        }");
            sb.AppendLine();
        }

        private static void EmitChildJoinDispatch(
            StringBuilder sb,
            MappingClassInfo info,
            List<ChildLink> childLinks)
        {
            if (childLinks.Count == 0) return;

            sb.AppendLine("            foreach (var child in node.Children)");
            sb.AppendLine("            {");
            sb.AppendLine("                switch (child.EntityId)");
            sb.AppendLine("                {");

            foreach (var group in childLinks.GroupBy(l => l.ChildModelName, System.StringComparer.Ordinal))
            {
                sb.AppendLine($"                    case EntityId.{group.Key}:");
                var links = group.ToList();

                if (links.Count == 1)
                {
                    var l = links[0];
                    sb.AppendLine($"                        builder.AddJoin(");
                    sb.AppendLine($"                            EntityId.{info.ModelType.Name},");
                    sb.AppendLine($"                            StorageEntityId.{l.ParentEntityName},");
                    sb.AppendLine($"                            EntityId.{l.ChildModelName},");
                    sb.AppendLine($"                            StorageEntityId.{l.ChildEntityName},");
                    sb.AppendLine($"                            ColumnId.{l.ParentEntityName}.{l.ParentJoinColumn},");
                    sb.AppendLine($"                            ColumnId.{l.ChildEntityName}.{l.ChildJoinColumn},");
                    sb.AppendLine($"                            JoinKind.Left, child.OutputAlias);");
                }
                else
                {
                    for (var i = 0; i < links.Count; i++)
                    {
                        var l  = links[i];
                        var kw = i == 0 ? "if" : "else if";
                        sb.AppendLine($"                        {kw} (child.OutputAlias == \"{l.NavigationName}\")");
                        sb.AppendLine($"                        {{");
                        sb.AppendLine($"                            builder.AddJoin(");
                        sb.AppendLine($"                                EntityId.{info.ModelType.Name},");
                        sb.AppendLine($"                                StorageEntityId.{l.ParentEntityName},");
                        sb.AppendLine($"                                EntityId.{l.ChildModelName},");
                        sb.AppendLine($"                                StorageEntityId.{l.ChildEntityName},");
                        sb.AppendLine($"                                ColumnId.{l.ParentEntityName}.{l.ParentJoinColumn},");
                        sb.AppendLine($"                                ColumnId.{l.ChildEntityName}.{l.ChildJoinColumn},");
                        sb.AppendLine($"                                JoinKind.Left, child.OutputAlias);");
                        sb.AppendLine($"                        }}");
                    }
                }

                sb.AppendLine($"                        {group.Key}Planner.Build(child, ref builder);");
                sb.AppendLine("                        break;");
            }

            sb.AppendLine("                }");
            sb.AppendLine("            }");
        }

        private static string ToCamel(string name) =>
            string.IsNullOrEmpty(name) ? name : char.ToLowerInvariant(name[0]) + name.Substring(1);

        private static void EmitBuildMutation(
            StringBuilder sb,
            MappingClassInfo info,
            ImmutableArray<MappingClassInfo> allMappings,
            List<MappingClassInfo> models,
            NavigationResolutionResult? navResult,
            bool composite)
        {
            sb.AppendLine("        public static void BuildMutation(in MutationIR node, ref MutationPlanBuilder builder)");
            sb.AppendLine("        {");

            if (composite)
            {
                EmitCompositeMutation(sb, info, allMappings, models);
            }
            else
            {
                var childLinks = ComputeChildLinks(info, allMappings, navResult)
                    .Where(l =>
                    {
                        var childInfo = allMappings.FirstOrDefault(m => string.Equals(m.ModelType.Name, l.ChildModelName, System.StringComparison.Ordinal));
                        return childInfo != null && !IsCompositeInfo(childInfo);
                    })
                    .ToList();

                EmitSimpleMutation(sb, info, childLinks);
            }

            sb.AppendLine("        }");
        }

        private static void EmitCompositeMutation(
            StringBuilder sb,
            MappingClassInfo info,
            ImmutableArray<MappingClassInfo> allMappings,
            List<MappingClassInfo> models)
        {
            var ownedEntityNames = new HashSet<string>(
                info.Definition.Entities.Where(k => k.EntityType != null).Select(k => k.EntityType!.Name),
                System.StringComparer.Ordinal);

            var childModels = models
                .Where(m => !IsCompositeInfo(m) && !string.Equals(m.ModelType.Name, info.ModelType.Name, System.StringComparison.Ordinal) && m.EntityType != null && ownedEntityNames.Contains(m.EntityType.Name))
                .Select(m => m.ModelType.Name)
                .Distinct(System.StringComparer.Ordinal)
                .OrderBy(n => n, System.StringComparer.Ordinal)
                .ToList();

            var allPrimaryLinks = info.Definition.Entities.Where(k => k.IsPrimary && k.EntityType != null).ToList();

            if (allPrimaryLinks.Count > 1)
            {
                foreach (var link in allPrimaryLinks)
                {
                    var linkEntityName = link.EntityType!.Name;

                    var entityFields = ComputeFieldMappingsEagerPublic(info, composite: true)
                        .Where(f => string.Equals(f.EntityTypeName, linkEntityName, StringComparison.Ordinal))
                        .ToList();

                    var keyAlreadyMapped = entityFields.Any(f =>
                        string.Equals(f.ColumnName, link.ToColumn, StringComparison.OrdinalIgnoreCase));

                    if (!keyAlreadyMapped
                        && !string.IsNullOrWhiteSpace(link.FromColumn)
                        && !string.IsNullOrWhiteSpace(link.ToColumn))
                    {
                        entityFields.Add((link.FromColumn, linkEntityName, link.ToColumn));
                    }

                    if (entityFields.Count == 0)
                        continue;

                    var varName = ToCamel(linkEntityName) + "Values";

                    sb.AppendLine($"            var {varName} = ImmutableArray.CreateBuilder<FieldValue>(node.Values.Length);");
                    sb.AppendLine("            foreach (var v in node.Values)");
                    sb.AppendLine("            {");
                    sb.AppendLine("                switch (v.FieldId)");
                    sb.AppendLine("                {");

                    foreach (var fm in entityFields)
                    {
                        sb.AppendLine($"                    case FieldId.{info.ModelType.Name}.{fm.FieldName}:");
                        sb.AppendLine($"                        {varName}.Add(new FieldValue(");
                        sb.AppendLine($"                            ColumnId.{fm.EntityTypeName}.{fm.ColumnName},");
                        sb.AppendLine($"                            v.RawValue));");
                        sb.AppendLine("                        break;");
                    }

                    sb.AppendLine("                }");
                    sb.AppendLine("            }");
                    sb.AppendLine();

                    var linkModel = allMappings.FirstOrDefault(m =>
                        m.IsModel && string.Equals(m.EntityType?.Name, linkEntityName, StringComparison.Ordinal));

                    // Only emit a row for this entity if the caller actually supplied
                    // at least one of its fields (its own key counts).
                    sb.AppendLine($"            if ({varName}.Count > 0)");
                    sb.AppendLine("            {");
                    sb.AppendLine($"                builder.AddRow(");
                    sb.AppendLine($"                    EntityId.{linkModel?.ModelType.Name ?? linkEntityName},");
                    sb.AppendLine($"                    StorageEntityId.{linkEntityName},");
                    sb.AppendLine($"                    node.OutputAlias,");
                    sb.AppendLine($"                    {varName}.ToImmutable());");
                    sb.AppendLine("            }");
                    sb.AppendLine();
                }

                return;
            }

            // --- single-primary composite path (e.g. CustomerCustomerEdge) unchanged below ---

            if (childModels.Count > 0)
            {
                sb.AppendLine("            foreach (var child in node.Children)");
                sb.AppendLine("            {");
                sb.AppendLine("                switch (child.EntityId)");
                sb.AppendLine("                {");

                foreach (var childName in childModels)
                {
                    sb.AppendLine($"                    case EntityId.{childName}:");
                    sb.AppendLine($"                        {childName}Planner.BuildMutation(child, ref builder);");
                    sb.AppendLine("                        break;");
                }

                sb.AppendLine("                }");
                sb.AppendLine("            }");
                sb.AppendLine();
            }

            var primaryLink       = allPrimaryLinks.FirstOrDefault();
            var primaryEntityName = primaryLink?.EntityType?.Name
                                    ?? throw new InvalidOperationException($"Composite model {info.ModelType.Name} has no primary storage entity.");

            var primarySchema = allMappings
                .FirstOrDefault(m => m.EntityType != null && string.Equals(m.EntityType.Name, primaryEntityName, System.StringComparison.Ordinal))
                ?.Schema ?? info.Schema;

            var primaryFields = ComputeFieldMappingsEagerPublic(info, composite: true)
                .Where(f => string.Equals(f.EntityTypeName, primaryEntityName, System.StringComparison.Ordinal))
                .ToList();

            var primaryKeyAlreadyMapped = primaryFields.Any(f =>
                string.Equals(f.ColumnName, primaryLink.ToColumn, StringComparison.OrdinalIgnoreCase));

            if (!primaryKeyAlreadyMapped
                && !string.IsNullOrWhiteSpace(primaryLink.FromColumn)
                && !string.IsNullOrWhiteSpace(primaryLink.ToColumn))
            {
                primaryFields.Add((primaryLink.FromColumn, primaryEntityName, primaryLink.ToColumn));
            }

            var conflictKeys = info.UpsertKeys
                .Where(k => !string.IsNullOrWhiteSpace(k.Key))
                .Select(k => k.Key)
                .Distinct(System.StringComparer.OrdinalIgnoreCase)
                .ToList();

            if (conflictKeys.Count == 0)
                conflictKeys = info.Definition.Entities
                    .Where(k => k.IsPrimary && !string.IsNullOrWhiteSpace(k.ToColumn))
                    .Select(k => k.ToColumn!)
                    .Distinct(System.StringComparer.OrdinalIgnoreCase)
                    .ToList();

            var conflictLiteral = conflictKeys.Count == 0
                ? "ImmutableArray<string>.Empty"
                : "ImmutableArray.Create(" + string.Join(", ", conflictKeys.Select(k => $"\"{k}\"")) + ")";

            var cteEntries = info.CteUpdateMeta;

            sb.AppendLine("            var edgeValues = ImmutableArray.CreateBuilder<FieldValue>(node.Values.Length);");
            sb.AppendLine("            foreach (var v in node.Values)");
            sb.AppendLine("            {");
            sb.AppendLine("                switch (v.FieldId)");
            sb.AppendLine("                {");

            foreach (var fm in primaryFields)
            {
                sb.AppendLine($"                    case FieldId.{info.ModelType.Name}.{fm.FieldName}:");
                sb.AppendLine($"                        edgeValues.Add(new FieldValue(");
                sb.AppendLine($"                            ColumnId.{fm.EntityTypeName}.{fm.ColumnName},");
                sb.AppendLine($"                            v.RawValue));");
                sb.AppendLine("                        break;");
            }

            sb.AppendLine("                }");
            sb.AppendLine("            }");
            sb.AppendLine();

            if (conflictKeys.Count > 0)
            {
                sb.AppendLine("            // Ensure backend writer-required conflict key placeholders exist");

                foreach (var kc in conflictKeys)
                {
                    var matchingField = primaryFields
                        .FirstOrDefault(f => string.Equals(f.ColumnName, kc, StringComparison.OrdinalIgnoreCase));

                    if (string.IsNullOrEmpty(matchingField.ColumnName))
                    {
                        matchingField = ComputeFieldMappingsEagerPublic(info, composite: true)
                            .FirstOrDefault(f => string.Equals(f.ColumnName, kc, StringComparison.OrdinalIgnoreCase));
                    }

                    if (string.IsNullOrEmpty(matchingField.ColumnName)
                        && string.Equals(primaryLink.ToColumn, kc, System.StringComparison.OrdinalIgnoreCase))
                    {
                        matchingField = (primaryLink.FromColumn, primaryEntityName, primaryLink.ToColumn);
                    }

                    if (string.IsNullOrEmpty(matchingField.ColumnName))
                    {
                        throw new InvalidOperationException(
                            $"Cannot resolve conflict key '{kc}' for composite '{info.ModelType.Name}'.");
                    }

                    string columnRef = $"ColumnId.{matchingField.EntityTypeName}.{matchingField.ColumnName}";

                    sb.AppendLine(
                        $"            if (!edgeValues.Any(ev => ev.FieldId == {columnRef}))");
                    sb.AppendLine("            {");
                    sb.AppendLine($"                edgeValues.Add(new FieldValue({columnRef}, null!));");
                    sb.AppendLine("            }");
                }

                sb.AppendLine();
            }

            sb.AppendLine($"            var cteChildren = ImmutableArray.CreateBuilder<MutationCteNode>({cteEntries.Count});");

            if (cteEntries.Count > 0)
            {
                sb.AppendLine("            foreach (var child in node.Children)");
                sb.AppendLine("            {");

                foreach (var cte in cteEntries)
                {
                    sb.AppendLine($"                if (string.Equals(child.OutputAlias, \"{cte.NavigationAlias}\", System.StringComparison.OrdinalIgnoreCase))");
                    sb.AppendLine("                {");
                    sb.AppendLine("                    string? nk = null;");
                    sb.AppendLine("                    foreach (var cv in child.Values)");
                    sb.AppendLine($"                        if (cv.FieldId == FieldId.{cte.RelatedEntityTypeName}.{cte.RelatedNaturalKeyColumn})");
                    sb.AppendLine("                        { nk = cv.RawValue; break; }");
                    sb.AppendLine("                    if (nk != null)");
                    sb.AppendLine("                        cteChildren.Add(new MutationCteNode(");
                    sb.AppendLine($"                            EntityId.{cte.RelatedEntityTypeName},");
                    sb.AppendLine($"                            StorageEntityId.{cte.RelatedEntityTypeName},");
                    sb.AppendLine($"                            \"{cte.NavigationAlias}\",");
                    sb.AppendLine($"                            ImmutableArray.Create(new FieldValue(ColumnId.{cte.RelatedEntityTypeName}.{cte.RelatedNaturalKeyColumn}, nk)),");
                    sb.AppendLine("                            ImmutableArray<MutationCteNode>.Empty));");
                    sb.AppendLine("                }");
                }

                sb.AppendLine("            }");
                sb.AppendLine();
            }

            sb.AppendLine("            builder.AddCteRoot(new MutationCteNode(");
            sb.AppendLine($"                EntityId.{info.ModelType.Name},");
            sb.AppendLine($"                StorageEntityId.{primaryEntityName},");
            sb.AppendLine($"                node.OutputAlias,");
            sb.AppendLine($"                edgeValues.ToImmutable(),");
            sb.AppendLine($"                cteChildren.ToImmutable(),");
            sb.AppendLine($"                \"{primarySchema}\",");
            sb.AppendLine($"                \"{primaryEntityName}\",");
            sb.AppendLine($"                {conflictLiteral}));");
        }

        private static void EmitSimpleMutation(
            StringBuilder sb,
            MappingClassInfo info,
            List<ChildLink> childLinks)
        {
            var fieldMappings   = ComputeFieldMappingsEagerPublic(info, composite: false);
            var storageTypeName = info.EntityType?.Name ?? info.ModelType.Name;

            var primaryLink = info.Definition.Entities.FirstOrDefault(k => k.IsPrimary);
            var keyAlreadyMapped = primaryLink != null &&
                fieldMappings.Any(fm => string.Equals(fm.FieldName, primaryLink.FromColumn, System.StringComparison.Ordinal));

            var allValueMappings = fieldMappings.ToList();
            if (primaryLink != null && !keyAlreadyMapped
                && !string.IsNullOrWhiteSpace(primaryLink.FromColumn)
                && !string.IsNullOrWhiteSpace(primaryLink.ToColumn))
            {
                allValueMappings.Add((primaryLink.FromColumn, storageTypeName, primaryLink.ToColumn));
            }

            if (allValueMappings.Count > 0)
            {
                sb.AppendLine("            var values = ImmutableArray.CreateBuilder<FieldValue>(node.Values.Length);");
                sb.AppendLine();
                sb.AppendLine("            foreach (var v in node.Values)");
                sb.AppendLine("            {");
                sb.AppendLine("                switch (v.FieldId)");
                sb.AppendLine("                {");

                foreach (var fm in allValueMappings)
                {
                    sb.AppendLine($"                    case FieldId.{info.ModelType.Name}.{fm.FieldName}:");
                    sb.AppendLine($"                        values.Add(new FieldValue(");
                    sb.AppendLine($"                            ColumnId.{fm.EntityTypeName}.{fm.ColumnName},");
                    sb.AppendLine($"                            v.RawValue));");
                    sb.AppendLine("                        break;");
                }

                sb.AppendLine("                }");
                sb.AppendLine("            }");
                sb.AppendLine();
                sb.AppendLine($"            builder.AddRow(");
                sb.AppendLine($"                EntityId.{info.ModelType.Name},");
                sb.AppendLine($"                StorageEntityId.{storageTypeName},");
                sb.AppendLine($"                node.OutputAlias,");
                sb.AppendLine($"                values.ToImmutable());");
            }
            else
            {
                sb.AppendLine($"            builder.AddRow(");
                sb.AppendLine($"                EntityId.{info.ModelType.Name},");
                sb.AppendLine($"                StorageEntityId.{storageTypeName},");
                sb.AppendLine($"                node.OutputAlias,");
                sb.AppendLine($"                ImmutableArray<FieldValue>.Empty);");
            }

            if (childLinks.Count > 0)
            {
                sb.AppendLine();
                sb.AppendLine("            foreach (var child in node.Children)");
                sb.AppendLine("            {");
                sb.AppendLine("                switch (child.EntityId)");
                sb.AppendLine("                {");

                foreach (var group in childLinks.GroupBy(l => l.ChildModelName, System.StringComparer.Ordinal))
                {
                    sb.AppendLine($"                    case EntityId.{group.Key}:");
                    sb.AppendLine($"                        {group.Key}Planner.BuildMutation(child, ref builder);");
                    sb.AppendLine("                        break;");
                }

                sb.AppendLine("                }");
                sb.AppendLine("            }");
            }
        }

        private static void EmitRegistry(StringBuilder sb, List<MappingClassInfo> models)
        {
            sb.AppendLine("    /// <summary>");
            sb.AppendLine("    /// Single entry point for plan building.");
            sb.AppendLine("    /// </summary>");
            sb.AppendLine("    public static class PlannerRegistry");
            sb.AppendLine("    {");
            sb.AppendLine($"        public const ushort PlannerCount = {models.Count};");
            sb.AppendLine();

            sb.AppendLine("        public static void Build(ushort entityId, in SelectionIR selection, ref QueryPlanBuilder builder)");
            sb.AppendLine("        {");
            sb.AppendLine("            switch (entityId)");
            sb.AppendLine("            {");
            foreach (var m in models)
            {
                sb.AppendLine($"                case EntityId.{m.ModelType.Name}:");
                sb.AppendLine($"                    {m.ModelType.Name}Planner.Build(selection, ref builder);");
                sb.AppendLine("                    return;");
            }
            sb.AppendLine("                default: ThrowUnknownEntity(entityId); return;");
            sb.AppendLine("            }");
            sb.AppendLine("        }");
            sb.AppendLine();

            sb.AppendLine("        public static void BuildMutation(ushort entityId, in MutationIR mutation, ref MutationPlanBuilder builder)");
            sb.AppendLine("        {");
            sb.AppendLine("            switch (entityId)");
            sb.AppendLine("            {");
            foreach (var m in models)
            {
                sb.AppendLine($"                case EntityId.{m.ModelType.Name}:");
                sb.AppendLine($"                    {m.ModelType.Name}Planner.BuildMutation(mutation, ref builder);");
                sb.AppendLine("                    return;");
            }
            sb.AppendLine("                default: ThrowUnknownEntity(entityId); return;");
            sb.AppendLine("            }");
            sb.AppendLine("        }");
            sb.AppendLine();

            // --- new members, still inside PlannerRegistry, using its own PlannerCount/ThrowUnknownEntity ---
            sb.AppendLine("        public static bool IsValidEntity(ushort entityId) => entityId < PlannerCount;");
            sb.AppendLine();
            sb.AppendLine("        public static string GetEntityName(ushort entityId)");
            sb.AppendLine("        {");
            sb.AppendLine("            switch (entityId)");
            sb.AppendLine("            {");
            foreach (var m in models)
            {
                sb.AppendLine($"                case EntityId.{m.ModelType.Name}: return \"{m.ModelType.Name}\";");
            }
            sb.AppendLine("                default: ThrowUnknownEntity(entityId); return string.Empty;");
            sb.AppendLine("            }");
            sb.AppendLine("        }");
            sb.AppendLine();

            sb.AppendLine("        private static void ThrowUnknownEntity(ushort entityId) =>");
            sb.AppendLine("            throw new System.ArgumentException($\"Unknown entity runtime ID: {entityId}\");");
            sb.AppendLine("    }");
        }

