        private static void EmitRegistry(StringBuilder sb, List<MappingClassInfo> models)
        {
            sb.AppendLine("    /// <summary>");
            sb.AppendLine("    /// Single entry point for plan building.");
            sb.AppendLine("    /// </summary>");
            sb.AppendLine("    public static class PlannerRegistry");
            sb.AppendLine("    {");
            sb.AppendLine($"        public const ushort PlannerCount = {models.Count};");
            sb.AppendLine();

            sb.AppendLine(
                "        public static void Build(ushort entityId, in SelectionIR selection, ref QueryPlanBuilder builder)");
            sb.AppendLine("        {");
            sb.AppendLine("            switch (entityId)");
            sb.AppendLine("            {");
            foreach (var m in models)
            {
                sb.AppendLine($"                case EntityId.{m.ModelType.Name}:");
                sb.AppendLine($"                    {m.ModelType.Name}Planner.Build(selection, ref builder);");
                sb.AppendLine("                    return;");
            }

            sb.AppendLine("                default: ThrowUnknownEntity(entityId); return;");
            sb.AppendLine("            }");
            sb.AppendLine("        }");
            sb.AppendLine();

            sb.AppendLine(
                "        public static void BuildMutation(ushort entityId, in MutationIR mutation, ref MutationPlanBuilder builder)");
            sb.AppendLine("        {");
            sb.AppendLine("            switch (entityId)");
            sb.AppendLine("            {");
            foreach (var m in models)
            {
                sb.AppendLine($"                case EntityId.{m.ModelType.Name}:");
                sb.AppendLine($"                    {m.ModelType.Name}Planner.BuildMutation(mutation, ref builder);");
                sb.AppendLine("                    return;");
            }

            sb.AppendLine("                default: ThrowUnknownEntity(entityId); return;");
            sb.AppendLine("            }");
            sb.AppendLine("        }");
            sb.AppendLine();

            sb.AppendLine("        public static bool IsValidEntity(ushort entityId) => entityId < PlannerCount;");
            sb.AppendLine();
            sb.AppendLine("        public static string GetEntityName(ushort entityId)");
            sb.AppendLine("        {");
            sb.AppendLine("            switch (entityId)");
            sb.AppendLine("            {");
            foreach (var m in models)
            {
                sb.AppendLine($"                case EntityId.{m.ModelType.Name}: return \"{m.ModelType.Name}\";");
            }

            sb.AppendLine("                default: ThrowUnknownEntity(entityId); return string.Empty;");
            sb.AppendLine("            }");
            sb.AppendLine("        }");
            sb.AppendLine();

            sb.AppendLine("        private static void ThrowUnknownEntity(ushort entityId) =>");
            sb.AppendLine(
                "            throw new System.ArgumentException($\"Unknown entity runtime ID: {entityId}\");");
            sb.AppendLine("    }");
        }

        internal static List<(string FieldName, string EntityTypeName, string ColumnName, string? StorageAlias)>
            ComputeFieldMappingsEagerPublic(MappingClassInfo info, bool composite)
        {
            return ComputeFieldMappingsEager(info, composite);
        }

        private static List<(string FieldName, string EntityTypeName, string ColumnName, string? StorageAlias)> ComputeFieldMappingsEager(
            MappingClassInfo info, bool composite)
        {
            var list = new List<(string, string, string, string?)>();
            foreach (var f in info.FieldMaps)
            {
                if (f.IsGenerated) continue;

                var entityTypeName = string.IsNullOrWhiteSpace(f.DestinationEntity)
                    ? (info.EntityType?.Name ?? info.ModelType.Name)
                    : f.DestinationEntity;

                list.Add((f.SourceName, entityTypeName, f.DestinationName, f.DestinationAlias));
            }

            return list;
        }

        internal static string GetPkPropertyName(INamedTypeSymbol entity)
        {
            if (entity.GetMembers().OfType<IPropertySymbol>().Any(p => p.Name == "Id"))
                return "Id";
            var conventional = entity.Name + "Key";
            return entity.GetMembers().OfType<IPropertySymbol>().Any(p => p.Name == conventional)
                ? conventional
                : "Id";
        }

        internal static IEnumerable<ChildLink> ComputeChildLinks(
    MappingClassInfo info,
    ImmutableArray<MappingClassInfo> allMappings,
    NavigationResolutionResult? navResult,
    List<FluentEntityNavigationConvention.EntityForeignKeyGraph.Edge> entityGraph)
{
    var parentEntity =
        info.Definition.Entities.FirstOrDefault(k => k.IsPrimary)?.EntityType
        ?? info.EntityType;
    if (parentEntity == null)
        yield break;
    if (info.Graph != null &&
        !string.IsNullOrWhiteSpace(info.Graph.GraphName))
    {
        var relatedModel = allMappings.FirstOrDefault(m =>
            m.IsModel &&
            (
                string.Equals(
                    m.ModelType.Name,
                    info.Graph.GraphName,
                    StringComparison.Ordinal)
                ||
                string.Equals(
                    m.EntityType?.Name,
                    info.Graph.To?.Label,
                    StringComparison.Ordinal)
            ));
        if (relatedModel != null)
        {
            yield return new ChildLink
            {
                NavigationName = info.Graph.GraphName,
                ChildModelName = relatedModel.ModelType.Name,
                ChildEntityName =
                    relatedModel.EntityType?.Name
                    ?? info.Graph.To?.Label
                    ?? relatedModel.ModelType.Name,
                Hops =
                [
                    new ChildLinkHop
                    {
                        FromEntityName = parentEntity.Name,
                        FromColumn = info.Graph.FromJoinColumn,
                        ToEntityName =
                            relatedModel.EntityType?.Name
                            ?? info.Graph.To?.Label
                            ?? relatedModel.ModelType.Name,
                        ToColumn = info.Graph.ToJoinColumn
                    }
                ],
                IsCollection = true
            };
            yield break;
        }
    }
    foreach (var autoChild in info.AutoChildAttachments)
    {
        var childMapping = allMappings.FirstOrDefault(m =>
            m.IsModel &&
            SymbolEqualityComparer.Default.Equals(
                m.ModelType,
                autoChild.ChildEntityType));
        if (childMapping == null)
            continue;
        yield return new ChildLink
        {
            NavigationName = autoChild.FieldName,
            ChildModelName = childMapping.ModelType.Name,
            ChildEntityName = autoChild.ChildEntityType.Name,
            Hops =
            [
                new ChildLinkHop
                {
                    FromEntityName = autoChild.ParentEntityType.Name,
                    FromColumn = autoChild.ParentJoinColumn,
                    ToEntityName = autoChild.ChildEntityType.Name,
                    ToColumn = autoChild.ChildJoinColumn
                }
            ],
            IsCollection = true
        };
    }
    foreach (var child in info.ModelChildren)
    {
        var childMapping = allMappings.FirstOrDefault(m =>
            m.IsModel &&
            string.Equals(
                m.ModelType.Name,
                child.To,
                StringComparison.Ordinal));

        if (childMapping == null)
            continue;

        var childEntity =
            childMapping.EntityType ??
            childMapping.Definition.Entities
                .FirstOrDefault(e => e.IsPrimary)?
                .EntityType;

        if (childEntity == null)
            continue;

        var path =
            FluentEntityNavigationConvention.EntityGraphPathfinder.FindPath(
                entityGraph,
                parentEntity,
                childEntity);

        if (path == null || path.Count == 0)
        {
            // fallback for direct model attachment
            var parentStorage =
                info.Definition.Entities
                    .FirstOrDefault(e => e.IsPrimary)?
                    .EntityType;

            if (parentStorage != null &&
                SymbolEqualityComparer.Default.Equals(
                    parentStorage,
                    childEntity))
            {
                path =
                [
                    new FluentEntityNavigationConvention.EntityForeignKeyGraph.Edge
                    (
                        parentStorage, "Id", childEntity, "Id"
                    )
                ];
            }
        }

        if (path == null || path.Count == 0)
            continue;

        yield return new ChildLink
        {
            NavigationName = child.To,
            ChildModelName = childMapping.ModelType.Name,
            ChildEntityName = childEntity.Name,

            Hops = path.Select(e => new ChildLinkHop
            {
                FromEntityName = e.DependentEntity.Name,
                FromColumn = e.DependentColumn,
                ToEntityName = e.PrincipalEntity.Name,
                ToColumn = e.PrincipalColumn
            }).ToList(),

            IsCollection = true
        };
    }
    if (navResult == null)
        yield break;
    foreach (var nav in navResult.Navigations)
    {
        var relatedModel = allMappings.FirstOrDefault(m =>
            m.IsModel &&
            SymbolEqualityComparer.Default.Equals(
                m.ModelType,
                nav.TargetModel));
        if (relatedModel == null)
            continue;
        foreach (var path in nav.JoinPaths)
        {
            yield return new ChildLink
            {
                NavigationName = nav.NavigationName,
                ChildModelName = relatedModel.ModelType.Name,
                ChildEntityName = path.TargetEntity.Name,
                Hops = path.Hops.Select(e => new ChildLinkHop
                {
                    FromEntityName = e.DependentEntity.Name,
                    FromColumn = e.DependentColumn,
                    ToEntityName = e.PrincipalEntity.Name,
                    ToColumn = e.PrincipalColumn
                }).ToList(),
                IsCollection = nav.IsCollection
            };
        }
    }
}
