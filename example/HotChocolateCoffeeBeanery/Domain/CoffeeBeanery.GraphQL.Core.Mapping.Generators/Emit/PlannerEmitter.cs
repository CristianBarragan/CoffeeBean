        public static string Emit(
            ImmutableArray<MappingClassInfo> allMappings,
            ImmutableHashSet<INamedTypeSymbol> rootEntityTypes,
            List<FluentEntityNavigationConvention.EntityForeignKeyGraph.Edge> entityGraph)
        {
            var models = allMappings
                .Where(m => m.IsModel)
                .OrderBy(m => m.ModelType.Name, System.StringComparer.Ordinal)
                .ToList();

            var navResults = models.ToDictionary(
                m => m.ModelType.Name,
                m => EntityNavigationConvention.Resolve(m, allMappings, entityGraph, rootEntityTypes),
                System.StringComparer.Ordinal);

            var sb = new StringBuilder();
            sb.AppendLine("#nullable enable");
            sb.AppendLine("// <auto-generated/>");

            sb.AppendLine("using System.Collections.Immutable;");
            sb.AppendLine("using CoffeeBeanery.GraphQL.Core.Runtime;");
            sb.AppendLine();
            sb.AppendLine("namespace CoffeeBeanery.GraphQL.Core.Runtime");
            sb.AppendLine("{");

            foreach (var model in models)
            {
                var navResult = navResults.TryGetValue(model.ModelType.Name, out var r) ? r : null;
                EmitPlanner(sb, model, allMappings, models, navResult);
            }

            EmitRegistry(sb, models);

            sb.AppendLine("}");
            return sb.ToString();
        }

        internal static bool IsCompositeInfo(MappingClassInfo info)
        {
            if (info.IsComposite) return true;
            if (info.ModelToEntityList.Count > 1) return true;
            if (info.Definition?.Entities?.Count > 1) return true;

            if (info.ClassSymbol != null)
            {
                var fkAttributeCount = info.ModelType?
                    .GetAttributes()
                    .Count(a => a.AttributeClass?.Name == "EntityForeignKeyAttribute");

                if (fkAttributeCount > 1) return true;

                var definitionProp = info.ClassSymbol
                    .GetMembers("Definition")
                    .OfType<IPropertySymbol>()
                    .FirstOrDefault();

                if (definitionProp != null)
                {
                    var syntaxRefs = definitionProp.DeclaringSyntaxReferences;
                    foreach (var sr in syntaxRefs)
                    {
                        var text = sr.GetSyntax().ToFullString();
                        var count = 0;
                        var idx = 0;
                        while ((idx = text.IndexOf("Entity = typeof(", idx, StringComparison.Ordinal)) >= 0)
                        {
                            count++;
                            idx++;
                        }
                        if (count > 1) return true;
                    }
                }
            }

            string? firstName = null;
            foreach (var k in info.ModelToEntity)
            {
                var name = k.EntityType?.Name;
                if (name is null) continue;
                if (firstName is null) firstName = name;
                else if (!string.Equals(firstName, name, System.StringComparison.Ordinal)) return true;
            }
            return false;
        }

        private static string GetEntityPkProperty(INamedTypeSymbol? entity,
            ImmutableArray<MappingClassInfo> allMappings)
        {
            if (entity == null) return "Id";
            var mappedInfo = allMappings.FirstOrDefault(m =>
                m.Definition.PrimaryKey != null &&
                m.Definition.PrimaryKey.Any(pk => SymbolEqualityComparer.Default.Equals(pk.Entity, entity)));
            if (mappedInfo != null)
            {
                return mappedInfo.Definition.PrimaryKey
                    .First(pk => SymbolEqualityComparer.Default.Equals(pk.Entity, entity)).ColumnKey;
            }

            if (entity.GetMembers().OfType<IPropertySymbol>()
                .Any(p => string.Equals(p.Name, "Id", System.StringComparison.Ordinal))) return "Id";
            var conventionalKey = entity.Name + "Key";
            return entity.GetMembers().OfType<IPropertySymbol>().Any(p =>
                string.Equals(p.Name, conventionalKey, System.StringComparison.Ordinal))
                ? conventionalKey
                : "Id";
        }

        private static void EmitBuildQuery(
            StringBuilder sb,
            MappingClassInfo info,
            ImmutableArray<MappingClassInfo> allMappings,
            NavigationResolutionResult? navResult,
            bool composite)
        {


            sb.AppendLine("        public static void Build(in SelectionIR node, ref QueryPlanBuilder builder)");
            sb.AppendLine("        {");

            // Pre-calculate secondary links so they are accessible to the childLinks filter below
            var secondaryLinks = info.Definition.Entities
                .Where(k => !k.IsPrimary && k.EntityType != null && k.AliasProperty != null)
                .ToList();

            if (composite)
            {
                var primaryLink = info.Definition.Entities.FirstOrDefault(k => k.IsPrimary);
                var primaryEntityType = primaryLink?.EntityType
                                        ?? throw new InvalidOperationException(
                                            $"Composite model {info.ModelType.Name} has no primary storage entity.");

                var allFieldMappings = ComputeFieldMappingsEagerPublic(info, composite: true);

                var entitiesToEmit = info.Definition.Entities
                    .Where(k => k.EntityType != null)
                    .Select(k => k.EntityType!)
                    .Distinct(SymbolEqualityComparer.Default)
                    .Cast<INamedTypeSymbol>()
                    .ToList();

                if (entitiesToEmit.Count > 0)
                {
                    sb.AppendLine("            foreach (var scalar in node.Scalars)");
                    sb.AppendLine("            {");
                    sb.AppendLine("                switch (scalar.FieldId)");
                    sb.AppendLine("                {");

                    foreach (var entityType in entitiesToEmit)
                    {
                        var entityFields = allFieldMappings
                            .Where(f => string.Equals(f.EntityTypeName, entityType.Name, System.StringComparison.Ordinal))
                            .ToList();

                        if (entityFields.Count == 0) continue;

                        // Root entity reads off node.OutputAlias directly (same table as the
                        // CTE/FROM row). Non-root entities were joined under a per-entity
                        // alias suffix by EmitHopChain when this model is reached as a child
                        // (see ComputeChildLinks/EmitChildJoinDispatch); when queried at the
                        // root directly there is currently no equivalent join emitted here --
                        // see open question below.
                        var aliasExpr = string.Equals(entityType.Name, primaryEntityType.Name, System.StringComparison.Ordinal)
                            ? "node.OutputAlias"
                            : $"node.OutputAlias + \"_{entityType.Name}\"";

                        foreach (var fm in entityFields)
                        {
                            sb.AppendLine($"                    case FieldId.{info.ModelType.Name}.{fm.FieldName}:");
                            sb.AppendLine($"                        builder.AddRootColumn(");
                            sb.AppendLine($"                            EntityId.{info.ModelType.Name},");
                            sb.AppendLine($"                            StorageEntityId.{fm.EntityTypeName},");
                            sb.AppendLine($"                            ColumnId.{fm.EntityTypeName}.{fm.ColumnName},");
                            sb.AppendLine($"                            {aliasExpr}, scalar.OutputAlias);");
                            sb.AppendLine("                        break;");
                        }
                    }

                    sb.AppendLine("                }");
                    sb.AppendLine("            }");
                    sb.AppendLine();
                }

                // Single graph block — was duplicated before, now appears exactly once.
                if (info.Graph != null && !string.IsNullOrWhiteSpace(info.Graph.GraphName))
                {
                    var g = info.Graph;
                    sb.AppendLine("            builder.AddGraphJoin(");
                    sb.AppendLine($"                EntityId.{info.ModelType.Name},");
                    sb.AppendLine($"                StorageEntityId.{primaryEntityType.Name},");
                    sb.AppendLine($"                \"{g.GraphName}\",");
                    sb.AppendLine($"                \"{g.EdgeLabel}\",");
                    sb.AppendLine($"                \"{g.EdgeKey}\",");
                    sb.AppendLine($"                \"{g.From!.Label}\",");
                    sb.AppendLine($"                \"{g.From.KeyColumn}\",");
                    sb.AppendLine($"                \"{g.From.Alias}\",");
                    sb.AppendLine($"                \"{g.FromJoinColumn}\",");
                    sb.AppendLine($"                \"{g.To!.Label}\",");
                    sb.AppendLine($"                \"{g.To.KeyColumn}\",");
                    sb.AppendLine($"                \"{g.To.Alias}\",");
                    sb.AppendLine($"                \"{g.ToJoinColumn}\",");
                    sb.AppendLine($"                node.OutputAlias + \"_graph\");");

                    sb.AppendLine();

                    foreach (var vertexSpec in new[] { (Vertex: g.From!, IsFrom: true), (Vertex: g.To!, IsFrom: false) })
                    {
                        var (vertex, isFrom) = vertexSpec;
                        var relatedModel = allMappings.FirstOrDefault(m =>
                            m.IsModel && string.Equals(m.EntityType?.Name, vertex.Label, System.StringComparison.Ordinal));
                        if (relatedModel is null) continue;

                        var relatedPrimaryKey = allMappings.SelectMany(m => m.Definition.PrimaryKey)
                            .FirstOrDefault(pk => string.Equals(pk.Entity.Name, vertex.Label, System.StringComparison.Ordinal));
                        var relatedModelKeyField =
                            relatedPrimaryKey?.ModelKey;

                        if (string.IsNullOrWhiteSpace(relatedModelKeyField) ||
                            !relatedModel.ModelType
                                .GetMembers()
                                .OfType<IPropertySymbol>()
                                .Any(p => string.Equals(
                                    p.Name,
                                    relatedModelKeyField,
                                    StringComparison.Ordinal)))
                        {
                            relatedModelKeyField =
                                relatedModel.Definition.Entities
                                    .FirstOrDefault(e => e.IsPrimary)?
                                    .FromColumn;
                        }

                        if (string.IsNullOrWhiteSpace(relatedModelKeyField) ||
                            !relatedModel.ModelType
                                .GetMembers()
                                .OfType<IPropertySymbol>()
                                .Any(p => string.Equals(
                                    p.Name,
                                    relatedModelKeyField,
                                    StringComparison.Ordinal)))
                        {
                            relatedModelKeyField = "Id";
                        }

                        var alias = vertex.Alias ?? vertex.Label;

                        sb.AppendLine($"            foreach (var fkChild in node.Children)");
                        sb.AppendLine($"            {{");
                        sb.AppendLine($"                if (string.Equals(fkChild.OutputAlias, \"{alias}\", System.StringComparison.OrdinalIgnoreCase))");
                        sb.AppendLine($"                {{");
                        sb.AppendLine($"                    foreach (var subScalar in fkChild.Scalars)");
                        sb.AppendLine($"                    {{");
                        sb.AppendLine($"                        switch (subScalar.FieldId)");
                        sb.AppendLine($"                        {{");
                        sb.AppendLine($"                            case FieldId.{relatedModel.ModelType.Name}.{relatedModelKeyField}:");
                        sb.AppendLine($"                                builder.AddColumn(");
                        sb.AppendLine($"                                    EntityId.{relatedModel.ModelType.Name},");
                        sb.AppendLine($"                                    StorageEntityId.{vertex.Label},");
                        sb.AppendLine($"                                    ColumnId.{vertex.Label}.{(isFrom ? g.FromJoinColumn : g.ToJoinColumn)},");
                        sb.AppendLine($"                                    fkChild.OutputAlias, subScalar.OutputAlias);");
                        sb.AppendLine($"                                break;");
                        sb.AppendLine($"                        }}");
                        sb.AppendLine($"                    }}");

                        var childrenOnly = "childrenOnly_" + alias;
                        sb.AppendLine($"                    var {childrenOnly} = new SelectionIR(");
                        sb.AppendLine($"                        EntityId.{relatedModel.ModelType.Name},");
                        sb.AppendLine($"                        fkChild.OutputAlias,");
                        sb.AppendLine($"                        fkChild.IsConditional,");
                        sb.AppendLine($"                        ImmutableArray<ScalarSelection>.Empty,");
                        sb.AppendLine($"                        fkChild.Children);");
                        sb.AppendLine($"                    {relatedModel.ModelType.Name}Planner.Build({childrenOnly}, ref builder);");
                        sb.AppendLine($"                }}");
                        sb.AppendLine($"            }}");
                    }

                    sb.AppendLine("        }");
                    sb.AppendLine();
                    return;
                }

                if (secondaryLinks.Count > 0)
                {
                    sb.AppendLine("            foreach (var fkChild in node.Children)");
                    sb.AppendLine("            {");

                    foreach (var link in secondaryLinks)
                    {
                        var relatedEntityType = link.EntityType!;
                        var alias = link.AliasProperty!;
                        var fkColumn = alias + "Id";

                        var relatedModel = allMappings.FirstOrDefault(m =>
                            m.IsModel &&
                            string.Equals(m.EntityType?.Name, relatedEntityType.Name, System.StringComparison.Ordinal));
                        if (relatedModel is null) continue;

                        string relatedEntityPk = GetEntityPkProperty(relatedEntityType, allMappings);

                        sb.AppendLine(
                            $"                if (string.Equals(fkChild.OutputAlias, \"{alias}\", System.StringComparison.OrdinalIgnoreCase))");
                        sb.AppendLine("                {");
                        sb.AppendLine("                    builder.AddJoin(");
                        sb.AppendLine($"                        EntityId.{info.ModelType.Name},");
                        sb.AppendLine($"                        StorageEntityId.{primaryEntityType.Name},");
                        sb.AppendLine($"                        EntityId.{relatedModel.ModelType.Name},");
                        sb.AppendLine($"                        StorageEntityId.{relatedEntityType.Name},");
                        sb.AppendLine($"                        ColumnId.{primaryEntityType.Name}.{fkColumn},");
                        sb.AppendLine($"                        ColumnId.{relatedEntityType.Name}.{relatedEntityPk},");
                        sb.AppendLine("                        JoinKind.Left, fkChild.OutputAlias);");
                        sb.AppendLine();
                        sb.AppendLine("                    foreach (var subScalar in fkChild.Scalars)");
                        sb.AppendLine("                    {");
                        sb.AppendLine("                        switch (subScalar.FieldId)");
                        sb.AppendLine("                        {");

                        foreach (var prop in IdEmitter.GetScalarProperties(relatedEntityType))
                        {
                            var modelFieldName = relatedModel.FieldMaps
                                                     .FirstOrDefault(f =>
                                                         !f.IsGenerated && string.Equals(f.DestinationName, prop.Name,
                                                             System.StringComparison.OrdinalIgnoreCase))
                                                     ?.SourceName
                                                 ?? prop.Name;

                            bool fieldExistsOnModel = relatedModel.ModelType.GetMembers().OfType<IPropertySymbol>()
                                .Any(p => string.Equals(p.Name, modelFieldName, System.StringComparison.Ordinal));
                            if (!fieldExistsOnModel) continue;

                            sb.AppendLine(
                                $"                            case FieldId.{relatedModel.ModelType.Name}.{modelFieldName}:");
                            sb.AppendLine("                                builder.AddColumn(");
                            sb.AppendLine(
                                $"                                    EntityId.{relatedModel.ModelType.Name},");
                            sb.AppendLine(
                                $"                                    StorageEntityId.{relatedEntityType.Name},");
                            sb.AppendLine(
                                $"                                    ColumnId.{relatedEntityType.Name}.{prop.Name},");
                            sb.AppendLine(
                                "                                    fkChild.OutputAlias, subScalar.OutputAlias);");
                            sb.AppendLine("                                break;");
                        }

                        sb.AppendLine("                        }");
                        sb.AppendLine("                    }");
                        sb.AppendLine();
                        sb.AppendLine("                    var childrenOnly = new SelectionIR(");
                        sb.AppendLine($"                        EntityId.{relatedModel.ModelType.Name},");
                        sb.AppendLine("                        fkChild.OutputAlias,");
                        sb.AppendLine("                        fkChild.IsConditional,");
                        sb.AppendLine("                        ImmutableArray<ScalarSelection>.Empty,");
                        sb.AppendLine("                        fkChild.Children);");
                        sb.AppendLine(
                            $"                    {relatedModel.ModelType.Name}Planner.Build(childrenOnly, ref builder);");
                        sb.AppendLine("                }");
                    }

                    sb.AppendLine("            }");
                    sb.AppendLine();
                }

                var childLinks = ComputeChildLinks(info, allMappings, navResult)
                    .Where(l =>
                    {
                        var childInfo = allMappings.FirstOrDefault(m =>
                            string.Equals(m.ModelType.Name, l.ChildModelName, System.StringComparison.Ordinal));
                        if (childInfo == null || IsCompositeInfo(childInfo)) return false;

                        // Exclude links already handled by secondary links mapping loop
                        if (secondaryLinks.Any(sl => string.Equals(sl.AliasProperty, l.NavigationName,
                                System.StringComparison.OrdinalIgnoreCase)))
                        {
                            return false;
                        }

                        return true;
                    })
                    .ToList();

                EmitChildJoinDispatch(sb, info, childLinks);
            }
            else
            {
                var fieldMappings = ComputeFieldMappingsEagerPublic(info, composite: false);

                if (fieldMappings.Count > 0)
                {
                    sb.AppendLine("            foreach (var scalar in node.Scalars)");
                    sb.AppendLine("            {");
                    sb.AppendLine("                switch (scalar.FieldId)");
                    sb.AppendLine("                {");

                    foreach (var fm in fieldMappings)
                    {
                        sb.AppendLine($"                    case FieldId.{info.ModelType.Name}.{fm.FieldName}:");
                        sb.AppendLine($"                        builder.AddRootColumn(");
                        sb.AppendLine($"                            EntityId.{info.ModelType.Name},");
                        sb.AppendLine($"                            StorageEntityId.{fm.EntityTypeName},");
                        sb.AppendLine($"                            ColumnId.{fm.EntityTypeName}.{fm.ColumnName},");
                        sb.AppendLine($"                            node.OutputAlias, scalar.OutputAlias);");
                        sb.AppendLine("                        break;");
                    }

                    sb.AppendLine("                }");
                    sb.AppendLine("            }");
                    sb.AppendLine();
                }

                var childLinks = ComputeChildLinks(info, allMappings, navResult)
                    .Where(l =>
                    {
                        var childInfo = allMappings.FirstOrDefault(m =>
                            string.Equals(m.ModelType.Name, l.ChildModelName, System.StringComparison.Ordinal));
                        return childInfo != null && !IsCompositeInfo(childInfo);
                    })
                    .ToList();

                EmitChildJoinDispatch(sb, info, childLinks);
            }

            sb.AppendLine("        }");
            sb.AppendLine();
        }

        private static void EmitChildJoinDispatch(
            StringBuilder sb,
            MappingClassInfo info,
            List<ChildLink> childLinks)
        {
            if (childLinks.Count == 0) return;

            sb.AppendLine("            foreach (var child in node.Children)");
            sb.AppendLine("            {");
            sb.AppendLine("                switch (child.EntityId)");
            sb.AppendLine("                {");

            foreach (var group in childLinks.GroupBy(l => l.ChildModelName, StringComparer.Ordinal))
            {
                sb.AppendLine($"                    case EntityId.{group.Key}:");

                var links = group.ToList();
                var byNavName = links.GroupBy(l => l.NavigationName, StringComparer.Ordinal).ToList();

                if (byNavName.Count > 1)
                {
                    // Disambiguation case: same child model reached via differently-named
                    // navigations (e.g. InnerCustomer / OuterCustomer both -> Customer).
                    // Exactly one path expected per nav name here.
                    for (var i = 0; i < byNavName.Count; i++)
                    {
                        var navGroup = byNavName[i];
                        var l = navGroup.Single();
                        var kw = i == 0 ? "if" : "else if";
                        sb.AppendLine($"                        {kw} (child.OutputAlias == \"{l.NavigationName}\")");
                        sb.AppendLine("                        {");
                        EmitHopChain(sb, info, l, "child.OutputAlias", indent: "                            ");
                        sb.AppendLine("                        }");
                    }
                }
                else
                {
                    var navLinks = byNavName[0].ToList();

                    if (navLinks.Count == 1)
                    {
                        // Simple single-path child.
                        EmitHopChain(sb, info, navLinks[0], "child.OutputAlias", indent: "                        ");
                    }
                    else
                    {
                        // Composite case: one navigation, multiple backing-entity paths
                        // (e.g. Product via CustomerBankingRelationship/Contract/Account/Transaction).
                        // All chains are emitted unconditionally under distinct join aliases;
                        // ProductPlanner.Build must read whichever alias is populated per row.
                        foreach (var l in navLinks)
                        {
                            var joinAlias = $"child.OutputAlias + \"_{l.ChildEntityName}\"";
                            EmitHopChain(sb, info, l, joinAlias, indent: "                        ");
                        }
                    }
                }

                sb.AppendLine($"                        {group.Key}Planner.Build(child, ref builder);");
                sb.AppendLine("                        break;");
            }

            sb.AppendLine("                }");
            sb.AppendLine("            }");
        }

        private static void EmitHopChain(
            StringBuilder sb,
            MappingClassInfo info,
            ChildLink link,
            string finalAliasExpr,
            string indent)
        {
            for (var i = 0; i < link.Hops.Count; i++)
            {
                var hop = link.Hops[i];
                var isLast = i == link.Hops.Count - 1;
                // Intermediate hops need their own pass-through alias; only the last
                // hop's join target is exposed under the GraphQL-visible alias.
                var aliasExpr = isLast ? finalAliasExpr : $"child.OutputAlias + \"_hop{i}\"";
                var parentEntityIdExpr = i == 0 ? $"EntityId.{info.ModelType.Name}" : $"EntityId.{hop.FromEntityName}";

                sb.AppendLine($"{indent}builder.AddJoin(");
                sb.AppendLine($"{indent}    {parentEntityIdExpr},");
                sb.AppendLine($"{indent}    StorageEntityId.{hop.FromEntityName},");
                sb.AppendLine($"{indent}    EntityId.{(isLast ? link.ChildModelName : hop.ToEntityName)},");
                sb.AppendLine($"{indent}    StorageEntityId.{hop.ToEntityName},");
                sb.AppendLine($"{indent}    ColumnId.{hop.FromEntityName}.{hop.FromColumn},");
                sb.AppendLine($"{indent}    ColumnId.{hop.ToEntityName}.{hop.ToColumn},");
                sb.AppendLine($"{indent}    JoinKind.Left, {aliasExpr});");
            }
        }

        private static void EmitPlanner(
            StringBuilder sb,
            MappingClassInfo info,
            ImmutableArray<MappingClassInfo> allMappings,
            List<MappingClassInfo> models,
            NavigationResolutionResult? navResult)
        {
            sb.AppendLine($"    public static class {info.ModelType.Name}Planner");
            sb.AppendLine("    {");

            var composite = IsCompositeInfo(info);

            EmitBuildQuery(sb, info, allMappings, navResult, composite);
            EmitBuildMutation(sb, info, allMappings, models, navResult, composite);

            sb.AppendLine("    }");
            sb.AppendLine();
        }

        private static string ToCamel(string name) =>
            string.IsNullOrEmpty(name) ? name : char.ToLowerInvariant(name[0]) + name.Substring(1);

        private static void EmitBuildMutation(
            StringBuilder sb,
            MappingClassInfo info,
            ImmutableArray<MappingClassInfo> allMappings,
            List<MappingClassInfo> models,
            NavigationResolutionResult? navResult,
            bool composite)
        {
            sb.AppendLine("        public static void BuildMutation(in MutationIR node, ref MutationPlanBuilder builder)");
            sb.AppendLine("        {");

            if (composite)
            {
                EmitCompositeMutation(
                    sb,
                    info,
                    allMappings,
                    models);
            }
            else
            {
                var allChildLinks = ComputeChildLinks(
                        info,
                        allMappings,
                        navResult)
                    .ToList();

                var simpleChildLinks = allChildLinks
                    .Where(l =>
                    {
                        var childInfo = allMappings.FirstOrDefault(m =>
                            string.Equals(
                                m.ModelType.Name,
                                l.ChildModelName,
                                StringComparison.Ordinal));

                        return childInfo != null &&
                               !IsCompositeInfo(childInfo);
                    })
                    .ToList();

                var compositeChildLinks = allChildLinks
                    .Where(l =>
                    {
                        var childInfo = allMappings.FirstOrDefault(m =>
                            string.Equals(
                                m.ModelType.Name,
                                l.ChildModelName,
                                StringComparison.Ordinal));

                        return childInfo != null &&
                               IsCompositeInfo(childInfo);
                    })
                    .ToList();

                EmitSimpleMutation(
                    sb,
                    info,
                    simpleChildLinks,
                    compositeChildLinks,
                    allMappings,
                    models);
            }

            sb.AppendLine("        }");
        }

        private static void EmitCompositeMutation(
            StringBuilder sb,
            MappingClassInfo info,
            ImmutableArray<MappingClassInfo> allMappings,
            List<MappingClassInfo> models)
        {
            var ownedEntityNames = new HashSet<string>(
                info.Definition.Entities
                    .Where(k => k.EntityType != null)
                    .Select(k => k.EntityType!.Name),
                StringComparer.Ordinal);

            var childModels = models
                .Where(m =>
                    !IsCompositeInfo(m) &&
                    !string.Equals(
                        m.ModelType.Name,
                        info.ModelType.Name,
                        StringComparison.Ordinal) &&
                    ownedEntityNames.Contains(m.EntityType?.Name ?? m.ModelType.Name))
                .Select(m => m.ModelType.Name)
                .Distinct(StringComparer.Ordinal)
                .OrderBy(n => n, StringComparer.Ordinal)
                .ToList();

            var storageLinks = info.Definition.Entities
                .Where(k => k.EntityType != null)
                .ToList();

            var allPrimaryLinks = storageLinks
                .Where(k => k.IsPrimary)
                .ToList();

            var relationshipLinks = storageLinks
                .Where(k =>
                    !k.IsPrimary &&
                    k.EntityType != null &&
                    !string.IsNullOrWhiteSpace(k.ToColumn))
                .ToList();

            sb.AppendLine(
                "            var pendingRows = new Dictionary<(ushort EntityId, ushort StorageEntityId, string Alias), ImmutableArray<FieldValue>.Builder>();");

            sb.AppendLine(
                "            void AddOrMergeRow(ushort entityId, ushort storageEntityId, string alias, FieldValue field)");

            sb.AppendLine(
                "            {");

            sb.AppendLine(
                "                var key = (entityId, storageEntityId, alias);");

            sb.AppendLine(
                "                if (!pendingRows.TryGetValue(key, out var values))");

            sb.AppendLine(
                "                {");

            sb.AppendLine(
                "                    values = ImmutableArray.CreateBuilder<FieldValue>();");

            sb.AppendLine(
                "                    pendingRows[key] = values;");

            sb.AppendLine(
                "                }");

            sb.AppendLine(
                "                if (!values.Any(x => x.FieldId == field.FieldId))");

            sb.AppendLine(
                "                    values.Add(field);");

            sb.AppendLine(
                "            }");

            if (allPrimaryLinks.Count > 1)
            {
                foreach (var link in allPrimaryLinks)
                {
                    var entityName = link.EntityType!.Name;

                    var entityFields =
                        ComputeFieldMappingsEagerPublic(
                            info,
                            composite: true)
                        .Where(f =>
                            string.Equals(
                                f.EntityTypeName,
                                entityName,
                                StringComparison.Ordinal))
                        .ToList();

                    if (!entityFields.Any(f =>
                            string.Equals(
                                f.ColumnName,
                                link.ToColumn,
                                StringComparison.OrdinalIgnoreCase)) &&
                        !string.IsNullOrWhiteSpace(link.FromColumn) &&
                        !string.IsNullOrWhiteSpace(link.ToColumn))
                    {
                        entityFields.Add(
                            (
                                link.FromColumn,
                                entityName,
                                link.ToColumn
                            ));
                    }

                    if (entityFields.Count == 0)
                        continue;

                    var valuesName = ToCamel(entityName) + "Values";

                    sb.AppendLine(
                        $"            var {valuesName} = ImmutableArray.CreateBuilder<FieldValue>(node.Values.Length);");

                    sb.AppendLine(
                        "            foreach (var v in node.Values)");

                    sb.AppendLine(
                        "            {");

                    sb.AppendLine(
                        "                switch (v.FieldId)");

                    sb.AppendLine(
                        "                {");

                    foreach (var fm in entityFields)
                    {
                        sb.AppendLine(
                            $"                    case FieldId.{info.ModelType.Name}.{fm.FieldName}:");

                        sb.AppendLine(
                            $"                        {valuesName}.Add(new FieldValue(");

                        sb.AppendLine(
                            $"                            FieldId.{info.ModelType.Name}.{fm.FieldName},");

                        sb.AppendLine(
                            $"                            ColumnId.{fm.EntityTypeName}.{fm.ColumnName},");

                        sb.AppendLine(
                            "                            v.RawValue));");

                        sb.AppendLine(
                            "                        break;");
                    }

                    sb.AppendLine(
                        "                }");

                    sb.AppendLine(
                        "            }");

                    var mappedModel = allMappings.FirstOrDefault(m =>
                        m.IsModel &&
                        string.Equals(
                            m.EntityType?.Name,
                            entityName,
                            StringComparison.Ordinal));

                    sb.AppendLine(
                        $"            if ({valuesName}.Count > 0)");

                    sb.AppendLine(
                        "            {");

                    sb.AppendLine(
                        "                builder.AddRow(");

                    sb.AppendLine(
                        $"                    EntityId.{mappedModel?.ModelType.Name ?? entityName},");

                    sb.AppendLine(
                        $"                    StorageEntityId.{entityName},");

                    sb.AppendLine(
                        "                    node.OutputAlias,");

                    sb.AppendLine(
                        $"                    {valuesName}.ToImmutable());");

                    sb.AppendLine(
                        "            }");
                }

                if (info.CteUpdateMeta.Count == 0)
                    return;
            }

            if (childModels.Count > 0)
            {
                sb.AppendLine(
                    "            foreach (var child in node.Children)");

                sb.AppendLine(
                    "            {");

                sb.AppendLine(
                    "                switch (child.EntityId)");

                sb.AppendLine(
                    "                {");

                foreach (var childName in childModels)
                {
                    sb.AppendLine(
                        $"                    case EntityId.{childName}:");

                    sb.AppendLine(
                        $"                        {childName}Planner.BuildMutation(child, ref builder);");

                    sb.AppendLine(
                        "                        break;");
                }

                sb.AppendLine(
                    "                }");

                sb.AppendLine(
                    "            }");
            }

            var primaryLink = allPrimaryLinks.FirstOrDefault();

            var primaryEntityName =
                primaryLink?.EntityType?.Name
                ?? throw new InvalidOperationException(
                    $"Composite model '{info.ModelType.Name}' has no primary storage entity.");

            var primarySchema =
                allMappings.FirstOrDefault(m =>
                        m.EntityType != null &&
                        string.Equals(
                            m.EntityType.Name,
                            primaryEntityName,
                            StringComparison.Ordinal))
                    ?.Schema
                ?? info.Schema;

            var edgeMappings = ComputeFieldMappingsEagerPublic(
                    info,
                    composite: true)
                .Where(f =>
                    string.Equals(
                        f.EntityTypeName,
                        primaryEntityName,
                        StringComparison.Ordinal))
                .GroupBy(f => new
                {
                    f.EntityTypeName,
                    f.ColumnName
                })
                .Select(g => g.First())
                .ToList();

            if (primaryLink != null &&
                !string.IsNullOrWhiteSpace(primaryLink.ToColumn))
            {
                var exists = edgeMappings.Any(f =>
                    string.Equals(
                        f.EntityTypeName,
                        primaryEntityName,
                        StringComparison.OrdinalIgnoreCase) &&
                    string.Equals(
                        f.ColumnName,
                        primaryLink.ToColumn,
                        StringComparison.OrdinalIgnoreCase));

                if (!exists)
                {
                    edgeMappings.Add(
                        (
                            primaryLink.FromColumn,
                            primaryEntityName,
                            primaryLink.ToColumn
                        ));
                }
            }

            edgeMappings = edgeMappings
                .GroupBy(f => new
                {
                    f.EntityTypeName,
                    f.ColumnName
                })
                .Select(g => g.First())
                .ToList();

            var conflictKeys = new List<string>();

            var isRelationshipEntity =
                relationshipLinks.Count > 0 &&
                info.ModelType.Name.IndexOf(
                    "Relationship",
                    StringComparison.OrdinalIgnoreCase) >= 0;

            if (isRelationshipEntity)
            {
                conflictKeys = relationshipLinks
                    .Where(x => !string.IsNullOrWhiteSpace(x.ToColumn))
                    .Select(x => x.ToColumn!)
                    .Distinct(StringComparer.OrdinalIgnoreCase)
                    .ToList();
            }

            if (conflictKeys.Count == 0)
            {
                conflictKeys = info.UpsertKeys
                    .Where(k => !string.IsNullOrWhiteSpace(k.Key))
                    .Select(k => k.Key)
                    .Distinct(StringComparer.OrdinalIgnoreCase)
                    .ToList();
            }

            if (conflictKeys.Count == 0)
            {
                conflictKeys = info.Definition.Entities
                    .Where(k =>
                        k.IsPrimary &&
                        !string.IsNullOrWhiteSpace(k.ToColumn))
                    .Select(k => k.ToColumn!)
                    .Distinct(StringComparer.OrdinalIgnoreCase)
                    .ToList();
            }

            var conflictLiteral =
                conflictKeys.Count == 0
                    ? "ImmutableArray<string>.Empty"
                    : "ImmutableArray.Create(" +
                      string.Join(
                          ", ",
                          conflictKeys.Select(k => $"\"{k}\"")) +
                      ")";

            var fkLinks = info.Definition.Entities
                .Where(k =>
                    !k.IsPrimary &&
                    k.EntityType != null &&
                    !string.IsNullOrWhiteSpace(k.AliasProperty))
                .ToList();

            foreach (var link in fkLinks)
            {
                sb.AppendLine(
                    "            foreach (var v in node.Values)");

                sb.AppendLine(
                    "            {");

                sb.AppendLine(
                    $"                if (v.FieldId == FieldId.{info.ModelType.Name}.{link.FromColumn})");

                sb.AppendLine(
                    "                {");

                sb.AppendLine(
                    "                    if (!string.IsNullOrWhiteSpace(v.RawValue))");

                sb.AppendLine(
                    "                    {");

                sb.AppendLine(
                    "                        AddOrMergeRow(");

                sb.AppendLine(
                    $"                            EntityId.{link.EntityType!.Name},");

                sb.AppendLine(
                    $"                            StorageEntityId.{link.EntityType.Name},");

                sb.AppendLine(
                    $"                            \"{link.AliasProperty}\",");

                sb.AppendLine(
                    "                            new FieldValue(");

                sb.AppendLine(
                    $"                                ColumnId.{link.EntityType.Name}.{link.ToColumn},");

                sb.AppendLine(
                    "                                v.RawValue));");

                sb.AppendLine(
                    "                    }");

                sb.AppendLine(
                    "                    break;");

                sb.AppendLine(
                    "                }");

                sb.AppendLine(
                    "            }");
            }

            sb.AppendLine(
                "            foreach (var child in node.Children)");

            sb.AppendLine(
                "            {");

            sb.AppendLine(
                "                switch (child.EntityId)");

            sb.AppendLine(
                "                {");

            foreach (var childName in childModels)
            {
                sb.AppendLine(
                    $"                    case EntityId.{childName}:");

                sb.AppendLine(
                    "                    {");

                sb.AppendLine(
                    "                        foreach (var childValue in child.Values)");

                sb.AppendLine(
                    "                        {");

                sb.AppendLine(
                    "                            AddOrMergeRow(");

                sb.AppendLine(
                    $"                                EntityId.{childName},");

                sb.AppendLine(
                    $"                                StorageEntityId.{childName},");

                sb.AppendLine(
                    "                                child.OutputAlias,");

                sb.AppendLine(
                    "                                childValue);");

                sb.AppendLine(
                    "                        }");

                sb.AppendLine(
                    "                        break;");

                sb.AppendLine(
                    "                    }");
            }

            sb.AppendLine(
                "                }");

            sb.AppendLine(
                "            }");

            sb.AppendLine();

            sb.AppendLine(
                "            foreach (var row in pendingRows)");

            sb.AppendLine(
                "            {");

            sb.AppendLine(
                "                builder.AddRow(");

            sb.AppendLine(
                "                    row.Key.EntityId,");

            sb.AppendLine(
                "                    row.Key.StorageEntityId,");

            sb.AppendLine(
                "                    row.Key.Alias,");

            sb.AppendLine(
                "                    row.Value.ToImmutable());");

            sb.AppendLine(
                "            }");

            var cteEntries = info.CteUpdateMeta;

            sb.AppendLine(
                $"            var cteChildren = ImmutableArray.CreateBuilder<MutationCteNode>({cteEntries.Count});");

            string? resolvedGraphFromAlias = null;
            string? resolvedGraphToAlias = null;

            if (info.Graph != null &&
                !string.IsNullOrWhiteSpace(info.Graph.GraphName))
            {
                // FIX: fkLinks/AliasProperty is the alias actually used at runtime
                // (child.OutputAlias in MutationIR). info.Graph.From/To.Alias is
                // frequently a concatenated query-side display string (e.g.
                // "InnerCustomerCustomer") that never matches a real child alias --
                // it must only be a fallback when no fkLinks entry exists, not the
                // primary source. Previously this was reversed, which silently
                // prevented graphFromKey/graphToKey from ever being set, and the
                // Cypher MERGE was never emitted.
                resolvedGraphFromAlias =
                    fkLinks.FirstOrDefault(l =>
                            string.Equals(
                                l.FromColumn,
                                info.Graph.From?.KeyColumn,
                                StringComparison.OrdinalIgnoreCase))
                        ?.AliasProperty
                    ?? info.Graph.From?.Alias;

                resolvedGraphToAlias =
                    fkLinks.FirstOrDefault(l =>
                            string.Equals(
                                l.FromColumn,
                                info.Graph.To?.KeyColumn,
                                StringComparison.OrdinalIgnoreCase))
                        ?.AliasProperty
                    ?? info.Graph.To?.Alias;

                sb.AppendLine(
                    "            string? graphFromKey = null, graphToKey = null, graphEdgeKey = null;");

                sb.AppendLine();

                sb.AppendLine(
                    "            foreach (var child in node.Children)");

                sb.AppendLine(
                    "            {");

                sb.AppendLine(
                    "                string? naturalKey = null;");

                sb.AppendLine(
                    "                foreach (var cv in child.Values)");

                sb.AppendLine(
                    "                {");

                sb.AppendLine(
                    "                    if (cv.FieldId == FieldId.Customer.CustomerKey)");

                sb.AppendLine(
                    "                    {");

                sb.AppendLine(
                    "                        naturalKey = cv.RawValue;");

                sb.AppendLine(
                    "                        break;");

                sb.AppendLine(
                    "                    }");

                sb.AppendLine(
                    "                }");

                sb.AppendLine();

                sb.AppendLine(
                    "                if (naturalKey != null)");

                sb.AppendLine(
                    "                {");

                sb.AppendLine(
                    $"                    if (string.Equals(child.OutputAlias, \"{resolvedGraphFromAlias}\", StringComparison.OrdinalIgnoreCase))");

                sb.AppendLine(
                    "                        graphFromKey = naturalKey;");

                sb.AppendLine();

                sb.AppendLine(
                    $"                    if (string.Equals(child.OutputAlias, \"{resolvedGraphToAlias}\", StringComparison.OrdinalIgnoreCase))");

                sb.AppendLine(
                    "                        graphToKey = naturalKey;");

                sb.AppendLine(
                    "                }");

                sb.AppendLine(
                    "            }");
            }

            if (cteEntries.Count > 0)
            {
                sb.AppendLine(
                    "            foreach (var child in node.Children)");

                sb.AppendLine(
                    "            {");

                foreach (var cte in cteEntries)
                {
                    sb.AppendLine(
                        $"                if (string.Equals(child.OutputAlias, \"{cte.NavigationAlias}\", System.StringComparison.OrdinalIgnoreCase))");

                    sb.AppendLine(
                        "                {");

                    sb.AppendLine(
                        "                    string? naturalKey = null;");

                    sb.AppendLine(
                        "                    foreach (var cv in child.Values)");

                    sb.AppendLine(
                        "                    {");

                    var relatedModel = allMappings.FirstOrDefault(m =>
                        m.IsModel &&
                        string.Equals(
                            m.EntityType?.Name,
                            cte.RelatedEntityTypeName,
                            StringComparison.Ordinal));

                    if (relatedModel == null)
                        continue;

                    var childKey = relatedModel.Definition.Entities
                                       .FirstOrDefault(e => e.IsPrimary)?.FromColumn
                                   ?? cte.RelatedNaturalKeyColumn;

                    sb.AppendLine(
                        $"if (cv.FieldId == FieldId.{cte.RelatedEntityTypeName}.{childKey})");

                    sb.AppendLine(
                        "                        {");

                    sb.AppendLine(
                        "                            naturalKey = cv.RawValue;");

                    sb.AppendLine(
                        "                            break;");

                    sb.AppendLine(
                        "                        }");

                    sb.AppendLine(
                        "                    }");

                    sb.AppendLine(
                        "                    if (!string.IsNullOrWhiteSpace(naturalKey))");

                    sb.AppendLine(
                        "                    {");

                    sb.AppendLine(
                        "                        cteChildren.Add(new MutationCteNode(");

                    sb.AppendLine(
                        $"                            EntityId.{cte.RelatedEntityTypeName},");

                    sb.AppendLine(
                        $"                            StorageEntityId.{cte.RelatedEntityTypeName},");

                    sb.AppendLine(
                        $"                            \"{cte.NavigationAlias}\",");

                    sb.AppendLine(
                        $"                            ImmutableArray.Create(new FieldValue(ColumnId.{cte.RelatedEntityTypeName}.{childKey}, naturalKey)),");

                    sb.AppendLine(
                        "                            ImmutableArray<MutationCteNode>.Empty));");

                    if (info.Graph != null &&
                        string.Equals(
                            cte.NavigationAlias,
                            resolvedGraphFromAlias,
                            StringComparison.OrdinalIgnoreCase))
                    {
                        sb.AppendLine(
                            "                        graphFromKey = naturalKey;");
                    }

                    if (info.Graph != null &&
                        string.Equals(
                            cte.NavigationAlias,
                            resolvedGraphToAlias,
                            StringComparison.OrdinalIgnoreCase))
                    {
                        sb.AppendLine(
                            "                        graphToKey = naturalKey;");
                    }

                    sb.AppendLine(
                        "                    }");

                    sb.AppendLine(
                        "                }");
                }

                sb.AppendLine(
                    "            }");
            }

            sb.AppendLine(
                "            var edgeValues = ImmutableArray.CreateBuilder<FieldValue>(node.Values.Length);");

            sb.AppendLine(
                "            foreach (var v in node.Values)");

            sb.AppendLine(
                "            {");

            sb.AppendLine(
                "                switch (v.FieldId)");

            sb.AppendLine(
                "                {");

            foreach (var fm in edgeMappings)
            {
                sb.AppendLine(
                    $"                    case FieldId.{info.ModelType.Name}.{fm.FieldName}:");

                sb.AppendLine(
                    "                        edgeValues.Add(new FieldValue(");

                sb.AppendLine(
                    $"                            FieldId.{info.ModelType.Name}.{fm.FieldName},");

                sb.AppendLine(
                    $"                            ColumnId.{fm.EntityTypeName}.{fm.ColumnName},");

                sb.AppendLine(
                    "                            v.RawValue));");

                if (info.Graph != null &&
                    string.Equals(
                        fm.FieldName,
                        info.Graph.EdgeKey,
                        StringComparison.Ordinal))
                {
                    sb.AppendLine(
                        "                        graphEdgeKey = v.RawValue;");
                }

                sb.AppendLine(
                    "                        break;");
            }

            sb.AppendLine(
                "                }");

            sb.AppendLine(
                "            }");

            if (info.Graph != null &&
                !string.IsNullOrWhiteSpace(info.Graph.GraphName))
            {
                var g = info.Graph;

                sb.AppendLine(
                    "            if (graphFromKey != null && graphToKey != null)");

                sb.AppendLine(
                    "            {");

                sb.AppendLine(
                    "                builder.AddGraphMerge(");

                sb.AppendLine(
                    $"                    \"{g.GraphName}\",");

                sb.AppendLine(
                    $"                    \"{g.EdgeLabel}\",");

                sb.AppendLine(
                    $"                    \"{g.From!.Label}\",");

                sb.AppendLine(
                    $"                    \"{g.FromJoinColumn}\",");

                sb.AppendLine(
                    "                    graphFromKey,");

                sb.AppendLine(
                    $"                    \"{g.To!.Label}\",");

                sb.AppendLine(
                    $"                    \"{g.ToJoinColumn}\",");

                sb.AppendLine(
                    "                    graphToKey,");

                sb.AppendLine(
                    $"                    \"{g.EdgeKey}\",");

                sb.AppendLine(
                    "                    graphEdgeKey,");

                sb.AppendLine(
                    "                    ImmutableDictionary<string, string>.Empty);");

                sb.AppendLine(
                    "            }");
            }

            sb.AppendLine(
                "            builder.AddCteRoot(new MutationCteNode(");

            sb.AppendLine(
                $"                EntityId.{info.ModelType.Name},");

            sb.AppendLine(
                $"                StorageEntityId.{primaryEntityName},");

            sb.AppendLine(
                "                node.OutputAlias,");

            sb.AppendLine(
                "                edgeValues.ToImmutable(),");

            sb.AppendLine(
                "                cteChildren.ToImmutable(),");

            sb.AppendLine(
                $"                \"{primarySchema}\",");

            sb.AppendLine(
                $"                \"{primaryEntityName}\",");

            sb.AppendLine(
                $"                {conflictLiteral}));");
        }



