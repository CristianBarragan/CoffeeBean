        // Emits AddJoin calls for a hop chain that stays entirely internal
        // to a single composite model's own backing entities (as opposed to
        // EmitHopChain below, which targets a genuinely separate child
        // model). The final hop's target alias matches the convention
        // already used by the entitiesToEmit scalar-column block:
        // node.OutputAlias + "_{finalEntityName}".
        // ---------------------------------------------------------------
        private static void EmitInternalHopChain(
            StringBuilder sb,
            MappingClassInfo info,
            List<FluentEntityNavigationConvention.EntityForeignKeyGraph.Edge> hops,
            string finalEntityName)
        {
            for (var i = 0; i < hops.Count; i++)
            {
                var edge = hops[i];
                var isLast = i == hops.Count - 1;

                // FindPath returns edges oriented FK(dependent) -> PK(principal);
                // walking direction here always proceeds primary -> target, and
                // FindPath already resolves the correct traversal order, so we
                // read From/To directly off which side matches the previous hop.
                var fromEntity = edge.DependentEntity;
                var fromColumn = edge.DependentColumn;
                var toEntity = edge.PrincipalEntity;
                var toColumn = edge.PrincipalColumn;

                var toAliasExpr = isLast
                    ? $"node.OutputAlias + \"_{finalEntityName}\""
                    : $"node.OutputAlias + \"_hop{i}\"";

                sb.AppendLine("            builder.AddJoin(");
                sb.AppendLine($"                EntityId.{info.ModelType.Name},");
                sb.AppendLine($"                StorageEntityId.{fromEntity.Name},");
                sb.AppendLine($"                EntityId.{info.ModelType.Name},");
                sb.AppendLine($"                StorageEntityId.{toEntity.Name},");
                sb.AppendLine($"                ColumnId.{fromEntity.Name}.{fromColumn},");
                sb.AppendLine($"                ColumnId.{toEntity.Name}.{toColumn},");
                sb.AppendLine($"                JoinKind.Left, {toAliasExpr});");
            }
        }

        private static void EmitChildJoinDispatch(
    StringBuilder sb,
    MappingClassInfo info,
    List<ChildLink> childLinks)
{
    if (childLinks.Count == 0)
        return;
    sb.AppendLine("            foreach (var child in node.Children)");
    sb.AppendLine("            {");
    sb.AppendLine("                switch (child.EntityId)");
    sb.AppendLine("                {");
    foreach (var group in childLinks.GroupBy(
        l => l.ChildModelName,
        StringComparer.Ordinal))
    {
        sb.AppendLine($"                    case EntityId.{group.Key}:");
        var links = group.ToList();
        var byNavigation = links
            .GroupBy(
                l => l.NavigationName,
                StringComparer.Ordinal)
            .ToList();
        if (byNavigation.Count > 1)
        {
            for (var i = 0; i < byNavigation.Count; i++)
            {
                var nav = byNavigation[i].First();
                var condition = i == 0 ? "if" : "else if";
                sb.AppendLine($"                        {condition} (string.Equals(child.OutputAlias, \"{nav.NavigationName}\", StringComparison.OrdinalIgnoreCase))");
                sb.AppendLine("                        {");
                EmitHopChain(
                    sb,
                    info,
                    nav,
                    "child.OutputAlias",
                    "                            ");
                sb.AppendLine("                        }");
            }
        }
        else
        {
            var navLinks = byNavigation[0].ToList();
            if (navLinks.Count == 1)
            {
                EmitHopChain(
                    sb,
                    info,
                    navLinks[0],
                    "child.OutputAlias",
                    "                        ");
            }
            else
            {
                foreach (var link in navLinks)
                {
                    EmitHopChain(
                        sb,
                        info,
                        link,
                        $"child.OutputAlias + \"_{link.ChildEntityName}\"",
                        "                        ");
                }
            }
        }
        sb.AppendLine($"                        {group.Key}Planner.Build(child, ref builder);");
        sb.AppendLine("                        break;");
    }
    sb.AppendLine("                }");
    sb.AppendLine("            }");
}

        private static void EmitHopChain(
    StringBuilder sb,
    MappingClassInfo info,
    ChildLink link,
    string finalAliasExpr,
    string indent)
{
    for (var i = 0; i < link.Hops.Count; i++)
    {
        var hop = link.Hops[i];
        var isLast = i == link.Hops.Count - 1;
        var aliasExpr = isLast
            ? finalAliasExpr
            : $"child.OutputAlias + \"_hop{i}\"";
        var fromEntityId =
            i == 0
                ? $"EntityId.{info.ModelType.Name}"
                : $"EntityId.{hop.FromEntityName}";
        var fromColumn =
            ResolveGeneratedColumnName(
                info,
                hop.FromEntityName,
                hop.FromColumn);
        var toColumn =
            ResolveGeneratedColumnName(
                info,
                hop.ToEntityName,
                hop.ToColumn);
        var targetEntity =
            isLast
                ? link.ChildModelName
                : info.ModelType.Name;
        sb.AppendLine($"{indent}builder.AddJoin(");
        sb.AppendLine($"{indent}    {fromEntityId},");
        sb.AppendLine($"{indent}    StorageEntityId.{hop.FromEntityName},");
        sb.AppendLine($"{indent}    EntityId.{targetEntity},");
        sb.AppendLine($"{indent}    StorageEntityId.{hop.ToEntityName},");
        sb.AppendLine($"{indent}    ColumnId.{hop.FromEntityName}.{fromColumn},");
        sb.AppendLine($"{indent}    ColumnId.{hop.ToEntityName}.{toColumn},");
        sb.AppendLine($"{indent}    JoinKind.Left, {aliasExpr});");
    }
}
private static string ResolveGeneratedColumnName(
    MappingClassInfo info,
    string entityName,
    string columnName)
{
    if (string.IsNullOrWhiteSpace(columnName))
        return columnName;
    var entity = info.Definition.Entities
        .FirstOrDefault(e =>
            e.EntityType != null &&
            string.Equals(
                e.EntityType.Name,
                entityName,
                StringComparison.Ordinal));
    if (entity?.EntityType == null)
        return columnName;
    var exists = entity.EntityType
        .GetMembers()
        .OfType<IPropertySymbol>()
        .Any(p =>
            string.Equals(
                p.Name,
                columnName,
                StringComparison.Ordinal));
    if (exists)
        return columnName;
    var mapped = info.Definition.Entities
        .Where(e =>
            e.EntityType != null &&
            string.Equals(
                e.EntityType.Name,
                entityName,
                StringComparison.Ordinal))
        .SelectMany(e =>
            e.EntityType!
                .GetMembers()
                .OfType<IPropertySymbol>())
        .FirstOrDefault(p =>
            p.Name.EndsWith(
                "Key",
                StringComparison.Ordinal));
    return mapped?.Name ?? columnName;
}

        private static void EmitPlanner(
            StringBuilder sb,
            MappingClassInfo info,
            ImmutableArray<MappingClassInfo> allMappings,
            List<MappingClassInfo> models,
            NavigationResolutionResult? navResult,
            List<FluentEntityNavigationConvention.EntityForeignKeyGraph.Edge> entityGraph)
        {
            sb.AppendLine($"    public static class {info.ModelType.Name}Planner");
            sb.AppendLine("    {");

            var composite = IsCompositeInfo(info);

            EmitBuildQuery(sb, info, allMappings, navResult, composite, entityGraph);
            EmitBuildMutation(sb, info, allMappings, models, navResult, composite, entityGraph);

            sb.AppendLine("    }");
            sb.AppendLine();
        }

        private static string ToCamel(string name) =>
            string.IsNullOrEmpty(name) ? name : char.ToLowerInvariant(name[0]) + name.Substring(1);

        private static void EmitBuildMutation(
            StringBuilder sb,
            MappingClassInfo info,
            ImmutableArray<MappingClassInfo> allMappings,
            List<MappingClassInfo> models,
            NavigationResolutionResult? navResult,
            bool composite,
            List<FluentEntityNavigationConvention.EntityForeignKeyGraph.Edge> entityGraph)
        {
            sb.AppendLine("        public static void BuildMutation(in MutationIR node, ref MutationPlanBuilder builder)");
            sb.AppendLine("        {");

            var childModels = info.ModelType
                .GetMembers()
                .OfType<IPropertySymbol>()
                .Select(p => FieldMapGeneration.UnwrapNullable(FieldMapGeneration.UnwrapCollection(p.Type)) as INamedTypeSymbol)
                .Where(t => t != null)
                .Where(t => !FieldMapGeneration.IsScalar(t))
                .Where(t => !SymbolEqualityComparer.Default.Equals(t, info.ModelType))
                .Select(t => allMappings.FirstOrDefault(m =>
                    SymbolEqualityComparer.Default.Equals(m.ModelType, t)))
                .Where(m => m != null)
                .GroupBy(m => m!.ModelType, SymbolEqualityComparer.Default)
                .Select(g => g.First()!)
                .ToList();
            
            if (childModels.Count > 0)
            {
                sb.AppendLine("foreach (var child in node.Children)");
                sb.AppendLine("{");
                sb.AppendLine("    switch (child.EntityId)");
                sb.AppendLine("    {");

                foreach (var child in childModels)
                {
                    sb.AppendLine($"        case EntityId.{child.ModelType.Name}:");
                    sb.AppendLine($"            {child.ModelType.Name}Planner.BuildMutation(child, ref builder);");
                    sb.AppendLine("            break;");
                }

                sb.AppendLine("    }");
                sb.AppendLine("}");
            }
            
            if (composite)
            {
                EmitCompositeMutation(
                    sb,
                    info,
                    allMappings,
                    models,
                    navResult,
                    entityGraph);
            }
            else
            {
                var allChildLinks = ComputeChildLinks(
                        info,
                        allMappings,
                        navResult,
                        entityGraph)
                    .ToList();
            
                var simpleChildLinks = allChildLinks
                    .Where(l =>
                    {
                        var childInfo = allMappings.FirstOrDefault(m =>
                            string.Equals(
                                m.ModelType.Name,
                                l.ChildModelName,
                                StringComparison.Ordinal));
            
                        return childInfo != null &&
                               !IsCompositeInfo(childInfo);
                    })
                    .ToList();
            
                var compositeChildLinks = allChildLinks
                    .Where(l =>
                    {
                        var childInfo = allMappings.FirstOrDefault(m =>
                            string.Equals(
                                m.ModelType.Name,
                                l.ChildModelName,
                                StringComparison.Ordinal));
            
                        return childInfo != null &&
                               IsCompositeInfo(childInfo);
                    })
                    .ToList();
            
                EmitSimpleMutation(
                    sb,
                    info,
                    simpleChildLinks,
                    compositeChildLinks,
                    allMappings,
                    models);
            }

            sb.AppendLine("        }");
        }

        private static void EmitCompositeMutation(
    StringBuilder sb,
    MappingClassInfo info,
    ImmutableArray<MappingClassInfo> allMappings,
    List<MappingClassInfo> models,
    NavigationResolutionResult? navResult,
    List<FluentEntityNavigationConvention.EntityForeignKeyGraph.Edge> entityGraph)
{
    var childModels = ComputeChildLinks(info, allMappings, navResult, entityGraph)
        .GroupBy(l => l.ChildModelName, StringComparer.Ordinal)
        .Select(g => (ModelName: g.Key, EntityName: g.First().ChildEntityName))
        .OrderBy(t => t.ModelName, StringComparer.Ordinal)
        .ToList();

    var storageLinks = info.Definition.Entities
        .Where(k => k.EntityType != null)
        .ToList();

    var allPrimaryLinks = storageLinks
        .Where(k => k.IsPrimary)
        .ToList();

    var relationshipLinks = storageLinks
        .Where(k =>
            !k.IsPrimary &&
            k.EntityType != null &&
            !string.IsNullOrWhiteSpace(k.ToColumn))
        .ToList();

    sb.AppendLine(
        "            var pendingRows = new Dictionary<(ushort EntityId, ushort StorageEntityId, string Alias), ImmutableArray<FieldValue>.Builder>();");

    sb.AppendLine(
        "            void AddOrMergeRow(ushort entityId, ushort storageEntityId, string alias, FieldValue field)");

    sb.AppendLine(
        "            {");

    sb.AppendLine(
        "                var key = (entityId, storageEntityId, alias);");

    sb.AppendLine(
        "                if (!pendingRows.TryGetValue(key, out var values))");

    sb.AppendLine(
        "                {");

    sb.AppendLine(
        "                    values = ImmutableArray.CreateBuilder<FieldValue>();");

    sb.AppendLine(
        "                    pendingRows[key] = values;");

    sb.AppendLine(
        "                }");

    sb.AppendLine(
        "                if (!values.Any(x => x.FieldId == field.FieldId))");

    sb.AppendLine(
        "                    values.Add(field);");

    sb.AppendLine(
        "            }");

    if (allPrimaryLinks.Count > 1)
    {
        foreach (var link in allPrimaryLinks)
        {
            var entityName = link.EntityType!.Name;

            var entityFields =
                ComputeFieldMappingsEagerPublic(
                    info,
                    composite: true)
                .Where(f =>
                    string.Equals(
                        f.EntityTypeName,
                        entityName,
                        StringComparison.Ordinal))
                .ToList();

            if (!entityFields.Any(f =>
                    string.Equals(
                        f.ColumnName,
                        link.ToColumn,
                        StringComparison.OrdinalIgnoreCase)) &&
                !string.IsNullOrWhiteSpace(link.FromColumn) &&
                !string.IsNullOrWhiteSpace(link.ToColumn))
            {
                entityFields.Add(
                    (
                        link.FromColumn,
                        entityName,
                        link.ToColumn,
                        (string?)null
                    ));
            }

            if (entityFields.Count == 0)
                continue;

            var valuesName = ToCamel(entityName) + "Values";

            sb.AppendLine(
                $"            var {valuesName} = ImmutableArray.CreateBuilder<FieldValue>(node.Values.Length);");

            sb.AppendLine(
                "            foreach (var v in node.Values)");

            sb.AppendLine(
                "            {");

            sb.AppendLine(
                "                switch (v.FieldId)");

            sb.AppendLine(
                "                {");

            foreach (var fm in entityFields)
            {
                sb.AppendLine(
                    $"                    case FieldId.{info.ModelType.Name}.{fm.FieldName}:");

                sb.AppendLine(
                    $"                        {valuesName}.Add(new FieldValue(");

                sb.AppendLine(
                    $"                            FieldId.{info.ModelType.Name}.{fm.FieldName},");

                sb.AppendLine(
                    $"                            ColumnId.{fm.EntityTypeName}.{fm.ColumnName},");

                sb.AppendLine(
                    "                            v.RawValue));");

                sb.AppendLine(
                    "                        break;");
            }

            sb.AppendLine(
                "                }");

            sb.AppendLine(
                "            }");

            var mappedModel = allMappings.FirstOrDefault(m =>
                m.IsModel &&
                string.Equals(
                    m.EntityType?.Name,
                    entityName,
                    StringComparison.Ordinal));

            sb.AppendLine(
                $"            if ({valuesName}.Count > 0)");

            sb.AppendLine(
                "            {");

            sb.AppendLine(
                "                builder.AddRow(");

            sb.AppendLine(
                $"                    EntityId.{mappedModel?.ModelType.Name ?? entityName},");

            sb.AppendLine(
                $"                    StorageEntityId.{entityName},");

            sb.AppendLine(
                "                    node.OutputAlias,");

            sb.AppendLine(
                $"                    {valuesName}.ToImmutable());");

            sb.AppendLine(
                "            }");
        }

        if (info.CteUpdateMeta.Count == 0)
            return;
    }

    if (childModels.Count > 0)
    {
        sb.AppendLine(
            "            foreach (var child in node.Children)");

        sb.AppendLine(
            "            {");

        sb.AppendLine(
            "                switch (child.EntityId)");

        sb.AppendLine(
            "                {");

        foreach (var (childName, childEntityName) in childModels)
        {
            sb.AppendLine(
                $"                    case EntityId.{childName}:");

            sb.AppendLine(
                "                    {");

            sb.AppendLine(
                "                        foreach (var childValue in child.Values)");

            sb.AppendLine(
                "                        {");

            sb.AppendLine(
                "                            AddOrMergeRow(");

            sb.AppendLine(
                $"                                EntityId.{childName},");

            sb.AppendLine(
                $"                                StorageEntityId.{childEntityName},");   // <-- was {childName}

            sb.AppendLine(
                "                                child.OutputAlias,");

            sb.AppendLine(
                "                                childValue);");

            sb.AppendLine(
                "                        }");

            sb.AppendLine(
                "                        break;");

            sb.AppendLine(
                "                    }");
        }

        sb.AppendLine(
            "                }");

        sb.AppendLine(
            "            }");
    }

    var primaryLink = allPrimaryLinks.FirstOrDefault();

    var primaryEntityName =
        primaryLink?.EntityType?.Name
        ?? throw new InvalidOperationException(
            $"Composite model '{info.ModelType.Name}' has no primary storage entity.");

    var primarySchema =
        allMappings.FirstOrDefault(m =>
                m.EntityType != null &&
                string.Equals(
                    m.EntityType.Name,
                    primaryEntityName,
                    StringComparison.Ordinal))
            ?.Schema
        ?? info.Schema;

    var edgeMappings = ComputeFieldMappingsEagerPublic(
            info,
            composite: true)
        .Where(f =>
            string.Equals(
                f.EntityTypeName,
                primaryEntityName,
                StringComparison.Ordinal))
        .GroupBy(f => new
        {
            f.EntityTypeName,
            f.ColumnName
        })
        .Select(g => g.First())
        .ToList();

    if (primaryLink != null &&
        !string.IsNullOrWhiteSpace(primaryLink.ToColumn))
    {
        var exists = edgeMappings.Any(f =>
            string.Equals(
                f.EntityTypeName,
                primaryEntityName,
                StringComparison.OrdinalIgnoreCase) &&
            string.Equals(
                f.ColumnName,
                primaryLink.ToColumn,
                StringComparison.OrdinalIgnoreCase));

        if (!exists)
        {
            edgeMappings.Add(
                (
                    primaryLink.FromColumn,
                    primaryEntityName,
                    primaryLink.ToColumn,
                    (string?)null
                ));
        }
    }

    edgeMappings = edgeMappings
        .GroupBy(f => new
        {
            f.EntityTypeName,
            f.ColumnName
        })
        .Select(g => g.First())
        .ToList();

    var conflictKeys = new List<string>();

    var isRelationshipEntity =
        relationshipLinks.Count > 0 &&
        info.ModelType.Name.IndexOf(
            "Relationship",
            StringComparison.OrdinalIgnoreCase) >= 0;

    if (isRelationshipEntity)
    {
        conflictKeys = relationshipLinks
            .Where(x => !string.IsNullOrWhiteSpace(x.ToColumn))
            .Select(x => x.ToColumn!)
            .Distinct(StringComparer.OrdinalIgnoreCase)
            .ToList();
    }

    if (conflictKeys.Count == 0)
    {
        conflictKeys = info.UpsertKeys
            .Where(k => !string.IsNullOrWhiteSpace(k.Key))
            .Select(k => k.Key)
            .Distinct(StringComparer.OrdinalIgnoreCase)
            .ToList();
    }

    if (conflictKeys.Count == 0)
    {
        conflictKeys = info.Definition.Entities
            .Where(k =>
                k.IsPrimary &&
                !string.IsNullOrWhiteSpace(k.ToColumn))
            .Select(k => k.ToColumn!)
            .Distinct(StringComparer.OrdinalIgnoreCase)
            .ToList();
    }

    var conflictLiteral =
        conflictKeys.Count == 0
            ? "ImmutableArray<string>.Empty"
            : "ImmutableArray.Create(" +
              string.Join(
                  ", ",
                  conflictKeys.Select(k => $"\"{k}\"")) +
              ")";

    var fkLinks = info.Definition.Entities
        .Where(k =>
            !k.IsPrimary &&
            k.EntityType != null &&
            !string.IsNullOrWhiteSpace(k.AliasProperty))
        .ToList();

    foreach (var link in fkLinks)
    {
        sb.AppendLine(
            "            foreach (var v in node.Values)");

        sb.AppendLine(
            "            {");

        sb.AppendLine(
            $"                if (v.FieldId == FieldId.{info.ModelType.Name}.{link.FromColumn})");

        sb.AppendLine(
            "                {");

        sb.AppendLine(
            "                    if (!string.IsNullOrWhiteSpace(v.RawValue))");

        sb.AppendLine(
            "                    {");

        sb.AppendLine(
            "                        AddOrMergeRow(");

        sb.AppendLine(
            $"                            EntityId.{link.EntityType!.Name},");

        sb.AppendLine(
            $"                            StorageEntityId.{link.EntityType.Name},");

        sb.AppendLine(
            $"                            \"{link.AliasProperty}\",");

        sb.AppendLine(
            "                            new FieldValue(");

        sb.AppendLine(
            $"                                ColumnId.{link.EntityType.Name}.{link.ToColumn},");

        sb.AppendLine(
            "                                v.RawValue));");

        sb.AppendLine(
            "                    }");

        sb.AppendLine(
            "                    break;");

        sb.AppendLine(
            "                }");

        sb.AppendLine(
            "            }");
    }

    sb.AppendLine(
        "            foreach (var child in node.Children)");

    sb.AppendLine(
        "            {");

    sb.AppendLine(
        "                switch (child.EntityId)");

    sb.AppendLine(
        "                {");

    foreach (var (childName, childEntityName) in childModels)
    {
        sb.AppendLine(
            $"                    case EntityId.{childName}:");

        sb.AppendLine(
            "                    {");

        sb.AppendLine(
            "                        foreach (var childValue in child.Values)");

        sb.AppendLine(
            "                        {");

        sb.AppendLine(
            "                            AddOrMergeRow(");

        sb.AppendLine(
            $"                                EntityId.{childName},");

        sb.AppendLine(
            $"                                StorageEntityId.{childEntityName},");

        sb.AppendLine(
            "                                child.OutputAlias,");

        sb.AppendLine(
            "                                childValue);");

        sb.AppendLine(
            "                        }");

        sb.AppendLine(
            "                        break;");

        sb.AppendLine(
            "                    }");
    }

    sb.AppendLine(
        "                }");

    sb.AppendLine(
        "            }");

    sb.AppendLine();

    sb.AppendLine(
        "            foreach (var row in pendingRows)");

    sb.AppendLine(
        "            {");

    sb.AppendLine(
        "                builder.AddRow(");

    sb.AppendLine(
        "                    row.Key.EntityId,");

    sb.AppendLine(
        "                    row.Key.StorageEntityId,");

    sb.AppendLine(
        "                    row.Key.Alias,");

    sb.AppendLine(
        "                    row.Value.ToImmutable());");

    sb.AppendLine(
        "            }");

    var cteEntries = info.CteUpdateMeta;

    sb.AppendLine(
        $"            var cteChildren = ImmutableArray.CreateBuilder<MutationCteNode>({cteEntries.Count});");

    string? resolvedGraphFromAlias = null;
    string? resolvedGraphToAlias = null;

    if (info.Graph != null &&
        !string.IsNullOrWhiteSpace(info.Graph.GraphName))
    {
        resolvedGraphFromAlias =
            fkLinks.FirstOrDefault(l =>
                    string.Equals(
                        l.FromColumn,
                        info.Graph.From?.KeyColumn,
                        StringComparison.OrdinalIgnoreCase))
                ?.AliasProperty
            ?? info.Graph.From?.Alias;

        resolvedGraphToAlias =
            fkLinks.FirstOrDefault(l =>
                    string.Equals(
                        l.FromColumn,
                        info.Graph.To?.KeyColumn,
                        StringComparison.OrdinalIgnoreCase))
                ?.AliasProperty
            ?? info.Graph.To?.Alias;

        sb.AppendLine(
            "            string? graphFromKey = null, graphToKey = null, graphEdgeKey = null;");

        sb.AppendLine();

        sb.AppendLine(
            "            foreach (var child in node.Children)");

        sb.AppendLine(
            "            {");

        sb.AppendLine(
            "                string? naturalKey = null;");

        sb.AppendLine(
            "                foreach (var cv in child.Values)");

        sb.AppendLine(
            "                {");

        sb.AppendLine(
            "                    if (cv.FieldId == FieldId.Customer.CustomerKey)");

        sb.AppendLine(
            "                    {");

        sb.AppendLine(
            "                        naturalKey = cv.RawValue;");

        sb.AppendLine(
            "                        break;");

        sb.AppendLine(
            "                    }");

        sb.AppendLine(
            "                }");

        sb.AppendLine();

        sb.AppendLine(
            "                if (naturalKey != null)");

        sb.AppendLine(
            "                {");

        sb.AppendLine(
            $"                    if (string.Equals(child.OutputAlias, \"{resolvedGraphFromAlias}\", StringComparison.OrdinalIgnoreCase))");

        sb.AppendLine(
            "                        graphFromKey = naturalKey;");

        sb.AppendLine();

        sb.AppendLine(
            $"                    if (string.Equals(child.OutputAlias, \"{resolvedGraphToAlias}\", StringComparison.OrdinalIgnoreCase))");

        sb.AppendLine(
            "                        graphToKey = naturalKey;");

        sb.AppendLine(
            "                }");

        sb.AppendLine(
            "            }");
    }

    if (cteEntries.Count > 0)
    {
        sb.AppendLine(
            "            foreach (var child in node.Children)");

        sb.AppendLine(
            "            {");

        foreach (var cte in cteEntries)
        {
            sb.AppendLine(
                $"                if (string.Equals(child.OutputAlias, \"{cte.NavigationAlias}\", System.StringComparison.OrdinalIgnoreCase))");

            sb.AppendLine(
                "                {");

            sb.AppendLine(
                "                    string? naturalKey = null;");

            sb.AppendLine(
                "                    foreach (var cv in child.Values)");

            sb.AppendLine(
                "                    {");

            var relatedModel = allMappings.FirstOrDefault(m =>
                m.IsModel &&
                string.Equals(
                    m.EntityType?.Name,
                    cte.RelatedEntityTypeName,
                    StringComparison.Ordinal));

            if (relatedModel == null)
                continue;

            var childKey = relatedModel.Definition.Entities
                               .FirstOrDefault(e => e.IsPrimary)?.FromColumn
                           ?? cte.RelatedNaturalKeyColumn;

            sb.AppendLine(
                $"if (cv.FieldId == FieldId.{cte.RelatedEntityTypeName}.{childKey})");

            sb.AppendLine(
                "                        {");

