        internal static string GetPkPropertyName(INamedTypeSymbol entity)
        {
            if (entity.GetMembers().OfType<IPropertySymbol>().Any(p => p.Name == "Id"))
                return "Id";
            var conventional = entity.Name + "Key";
            return entity.GetMembers().OfType<IPropertySymbol>().Any(p => p.Name == conventional)
                ? conventional : "Id";
        }
        
        internal static IEnumerable<ChildLink> ComputeChildLinks(
            MappingClassInfo info,
            ImmutableArray<MappingClassInfo> allMappings,
            NavigationResolutionResult? navResult)
        {
            if (navResult == null) yield break;

            var parentEntity = info.Definition.Entities.FirstOrDefault(k => k.IsPrimary)?.EntityType
                                ?? info.EntityType;
            if (parentEntity == null) yield break;

            string GetPk(INamedTypeSymbol? entity)
            {
                if (entity == null) return "Id";
                var mapped = allMappings.FirstOrDefault(m =>
                    m.Definition.PrimaryKey != null &&
                    m.Definition.PrimaryKey.Any(pk => SymbolEqualityComparer.Default.Equals(pk.Entity, entity)));
                if (mapped != null)
                    return mapped.Definition.PrimaryKey.First(pk => SymbolEqualityComparer.Default.Equals(pk.Entity, entity)).ColumnKey;
                if (entity.GetMembers().OfType<IPropertySymbol>().Any(p => p.Name == "Id"))
                    return "Id";
                var conventional = entity.Name + "Key";
                return entity.GetMembers().OfType<IPropertySymbol>().Any(p => p.Name == conventional)
                    ? conventional : "Id";
            }

            foreach (var nav in navResult.Navigations)
            {
                if (nav.RelatedEntityType == null) continue;

                var relatedModel = allMappings.FirstOrDefault(m =>
                    m.IsModel && string.Equals(m.EntityType?.Name, nav.RelatedEntityType.Name, StringComparison.Ordinal));
                if (relatedModel == null) continue;

                string parentJoinColumn, childJoinColumn;

                if (nav.FkOwnedByDeclaringEntity)
                {
                    // declaring entity (parent) holds the FK pointing at the related (child) entity's PK
                    parentJoinColumn = nav.ForeignKeyProperty;
                    childJoinColumn  = GetPk(nav.RelatedEntityType);
                }
                else
                {
                    // related entity (child) holds the FK pointing back at the declaring (parent) entity's PK
                    parentJoinColumn = GetPk(parentEntity);
                    childJoinColumn  = nav.ForeignKeyProperty;
                }

                yield return new ChildLink
                {
                    NavigationName   = nav.NavigationName,
                    ChildModelName   = relatedModel.ModelType.Name,
                    ParentEntityName = parentEntity.Name,
                    ChildEntityName  = nav.RelatedEntityType.Name,
                    ParentJoinColumn = parentJoinColumn,
                    ChildJoinColumn  = childJoinColumn,
                    IsCollection     = nav.IsCollection
                };
            }
        }
