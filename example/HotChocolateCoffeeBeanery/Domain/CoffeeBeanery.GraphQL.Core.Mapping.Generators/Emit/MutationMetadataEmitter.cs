using System;
using System.Collections.Generic;
using System.Collections.Immutable;
using System.Linq;
using System.Text;
using Microsoft.CodeAnalysis;
using CoffeeBeanery.GraphQL.Core.Mapping.Generators.Model;

namespace CoffeeBeanery.GraphQL.Core.Mapping.Generators.Emit;

internal static class MutationMetadataEmitter
{
    public static string Emit(ImmutableArray<MappingClassInfo> allMappings)
    {
        var models =
            allMappings
                .Where(x => x.ModelType != null)
                .OrderBy(x => x.ModelType!.Name)
                .ToList();

        var sb = new StringBuilder();

        sb.AppendLine("#nullable enable");
        sb.AppendLine("// <auto-generated/>");
        sb.AppendLine();
        sb.AppendLine("using System;");
        sb.AppendLine("using System.Collections.Generic;");
        sb.AppendLine("using System.Collections.Immutable;");
        sb.AppendLine();
        sb.AppendLine("namespace CoffeeBeanery.GraphQL.Core.Runtime;");
        sb.AppendLine();
        sb.AppendLine("public static class MutationMetadataRegistry");
        sb.AppendLine("{");
        sb.AppendLine("    private static readonly MutationEntityMetadata[] _entities =");
        sb.AppendLine("    {");

        for (var i = 0; i < models.Count; i++)
        {
            var comma = i < models.Count - 1 ? "," : "";
            sb.AppendLine($"        Create{models[i].ModelType!.Name}(){comma}");
        }

        sb.AppendLine("    };");
        sb.AppendLine();
        sb.AppendLine("    public static int Count => _entities.Length;");
        sb.AppendLine();
        sb.AppendLine("    public static MutationEntityMetadata Get(ushort entityId)");
        sb.AppendLine("    {");
        sb.AppendLine("        if (entityId >= _entities.Length)");
        sb.AppendLine("            throw new ArgumentOutOfRangeException(nameof(entityId));");
        sb.AppendLine();
        sb.AppendLine("        return _entities[entityId];");
        sb.AppendLine("    }");
        sb.AppendLine();

        foreach (var model in models)
        {
            EmitFactory(sb, model);
            sb.AppendLine();
        }

        sb.AppendLine("}");

        return sb.ToString();
    }

    private static void EmitFactory(
    StringBuilder sb,
    MappingClassInfo info)
{
    var modelName = info.ModelType!.Name;

    var primaryEntity =
        info.Definition.Entities.FirstOrDefault(e => e.IsPrimary)
        ?? info.Definition.Entities.FirstOrDefault();

    if (primaryEntity?.EntityType == null)
    {
        sb.AppendLine($"    private static MutationEntityMetadata Create{modelName}()");
        sb.AppendLine("        => throw new InvalidOperationException(" +
                       $"\"{modelName} has no primary entity — cannot generate mutation metadata.\");");
        return;
    }

    var tableName = IdEmitter.StripEntitySuffix(primaryEntity.EntityType.Name);
    var schema = info.Schema ?? "public";

    var distinctEntityTypeCount =
        info.Definition.Entities
            .Select(e => e.EntityType)
            .Distinct(SymbolEqualityComparer.Default)
            .Count();

    var isGraph =
        info.IsGraph ||
        distinctEntityTypeCount > 1;

    var kind =
        isGraph
            ? "MutationKind.GraphEdge"
            : "MutationKind.Entity";

    var primaryColumns =
        info.Definition.PrimaryKey
            .Select(pk => pk.ColumnKey)
            .Where(c => !string.IsNullOrWhiteSpace(c))
            .ToList();


    sb.AppendLine($"    private static MutationEntityMetadata Create{modelName}()");
    sb.AppendLine("    {");
    sb.AppendLine("        return new MutationEntityMetadata(");
    sb.AppendLine($"            EntityId.{modelName},");
    sb.AppendLine($"            StorageEntityId.{tableName},");
    sb.AppendLine($"            \"{schema}\",");
    sb.AppendLine($"            \"{tableName}\",");
    sb.AppendLine($"            {(info.IsComposite ? "false" : "true")},");
    sb.AppendLine($"            {kind},");
    sb.AppendLine(
        "            ImmutableArray.Create(" +
        string.Join(", ", primaryColumns.Select(x => $"\"{x}\"")) +
        "),");

    sb.AppendLine();
    sb.AppendLine("            new Dictionary<ushort, ImmutableArray<MutationFieldMetadata>>");
    sb.AppendLine("            {");


    var grouped =
        info.FieldMaps
            .Where(f => !f.IsNavigationKey)
            .GroupBy(f => f.SourceName, StringComparer.Ordinal)
            .ToList();


    var lines = new List<string>();


    foreach (var group in grouped)
    {
        var fieldIdName = group.Key;

        var targetLines =
            group.Select(target =>
            {
                var isPrimaryKey =
                    info.Definition.PrimaryKey.Any(pk =>
                        string.Equals(
                            pk.Entity?.Name,
                            target.DestinationEntity,
                            StringComparison.Ordinal) &&
                        string.Equals(
                            pk.ColumnKey,
                            target.DestinationName,
                            StringComparison.Ordinal));


                var storageEntityName =
                    IdEmitter.StripEntitySuffix(
                        target.DestinationEntity);


                return
                    $"new MutationFieldMetadata(" +
                    $"FieldId.{modelName}.{fieldIdName}, " +
                    $"EntityId.{modelName}, " +
                    $"StorageEntityId.{storageEntityName}, " +
                    $"ColumnId.{target.DestinationEntity}.{target.DestinationName}, " +
                    $"{(isPrimaryKey ? "true" : "false")})";
            });


        lines.Add(
            $"                [FieldId.{modelName}.{fieldIdName}] = " +
            $"ImmutableArray.Create({string.Join(", ", targetLines)})");
    }


    sb.AppendLine(string.Join(",\n", lines));

    sb.AppendLine("            });");
    sb.AppendLine("    }");
}
    
    private static void EmitGraphMetadata(
    StringBuilder sb,
    MappingClassInfo info)
{
    if (!info.IsGraph || info.Definition.Graph == null)
    {
        sb.AppendLine("            null,");
        sb.AppendLine("            null,");
        sb.AppendLine("            null,");
        sb.AppendLine("            null,");
        sb.AppendLine("            null,");
        sb.AppendLine("            null,");
        sb.AppendLine("            null,");
        sb.AppendLine("            null,");
        return;
    }

    var graph = info.Definition.Graph;

    var fromField =
        info.FieldMaps.FirstOrDefault(x =>
            string.Equals(
                x.SourceName,
                graph.From.KeyColumn,
                StringComparison.OrdinalIgnoreCase));

    var toField =
        info.FieldMaps.FirstOrDefault(x =>
            string.Equals(
                x.SourceName,
                graph.To.KeyColumn,
                StringComparison.OrdinalIgnoreCase));


    if (fromField.SourceName == null ||
        toField.SourceName == null)
    {
        sb.AppendLine("            null,");
        sb.AppendLine("            null,");
        sb.AppendLine("            null,");
        sb.AppendLine("            null,");
        sb.AppendLine("            null,");
        sb.AppendLine("            null,");
        sb.AppendLine("            null,");
        sb.AppendLine("            null,");
        return;
    }


    sb.AppendLine($"            \"{graph.GraphName}\",");
    sb.AppendLine($"            \"{graph.EdgeLabel}\",");
    sb.AppendLine($"            \"{graph.From.Label}\",");
    sb.AppendLine($"            \"{graph.To.Label}\",");

    sb.AppendLine($"            \"{graph.From.KeyColumn}\",");
    sb.AppendLine($"            \"{graph.To.KeyColumn}\",");

    sb.AppendLine(
        $"            FieldId.{info.ModelType!.Name}.{fromField.SourceName},");

    sb.AppendLine(
        $"            FieldId.{info.ModelType!.Name}.{toField.SourceName},");
}
}