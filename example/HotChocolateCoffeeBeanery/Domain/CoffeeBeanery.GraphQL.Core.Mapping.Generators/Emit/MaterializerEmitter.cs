    internal static class MaterializerEmitter
    {
        private const string Sentinel = "ushort.MaxValue";
        public static string Emit(
            ImmutableArray<MappingClassInfo> allMappings,
            ImmutableHashSet<INamedTypeSymbol> rootEntityTypes,
            List<FluentEntityNavigationConvention.EntityForeignKeyGraph.Edge> entityGraph)
        {
            var models = allMappings
                .Where(m => m.IsModel)
                .OrderBy(m => m.ModelType.Name, StringComparer.Ordinal)
                .ToList();
            var navResults = models.ToDictionary(
                m => m.ModelType.Name,
                m => EntityNavigationConvention.Resolve(m, allMappings, entityGraph, rootEntityTypes),
                StringComparer.Ordinal);
            var entities = allMappings
                .SelectMany(m => m.Definition.Entities)
                .Select(k => k.EntityType)
                .Where(t => t is not null)
                .GroupBy(t => t!.Name, StringComparer.Ordinal)
                .Select(g => g.First()!)
                .OrderBy(t => t.Name, StringComparer.Ordinal)
                .ToList();
            var sb = new StringBuilder();
            sb.AppendLine("#nullable enable");
            sb.AppendLine("// <auto-generated/>");
            sb.AppendLine("using System.Collections.Generic;");
            sb.AppendLine("using System.Data;");
            sb.AppendLine("using System.Linq;");
            sb.AppendLine("using Domain.Model;");
            sb.AppendLine("using CoffeeBeanery.GraphQL.Core.Runtime;");
            sb.AppendLine();
            sb.AppendLine("namespace CoffeeBeanery.GraphQL.Core.Runtime");
            sb.AppendLine("{");
            sb.AppendLine("    public static class MaterializerRegistry");
            sb.AppendLine("    {");
            sb.AppendLine("        public static object? Materialize(ushort storageEntityId, IDataRecord record, ushort[] map)");
            sb.AppendLine("        {");
            sb.AppendLine("            switch (storageEntityId)");
            sb.AppendLine("            {");
            foreach (var entity in entities)
                sb.AppendLine($"                case StorageEntityId.{entity.Name}: return {entity.Name}Materializer.Materialize(record, map);");
            sb.AppendLine("                default: return null;");
            sb.AppendLine("            }");
            sb.AppendLine("        }");
            sb.AppendLine("    }");
            sb.AppendLine();
            sb.AppendLine("    public static class ResultBuilderRegistry");
            sb.AppendLine("    {");
            sb.AppendLine("        public static List<T> Build<T>(ushort entityId, RowLayout layout, List<object?[]> rows) where T : class");
            sb.AppendLine("        {");
            sb.AppendLine("            switch (entityId)");
            sb.AppendLine("            {");
            foreach (var model in models)
                sb.AppendLine($"                case EntityId.{model.ModelType.Name}: return (List<T>)(object){model.ModelType.Name}ResultBuilder.Build(layout, rows);");
            sb.AppendLine("                default: throw new global::System.InvalidOperationException($\"No result builder registered for entity {entityId}.\");");
            sb.AppendLine("            }");
            sb.AppendLine("        }");
            sb.AppendLine("    }");
            sb.AppendLine();
            foreach (var entity in entities)
                EmitEntityMaterializer(sb, entity);
            foreach (var model in models)
                EmitModelMapper(sb, model);
            foreach (var model in models)
            {
                var navResult = navResults.TryGetValue(model.ModelType.Name, out var r) ? r : null;
                EmitResultBuilder(sb, model, allMappings, models, navResult, entityGraph);
            }
            sb.AppendLine("}");
            return sb.ToString();
        }
        
                private static void EmitEntityMaterializer(StringBuilder sb, INamedTypeSymbol entityType)
        {
            var scalarProps = IdEmitter.GetScalarProperties(entityType);
            var pkProp = scalarProps.FirstOrDefault(p =>
                string.Equals(p.Name, "Id", StringComparison.Ordinal))
                ?? (scalarProps.Count > 0 ? scalarProps[0] : null);
            sb.AppendLine($"    public static class {entityType.Name}Materializer");
            sb.AppendLine("    {");
            sb.AppendLine($"        public static Database.Entity.{entityType.Name}? Materialize(IDataRecord record, ushort[] map)");
            sb.AppendLine("        {");
            if (pkProp is not null)
            {
                sb.AppendLine($"            var pkOrdinal = map[ColumnId.{entityType.Name}.{pkProp.Name}];");
                sb.AppendLine($"            if (pkOrdinal == {Sentinel} || record.IsDBNull(pkOrdinal)) return null;");
                sb.AppendLine();
            }
            sb.AppendLine($"            var entity = new Database.Entity.{entityType.Name}();");
            foreach (var prop in scalarProps)
            {
                var ordinal = $"_o_{prop.Name}";
                sb.AppendLine($"            var {ordinal} = map[ColumnId.{entityType.Name}.{prop.Name}];");
                var type = prop.Type;
                var nullableType = type as INamedTypeSymbol;
                var underlying = nullableType?.OriginalDefinition.SpecialType == SpecialType.System_Nullable_T
                    ? nullableType.TypeArguments[0]
                    : type;
                if (underlying.TypeKind == TypeKind.Enum)
                {
                    var enumTypeName = underlying.ToDisplayString(SymbolDisplayFormat.FullyQualifiedFormat)
                        .Replace("global::", "");
                    if (underlying.Equals(type, SymbolEqualityComparer.Default))
                    {
                        sb.AppendLine(
                            $"            entity.{prop.Name} = {ordinal} == {Sentinel} ? default({enumTypeName}) : ({enumTypeName})record.GetInt32({ordinal});");
                    }
                    else
                    {
                        sb.AppendLine(
                            $"            entity.{prop.Name} = {ordinal} == {Sentinel} ? null : record.IsDBNull({ordinal}) ? null : ({enumTypeName})record.GetInt32({ordinal});");
                    }
                }
                else
                {
                    sb.AppendLine(
                        $"            entity.{prop.Name} = {BuildMapAccessor(prop, ordinal)};");
                }
            }
            sb.AppendLine("            return entity;");
            sb.AppendLine("        }");
            sb.AppendLine("    }");
            sb.AppendLine();
        }
        private static string BuildMapAccessor(IPropertySymbol prop, string ordinalExpr)
        {
            var type = prop.Type;
            var unwrapped = AdapterEmitter.UnwrapNullable(type);
            var isNullable =
                !SymbolEqualityComparer.Default.Equals(type, unwrapped)
                || type.NullableAnnotation == NullableAnnotation.Annotated;
            var defaultLiteral =
                isNullable
                    ? "null"
                    : $"default({unwrapped.ToDisplayString()})";
            var getter = unwrapped switch
            {
                { SpecialType: SpecialType.System_String } =>
                    $"record.GetString({ordinalExpr})",
                { SpecialType: SpecialType.System_Int32 } =>
                    $"record.GetInt32({ordinalExpr})",
                { SpecialType: SpecialType.System_Boolean } =>
                    $"record.GetBoolean({ordinalExpr})",
                { SpecialType: SpecialType.System_DateTime } =>
                    $"record.GetDateTime({ordinalExpr})",
                { Name: "Guid" } =>
                    $"record.GetGuid({ordinalExpr})",
                { TypeKind: TypeKind.Enum } =>
                    $"({unwrapped.ToDisplayString()})record.GetInt32({ordinalExpr})",
                _ =>
                    $"({unwrapped.ToDisplayString()})record.GetValue({ordinalExpr})"
            };
            var readExpr = isNullable
                ? $"record.IsDBNull({ordinalExpr}) ? {defaultLiteral} : {getter}"
                : getter;
            return $"{ordinalExpr} == {Sentinel} ? {defaultLiteral} : {readExpr}";
        }
        
                private static void EmitModelMapper(StringBuilder sb, MappingClassInfo model)
        {
            if (PlannerEmitter.IsCompositeInfo(model))
                return;
            var entityType = model.EntityType
                ?? model.Definition.Entities.FirstOrDefault(k => k.IsPrimary)?.EntityType;
            if (entityType is null)
                return;
            var fields = PlannerEmitter
                .ComputeFieldMappingsEagerPublic(model, composite: false)
                .Where(f =>
                    string.Equals(
                        f.EntityTypeName,
                        entityType.Name,
                        StringComparison.Ordinal))
                .ToList();
            sb.AppendLine($"    public static class {model.ModelType.Name}ModelMapper");
            sb.AppendLine("    {");
            sb.AppendLine($"        public static {model.ModelType.Name} FromEntity(Database.Entity.{entityType.Name} entity)");
            sb.AppendLine("        {");
            sb.AppendLine($"            var model = new {model.ModelType.Name}();");
            foreach (var fm in fields)
            {
                sb.AppendLine(
                    $"            {BuildFieldAssignment(fm, model.ModelType, entityType, "entity", "model")}");
            }
            sb.AppendLine("            return model;");
            sb.AppendLine("        }");
            sb.AppendLine("    }");
            sb.AppendLine();
        }
        private static void EmitResultBuilder(
    StringBuilder sb,
    MappingClassInfo info,
    ImmutableArray<MappingClassInfo> allMappings,
    List<MappingClassInfo> models,
    NavigationResolutionResult? navResult,
    List<FluentEntityNavigationConvention.EntityForeignKeyGraph.Edge> entityGraph)
{
    var primaryLink =
        info.Definition.Entities.FirstOrDefault(k => k.IsPrimary);

    var primaryEntityName =
        primaryLink?.EntityType?.Name
        ?? info.EntityType?.Name;

    if (primaryEntityName is null)
        return;

    var primaryEntityType =
        primaryLink?.EntityType
        ?? info.EntityType;

    var childLinks =
        PlannerEmitter
            .ComputeChildLinks(
                info,
                allMappings,
                navResult,
                entityGraph)
            .Where(l =>
                !string.Equals(
                    l.ChildModelName,
                    info.ModelType.Name,
                    StringComparison.Ordinal))
            .ToList();

    var fkNavAliases =
        info.Definition.Entities
            .Where(k =>
                !k.IsPrimary &&
                !string.IsNullOrWhiteSpace(k.AliasProperty))
            .Select(k =>
            {
                var entityName = k.EntityType!.Name;
                var entitySymbol = k.EntityType!;

                var relatedModel =
                    allMappings.FirstOrDefault(m =>
                        m.IsModel &&
                        !PlannerEmitter.IsCompositeInfo(m) &&
                        string.Equals(
                            m.EntityType?.Name,
                            entityName,
                            StringComparison.Ordinal));

                return (
                    Alias: k.AliasProperty!,
                    EntityName: entityName,
                    EntityType: entitySymbol,
                    ModelName:
                        relatedModel?.ModelType.Name
                        ?? entityName);
            })
            .ToList();

    var distinctLayoutNames =
        new HashSet<string>(StringComparer.OrdinalIgnoreCase);

    var uniqueVariablesToEmit =
        new List<(string LayoutName, string VarName)>();

    foreach (var item in fkNavAliases)
    {
        if (distinctLayoutNames.Add(item.Alias))
            uniqueVariablesToEmit.Add(
                (item.Alias, ToCamel(item.Alias)));
    }

    foreach (var link in childLinks)
    {
        if (distinctLayoutNames.Add(link.NavigationName))
            uniqueVariablesToEmit.Add(
                (link.NavigationName, ToCamel(link.NavigationName)));
    }

    string GetEntityPkProperty(INamedTypeSymbol? entity)
    {
        if (entity == null)
            return "Id";

        var mappedInfo =
            allMappings.FirstOrDefault(m =>
                m.Definition.PrimaryKey != null &&
                m.Definition.PrimaryKey.Any(pk =>
                    SymbolEqualityComparer.Default.Equals(
                        pk.Entity,
                        entity)));

        if (mappedInfo != null)
        {
            return mappedInfo.Definition.PrimaryKey
                .First(pk =>
                    SymbolEqualityComparer.Default.Equals(
                        pk.Entity,
                        entity))
                .ColumnKey;
        }

        if (entity.GetMembers()
            .OfType<IPropertySymbol>()
            .Any(p =>
                string.Equals(
                    p.Name,
                    "Id",
                    StringComparison.Ordinal)))
            return "Id";

        var conventionalKey =
            entity.Name + "Key";

        return entity.GetMembers()
            .OfType<IPropertySymbol>()
            .Any(p =>
                string.Equals(
                    p.Name,
                    conventionalKey,
                    StringComparison.Ordinal))
            ? conventionalKey
            : "Id";
    }

    var rootEntityPk =
        GetEntityPkProperty(primaryEntityType);

    var rootPkSymbol =
        primaryEntityType?
            .GetMembers()
            .OfType<IPropertySymbol>()
            .FirstOrDefault(p =>
                string.Equals(
                    p.Name,
                    rootEntityPk,
                    StringComparison.Ordinal));

    var keyTypeName =
        rootPkSymbol?
            .Type
            .ToDisplayString(
                SymbolDisplayFormat.FullyQualifiedFormat)
        ?? "int";

    if (keyTypeName.EndsWith("?"))
        keyTypeName =
            keyTypeName.Substring(
                0,
                keyTypeName.Length - 1);

    sb.AppendLine($"    public static class {info.ModelType.Name}ResultBuilder");
    sb.AppendLine("    {");
    sb.AppendLine($"        public static List<{info.ModelType.Name}> Build(RowLayout layout, List<object?[]> rows)");
    sb.AppendLine("        {");
    sb.AppendLine($"            var rootIdx = layout.IndexOf(\"{info.ModelType.Name}\");");
    sb.AppendLine("            if (rootIdx < 0) return new();");

    sb.AppendLine($"            var order = new List<{keyTypeName}>();");
    sb.AppendLine($"            var byRootId = new Dictionary<{keyTypeName}, {info.ModelType.Name}>();");

    foreach (var item in uniqueVariablesToEmit)
    {
        sb.AppendLine(
            $"            var {item.VarName}Idx = layout.IndexOf(\"{item.LayoutName}\");");
    }

    sb.AppendLine("            foreach (var row in rows)");
    sb.AppendLine("            {");

    sb.AppendLine(
        $"                var rootEntity = (Database.Entity.{primaryEntityName}?)row[rootIdx];");

    sb.AppendLine(
        "                if (rootEntity is null) continue;");

    sb.AppendLine(
        $"                if (!byRootId.TryGetValue(rootEntity.{rootEntityPk}, out var model))");

    sb.AppendLine("                {");

    sb.AppendLine(
        $"                    model = new {info.ModelType.Name}();");

    var primaryFields =
        PlannerEmitter
            .ComputeFieldMappingsEagerPublic(
                info,
                composite: true)
            .Where(f =>
                string.Equals(
                    f.EntityTypeName,
                    primaryEntityName,
                    StringComparison.Ordinal))
            .ToList();

    foreach (var fm in primaryFields)
    {
        sb.AppendLine(
            $"                    {BuildFieldAssignment(fm, info.ModelType, primaryEntityType, "rootEntity", "model")}");
    }

    sb.AppendLine(
        $"                    byRootId[rootEntity.{rootEntityPk}] = model;");

    sb.AppendLine(
        $"                    order.Add(rootEntity.{rootEntityPk});");

    sb.AppendLine("                }");

    foreach (var link in childLinks)
    {
        if (fkNavAliases.Any(a =>
            string.Equals(
                a.Alias,
                link.NavigationName,
                StringComparison.Ordinal)))
            continue;

        var camel =
            ToCamel(link.NavigationName);

        var childProperty =
            info.ModelType
                .GetMembers()
                .OfType<IPropertySymbol>()
                .FirstOrDefault(p =>
                    string.Equals(
                        p.Name,
                        link.NavigationName,
                        StringComparison.Ordinal));

        var isCollection =
            childProperty != null &&
            childProperty.Type is INamedTypeSymbol named &&
            named.IsGenericType &&
            (
                named.Name == "List" ||
                named.Name == "ICollection" ||
                named.Name == "IEnumerable" ||
                named.Name == "IList" ||
                named.Name == "IReadOnlyList" ||
                named.Name == "IReadOnlyCollection"
            );

        sb.AppendLine(
            $"                if ({camel}Idx >= 0)");

        sb.AppendLine("                {");

        sb.AppendLine(
            $"                    var {camel} = (Database.Entity.{link.ChildEntityName}?)row[{camel}Idx];");

        sb.AppendLine(
            $"                    if ({camel} is not null)");

        sb.AppendLine("                    {");

        if (isCollection)
        {
            sb.AppendLine(
                $"                        model.{link.NavigationName} ??= new();");

            sb.AppendLine(
                $"                        if (!model.{link.NavigationName}.Any())");

            sb.AppendLine("                        {");

            sb.AppendLine(
                $"                            model.{link.NavigationName}.Add(new {link.ChildModelName}());");

            sb.AppendLine("                        }");
        }
        else
        {
            sb.AppendLine(
                $"                        if (model.{link.NavigationName} is null)");

            sb.AppendLine("                        {");

            sb.AppendLine(
                $"                            model.{link.NavigationName} = new {link.ChildModelName}();");

            sb.AppendLine("                        }");
        }

        sb.AppendLine("                    }");
        sb.AppendLine("                }");
    }

    sb.AppendLine("            }");

    sb.AppendLine();
    sb.AppendLine(
        "            return order.Select(id => byRootId[id]).ToList();");

    sb.AppendLine("        }");
    sb.AppendLine("    }");
    sb.AppendLine();
}
        private static string BuildFieldAssignment(
    (string FieldName, string EntityTypeName, string ColumnName, string? StorageAlias) fm,
    INamedTypeSymbol modelType,
    INamedTypeSymbol? entityType,
    string sourceVar,
    string targetVar)
{
    var modelProp =
        modelType.GetMembers()
            .OfType<IPropertySymbol>()
            .FirstOrDefault(p =>
                string.Equals(
                    p.Name,
                    fm.FieldName,
                    StringComparison.Ordinal));

    var entityProp =
        entityType?
            .GetMembers()
            .OfType<IPropertySymbol>()
            .FirstOrDefault(p =>
                string.Equals(
                    p.Name,
                    fm.ColumnName,
                    StringComparison.Ordinal));

    if (modelProp is null || entityProp is null)
        return $"// Mapping missing {fm.FieldName} -> {fm.ColumnName}";

    var modelTypeSymbol = AdapterEmitter.UnwrapNullable(modelProp.Type);
    var entityTypeSymbol = AdapterEmitter.UnwrapNullable(entityProp.Type);

    if (modelTypeSymbol.TypeKind == TypeKind.Enum &&
        entityTypeSymbol.TypeKind == TypeKind.Enum)
    {
        var modelEnum =
            modelTypeSymbol
                .ToDisplayString(SymbolDisplayFormat.FullyQualifiedFormat)
                .Replace("global::", "");

        var nullable =
            modelProp.Type.OriginalDefinition.SpecialType ==
            SpecialType.System_Nullable_T;

        if (nullable)
        {
            return
                $"{targetVar}.{modelProp.Name} = " +
                $"{sourceVar}.{entityProp.Name} is null ? null : " +
                $"({modelEnum}){sourceVar}.{entityProp.Name};";
        }

        return
            $"{targetVar}.{modelProp.Name} = " +
            $"({modelEnum}){sourceVar}.{entityProp.Name};";
    }

    if (modelProp.Type.SpecialType == SpecialType.System_String &&
        entityProp.Type.SpecialType != SpecialType.System_String)
    {
        return
            $"{targetVar}.{modelProp.Name} = " +
            $"{sourceVar}.{entityProp.Name}?.ToString();";
    }

    return
        $"{targetVar}.{modelProp.Name} = {sourceVar}.{entityProp.Name};";
}
        internal static ITypeSymbol UnwrapCollection(ITypeSymbol type)
        {
            if (type is INamedTypeSymbol named &&
                named.IsGenericType &&
                named.TypeArguments.Length == 1)
            {
                if (named.Name is "List"
                    or "ICollection"
                    or "IEnumerable"
                    or "IList"
                    or "IReadOnlyList"
                    or "IReadOnlyCollection")
                {
                    return named.TypeArguments[0];
                }
            }
            return type;
        }
        private static string ToCamel(string value)
        {
            if (string.IsNullOrEmpty(value))
                return value;
            return char.ToLowerInvariant(value[0]) + value.Substring(1);
        }
    }
