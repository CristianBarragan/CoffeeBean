    internal static class MaterializerEmitter
    {
        private const string Sentinel = "ushort.MaxValue";

        public static string Emit(
            ImmutableArray<MappingClassInfo> allMappings,
            ImmutableHashSet<INamedTypeSymbol> rootEntityTypes,
            List<FluentEntityNavigationConvention.EntityForeignKeyGraph.Edge> entityGraph)
        {
            var models = allMappings
                .Where(m => m.IsModel)
                .OrderBy(m => m.ModelType.Name, System.StringComparer.Ordinal)
                .ToList();

            var navResults = models.ToDictionary(
                m => m.ModelType.Name,
                m => EntityNavigationConvention.Resolve(m, allMappings, entityGraph, rootEntityTypes),
                System.StringComparer.Ordinal);
            
            var entities = allMappings
                .SelectMany(m => m.Definition.Entities)
                .Select(k => k.EntityType)
                .Where(t => t is not null)
                .GroupBy(t => t!.Name, System.StringComparer.Ordinal)
                .Select(g => g.First()!)
                .OrderBy(t => t.Name, System.StringComparer.Ordinal)
                .ToList();

            var sb = new StringBuilder();
            sb.AppendLine("#nullable enable");
            sb.AppendLine("// <auto-generated/>");
            
            sb.AppendLine("using System.Collections.Generic;");
            sb.AppendLine("using System.Data;");
            sb.AppendLine("using System.Linq;");
            sb.AppendLine("using Domain.Model;");
            sb.AppendLine("using CoffeeBeanery.GraphQL.Core.Runtime;");
            sb.AppendLine();
            sb.AppendLine("namespace CoffeeBeanery.GraphQL.Core.Runtime");
            sb.AppendLine("{");

            sb.AppendLine("    public static class MaterializerRegistry");
            sb.AppendLine("    {");
            sb.AppendLine("        public static object? Materialize(ushort storageEntityId, IDataRecord record, ushort[] map)");
            sb.AppendLine("        {");
            sb.AppendLine("            switch (storageEntityId)");
            sb.AppendLine("            {");
            foreach (var entity in entities)
                sb.AppendLine($"                case StorageEntityId.{entity.Name}: return {entity.Name}Materializer.Materialize(record, map);");
            sb.AppendLine("                default: return null;");
            sb.AppendLine("            }");
            sb.AppendLine("        }");
            sb.AppendLine("    }");
            sb.AppendLine();

            sb.AppendLine("    public static class ResultBuilderRegistry");
            sb.AppendLine("    {");
            sb.AppendLine("        public static List<T> Build<T>(ushort entityId, RowLayout layout, List<object?[]> rows) where T : class");
            sb.AppendLine("        {");
            sb.AppendLine("            switch (entityId)");
            sb.AppendLine("            {");
            foreach (var model in models)
                sb.AppendLine($"                case EntityId.{model.ModelType.Name}: return (List<T>)(object){model.ModelType.Name}ResultBuilder.Build(layout, rows);");
            sb.AppendLine("                default: throw new global::System.InvalidOperationException($\"No result builder registered for entity {entityId}.\");");
            sb.AppendLine("            }");
            sb.AppendLine("        }");
            sb.AppendLine("    }");
            sb.AppendLine();

            foreach (var entity in entities)
                EmitEntityMaterializer(sb, entity);

            foreach (var model in models)
                EmitModelMapper(sb, model);

            foreach (var model in models)
            {
                var navResult = navResults.TryGetValue(model.ModelType.Name, out var r) ? r : null;
                EmitResultBuilder(sb, model, allMappings, models, navResult);
            }

            sb.AppendLine("}");
            return sb.ToString();
        }

        // ---------------------------------------------------------------
        // Entity materializer — map-based ordinal lookup
        // ---------------------------------------------------------------

        private static void EmitEntityMaterializer(StringBuilder sb, INamedTypeSymbol entityType)
        {
            var scalarProps = IdEmitter.GetScalarProperties(entityType);

            var pkProp = scalarProps.FirstOrDefault(p =>
                string.Equals(p.Name, "Id", System.StringComparison.Ordinal))
                ?? (scalarProps.Count > 0 ? scalarProps[0] : null);

            sb.AppendLine($"    public static class {entityType.Name}Materializer");
            sb.AppendLine("    {");
            sb.AppendLine($"        // map is indexed by ColumnId.{entityType.Name}.* constants.");
            sb.AppendLine($"        // Entries equal to ushort.MaxValue mean the column was not projected.");
            sb.AppendLine($"        public static Database.Entity.{entityType.Name}? Materialize(IDataRecord record, ushort[] map)");
            sb.AppendLine("        {");

            if (pkProp is not null)
            {
                sb.AppendLine($"            var pkOrdinal = map[ColumnId.{entityType.Name}.{pkProp.Name}];");
                sb.AppendLine($"            if (pkOrdinal == {Sentinel} || record.IsDBNull(pkOrdinal)) return null;");
                sb.AppendLine();
            }

            sb.AppendLine($"            var entity = new Database.Entity.{entityType.Name}();");

            foreach (var prop in scalarProps)
            {
                var ordinal = $"_o_{prop.Name}";
                sb.AppendLine($"            var {ordinal} = map[ColumnId.{entityType.Name}.{prop.Name}];");

                var type = prop.Type;
                var nullableType = type as INamedTypeSymbol;
                var underlying = nullableType?.OriginalDefinition.SpecialType == SpecialType.System_Nullable_T
                    ? nullableType.TypeArguments[0]
                    : type;

                if (underlying.TypeKind == TypeKind.Enum)
                {
                    var enumTypeName = underlying.ToDisplayString(SymbolDisplayFormat.FullyQualifiedFormat)
                                                 .Replace("global::", "");

                    if (underlying.Equals(type, SymbolEqualityComparer.Default))
                    {
                        sb.AppendLine(
                            $"            entity.{prop.Name} = {ordinal} == {Sentinel} ? default({enumTypeName}) : ({enumTypeName})record.GetInt32({ordinal});");
                    }
                    else
                    {
                        sb.AppendLine(
                            $"            entity.{prop.Name} = {ordinal} == {Sentinel} ? null : record.IsDBNull({ordinal}) ? null : ({enumTypeName})record.GetInt32({ordinal});");
                    }
                }
                else
                {
                    var accessExpr = BuildMapAccessor(prop, ordinal);
                    sb.AppendLine($"            entity.{prop.Name} = {accessExpr};");
                }
            }

            sb.AppendLine("            return entity;");
            sb.AppendLine("        }");
            sb.AppendLine("    }");
            sb.AppendLine();
        }

        private static string BuildMapAccessor(IPropertySymbol prop, string ordinalExpr)
        {
            var type      = prop.Type;
            var unwrapped = AdapterEmitter.UnwrapNullable(type);
            var isNullable = !SymbolEqualityComparer.Default.Equals(type, unwrapped)
                             || type.NullableAnnotation == NullableAnnotation.Annotated;

            var defaultLiteral = isNullable ? "null" : $"default({unwrapped.ToDisplayString()})";

            // Switch on UNWRAPPED type — fixes Guid? and enum? falling through to wrong branch
            var getter = unwrapped switch
            {
                { SpecialType: SpecialType.System_String }   => $"record.GetString({ordinalExpr})",
                { SpecialType: SpecialType.System_Int32 }    => $"record.GetInt32({ordinalExpr})",
                { SpecialType: SpecialType.System_Boolean }  => $"record.GetBoolean({ordinalExpr})",
                { SpecialType: SpecialType.System_DateTime } => $"record.GetDateTime({ordinalExpr})",
                { Name: "Guid" }                              => $"record.GetGuid({ordinalExpr})",
                { TypeKind: TypeKind.Enum }                   => $"({unwrapped.ToDisplayString()})record.GetInt32({ordinalExpr})",
                _ => $"({unwrapped.ToDisplayString()})record.GetValue({ordinalExpr})"
            };

            var readExpr = isNullable
                ? $"record.IsDBNull({ordinalExpr}) ? {defaultLiteral} : {getter}"
                : getter;

            return $"{ordinalExpr} == {Sentinel} ? {defaultLiteral} : {readExpr}";
        }

        // ---------------------------------------------------------------
        // Entity -> Model mapper
        // ---------------------------------------------------------------

        private static void EmitModelMapper(StringBuilder sb, MappingClassInfo model)
        {
            if (PlannerEmitter.IsCompositeInfo(model)) return;

            var entityType = model.EntityType
                ?? model.Definition.Entities.FirstOrDefault(k => k.IsPrimary)?.EntityType;
            if (entityType is null) return;

            var fields = PlannerEmitter.ComputeFieldMappingsEagerPublic(model, composite: false)
                .Where(f => string.Equals(f.EntityTypeName, entityType.Name, System.StringComparison.Ordinal))
                .ToList();

            sb.AppendLine($"    public static class {model.ModelType.Name}ModelMapper");
            sb.AppendLine("    {");
            sb.AppendLine($"        public static {model.ModelType.Name} FromEntity(Database.Entity.{entityType.Name} entity)");
            sb.AppendLine("        {");
            sb.AppendLine($"            var model = new {model.ModelType.Name}();");

            foreach (var fm in fields)
                sb.AppendLine($"            {BuildFieldAssignment(fm, model.ModelType, entityType, "entity", "model")}");

            sb.AppendLine("            return model;");
            sb.AppendLine("        }");
            sb.AppendLine("    }");
            sb.AppendLine();
        }

        private static void EmitResultBuilder(
            StringBuilder sb,
            MappingClassInfo info,
            ImmutableArray<MappingClassInfo> allMappings,
            List<MappingClassInfo> models,
            NavigationResolutionResult? navResult)
        {
            var composite = PlannerEmitter.IsCompositeInfo(info);

            var primaryLink       = info.Definition.Entities.FirstOrDefault(k => k.IsPrimary);
            var primaryEntityName = primaryLink?.EntityType?.Name ?? info.EntityType?.Name;
            if (primaryEntityName is null) return;

            var primaryEntityType = primaryLink?.EntityType ?? info.EntityType;

            var childLinks = PlannerEmitter
                .ComputeChildLinks(info, allMappings, navResult)
                .Where(l => !string.Equals(
                    l.ChildModelName,
                    info.ModelType.Name,
                    StringComparison.Ordinal))
                .ToList();

            var fkNavAliases = info.Definition.Entities
                .Where(k => !k.IsPrimary && !string.IsNullOrWhiteSpace(k.AliasProperty))
                .Select(k =>
                {
                    var entityName   = k.EntityType!.Name;
                    var entitySymbol = k.EntityType!;
                    var relatedModel = allMappings.FirstOrDefault(m =>
                        m.IsModel &&
                        !PlannerEmitter.IsCompositeInfo(m) &&
                        string.Equals(m.EntityType?.Name, entityName, System.StringComparison.Ordinal));
                    return (
                        Alias:       k.AliasProperty!,
                        EntityName:  entityName,
                        EntityType:  entitySymbol,
                        ModelName:   relatedModel?.ModelType.Name ?? entityName);
                })
                .ToList();

            // Collect ALL unique layout variables used across both aliases and children
            var distinctLayoutNames = new HashSet<string>(System.StringComparer.OrdinalIgnoreCase);
            var uniqueVariablesToEmit = new List<(string LayoutName, string VarName)>();

            foreach (var (alias, _, _, _) in fkNavAliases)
            {
                if (distinctLayoutNames.Add(alias))
                    uniqueVariablesToEmit.Add((alias, ToCamel(alias)));
            }
            foreach (var link in childLinks)
            {
                if (distinctLayoutNames.Add(link.NavigationName))
                    uniqueVariablesToEmit.Add((link.NavigationName, ToCamel(link.NavigationName)));
            }

            // Helper to find the database entity's column primary key property name
            string GetEntityPkProperty(INamedTypeSymbol? entity)
            {
                if (entity == null) return "Id";
                var mappedInfo = allMappings.FirstOrDefault(m => 
                    m.Definition.PrimaryKey != null && 
                    m.Definition.PrimaryKey.Any(pk => SymbolEqualityComparer.Default.Equals(pk.Entity, entity)));
                if (mappedInfo != null)
                {
                    return mappedInfo.Definition.PrimaryKey.First(pk => SymbolEqualityComparer.Default.Equals(pk.Entity, entity)).ColumnKey;
                }
                if (entity.GetMembers().OfType<IPropertySymbol>().Any(p => string.Equals(p.Name, "Id", System.StringComparison.Ordinal))) return "Id";
                var conventionalKey = entity.Name + "Key";
                return entity.GetMembers().OfType<IPropertySymbol>().Any(p => string.Equals(p.Name, conventionalKey, System.StringComparison.Ordinal)) ? conventionalKey : "Id";
            }

            var rootEntityPk = GetEntityPkProperty(primaryEntityType);
            var rootPkSymbol = primaryEntityType?.GetMembers().OfType<IPropertySymbol>()
                .FirstOrDefault(p => string.Equals(p.Name, rootEntityPk, System.StringComparison.Ordinal));
            
            var keyTypeName = rootPkSymbol?.Type.ToDisplayString(SymbolDisplayFormat.FullyQualifiedFormat) ?? "int";
            if (keyTypeName.EndsWith("?")) keyTypeName = keyTypeName.Substring(0, keyTypeName.Length - 1);

            sb.AppendLine($"    public static class {info.ModelType.Name}ResultBuilder");
            sb.AppendLine("    {");
            sb.AppendLine($"        public static List<{info.ModelType.Name}> Build(RowLayout layout, List<object?[]> rows)");
            sb.AppendLine("        {");
            sb.AppendLine($"            var rootIdx = layout.IndexOf(\"{info.ModelType.Name}\");");
            sb.AppendLine("            if (rootIdx < 0) return new();");
            sb.AppendLine();
            sb.AppendLine($"            var order    = new List<{keyTypeName}>();");
            sb.AppendLine($"            var byRootId = new Dictionary<{keyTypeName}, {info.ModelType.Name}>();");
            sb.AppendLine();

            // Emit layout indexing definitions
            foreach (var item in uniqueVariablesToEmit)
                sb.AppendLine($"            var {item.VarName}Idx = layout.IndexOf(\"{item.LayoutName}\");");

            sb.AppendLine();
            sb.AppendLine("            foreach (var row in rows)");
            sb.AppendLine("            {");
            sb.AppendLine($"                var rootEntity = (Database.Entity.{primaryEntityName}?)row[rootIdx];");
            sb.AppendLine("                if (rootEntity is null) continue;");
            sb.AppendLine();
            sb.AppendLine($"                if (!byRootId.TryGetValue(rootEntity.{rootEntityPk}, out var model))");
            sb.AppendLine("                {");
            sb.AppendLine($"                    model = new {info.ModelType.Name}();");

            var primaryFields = PlannerEmitter.ComputeFieldMappingsEagerPublic(info, composite: true)
                .Where(f => string.Equals(f.EntityTypeName, primaryEntityName, System.StringComparison.Ordinal))
                .ToList();

            foreach (var fm in primaryFields)
                sb.AppendLine($"                    {BuildFieldAssignment(fm, info.ModelType, primaryEntityType, "rootEntity", "model")}");

            sb.AppendLine($"                    byRootId[rootEntity.{rootEntityPk}] = model;");
            sb.AppendLine($"                    order.Add(rootEntity.{rootEntityPk});");
            sb.AppendLine("                }");
            sb.AppendLine();

            // Handle layout property flatten assignments
            foreach (var (alias, entityName, entityType, modelName) in fkNavAliases)
            {
                var camel = ToCamel(alias);
                var targetModelInfo = allMappings.FirstOrDefault(m => string.Equals(m.ModelType.Name, modelName, System.StringComparison.Ordinal));
                var isTargetComposite = targetModelInfo != null && PlannerEmitter.IsCompositeInfo(targetModelInfo);
                
                var targetMapper = (models.Any(m => m.ModelType.Name == modelName) && !isTargetComposite) 
                    ? $"{modelName}ModelMapper.FromEntity" 
                    : null;

                sb.AppendLine($"                if ({camel}Idx >= 0 && model.{alias} is null)");
                sb.AppendLine("                {");
                sb.AppendLine($"                    var {camel} = (Database.Entity.{entityName}?)row[{camel}Idx];");
                
                if (targetMapper != null)
                {
                    sb.AppendLine($"                    if ({camel} is not null) model.{alias} = {targetMapper}({camel});");
                    
                    var flattenFields = PlannerEmitter.ComputeFieldMappingsEagerPublic(info, composite: true)
                        .Where(f => string.Equals(f.EntityTypeName, entityName, System.StringComparison.Ordinal))
                        .ToList();
                    foreach (var fm in flattenFields)
                    {
                        // Fix: Prevent Inner aliases from overwriting Outer fields, and vice-versa
                        if (alias.StartsWith("Inner") && fm.FieldName.StartsWith("Outer")) continue;
                        if (alias.StartsWith("Outer") && fm.FieldName.StartsWith("Inner")) continue;

                        sb.AppendLine($"                    if ({camel} is not null) {BuildFieldAssignment(fm, info.ModelType, entityType, camel, "model")}");
                    }
                }
                else
                {
                    sb.AppendLine($"                    if ({camel} is not null)");
                    sb.AppendLine("                    {");
                    sb.AppendLine($"                        model.{alias} = new {modelName}();");
                    var flattenFields = PlannerEmitter.ComputeFieldMappingsEagerPublic(info, composite: true)
                        .Where(f => string.Equals(f.EntityTypeName, entityName, System.StringComparison.Ordinal))
                        .ToList();
                    foreach (var fm in flattenFields)
                    {
                        var targetTypeSymbol = targetModelInfo?.ModelType ?? info.ModelType;
                        sb.AppendLine($"                        {BuildFieldAssignment(fm, targetTypeSymbol, entityType, camel, $"model.{alias}")}");
                    }
                    sb.AppendLine("                    }");
                }

                sb.AppendLine("                }");
                sb.AppendLine();
            }

            // Handle navigation child mapping nodes
            foreach (var link in childLinks)
            {
                if (fkNavAliases.Any(a => string.Equals(a.Alias, link.NavigationName, System.StringComparison.Ordinal)))
                    continue;

                var camel = ToCamel(link.NavigationName);
                var childMapping = allMappings.FirstOrDefault(m => string.Equals(m.ModelType.Name, link.ChildModelName, System.StringComparison.Ordinal));
                
                var isChildComposite = childMapping != null && PlannerEmitter.IsCompositeInfo(childMapping);
                var targetMapper = (models.Any(m => m.ModelType.Name == link.ChildModelName) && !isChildComposite)
                    ? $"{link.ChildModelName}ModelMapper.FromEntity" 
                    : null;

                var childModelProp = info.ModelType.GetMembers().OfType<IPropertySymbol>().FirstOrDefault(p => p.Name == link.NavigationName);
                
                var childEntitySymbol = childMapping?.EntityType ?? childMapping?.Definition.Entities.FirstOrDefault(k => k.IsPrimary)?.EntityType;
                string entityJoinKey = GetEntityPkProperty(childEntitySymbol);
                string modelJoinKey = GetChildJoinColumn(link); 

                if (childEntitySymbol != null)
                {
                    var mappedInfo = allMappings.FirstOrDefault(m => 
                        m.Definition.PrimaryKey != null && 
                        m.Definition.PrimaryKey.Any(pk => SymbolEqualityComparer.Default.Equals(pk.Entity, childEntitySymbol)));
                    if (mappedInfo != null)
                    {
                        modelJoinKey = mappedInfo.Definition.PrimaryKey.First(pk => SymbolEqualityComparer.Default.Equals(pk.Entity, childEntitySymbol)).ModelKey;
                    }
                }

                var unwrappedType = childModelProp != null ? UnwrapCollection(childModelProp.Type) : null;
                var childModelKeySymbol = unwrappedType?.GetMembers().OfType<IPropertySymbol>().FirstOrDefault(p => p.Name == modelJoinKey);
                
                var modelKeyTypeStr = childModelKeySymbol?.Type.ToDisplayString() ?? "";
                var isComparisonMismatch = modelKeyTypeStr.Contains("Guid") || modelKeyTypeStr.Contains("string");

                if (link.IsCollection)
                {
                    sb.AppendLine($"                if ({camel}Idx >= 0)");
                    sb.AppendLine("                {");
                    sb.AppendLine($"                    var {camel} = (Database.Entity.{link.ChildEntityName}?)row[{camel}Idx];");
                    sb.AppendLine($"                    if ({camel} is not null)");
                    sb.AppendLine("                    {");
                    sb.AppendLine($"                        model.{link.NavigationName} ??= new();");
                    
                    if (isComparisonMismatch)
                    {
                        bool isModelNullable = childModelKeySymbol?.Type.NullableAnnotation == NullableAnnotation.Annotated || 
                                               (childModelKeySymbol?.Type.OriginalDefinition.SpecialType == SpecialType.System_Nullable_T);
                        
                        var entityPropSymbol = childEntitySymbol?.GetMembers().OfType<IPropertySymbol>()
                            .FirstOrDefault(p => string.Equals(p.Name, entityJoinKey, System.StringComparison.Ordinal));
                        bool isEntityNullable = entityPropSymbol?.Type.NullableAnnotation == NullableAnnotation.Annotated || 
                                                (entityPropSymbol?.Type.OriginalDefinition.SpecialType == SpecialType.System_Nullable_T);

                        string modelAccess = isModelNullable ? $"x.{modelJoinKey}?.ToString()" : $"x.{modelJoinKey}.ToString()";
                        string entityAccess = isEntityNullable ? $"{camel}.{entityJoinKey}?.ToString()" : $"{camel}.{entityJoinKey}.ToString()";

                        sb.AppendLine($"                        if (!model.{link.NavigationName}.Any(x => {modelAccess} == {entityAccess}))");
                    }
                    else
                    {
                        sb.AppendLine($"                        if (!model.{link.NavigationName}.Any(x => x.{modelJoinKey} == {camel}.{entityJoinKey}))");
                    }
                    
                    sb.AppendLine("                        {");
                    if (targetMapper != null)
                    {
                        sb.AppendLine($"                            model.{link.NavigationName}.Add({targetMapper}({camel}));");
                    }
                    else
                    {
                        sb.AppendLine($"                            var compositeItem = new {link.ChildModelName}();");
                        var compositeFields = PlannerEmitter.ComputeFieldMappingsEagerPublic(childMapping!, composite: true)
                            .Where(f => string.Equals(f.EntityTypeName, link.ChildEntityName, System.StringComparison.Ordinal))
                            .ToList();
                        
                        foreach (var fm in compositeFields)
                        {
                            var targetTypeSymbol = childMapping?.ModelType ?? info.ModelType;
                            sb.AppendLine($"                            {BuildFieldAssignment(fm, targetTypeSymbol, childEntitySymbol, camel, "compositeItem")}");
                        }

                        if (!compositeFields.Any(f => string.Equals(f.FieldName, modelJoinKey, System.StringComparison.Ordinal)))
                        {
                            var modelKeyProp = (childMapping?.ModelType ?? info.ModelType).GetMembers().OfType<IPropertySymbol>()
                                .FirstOrDefault(p => string.Equals(p.Name, modelJoinKey, StringComparison.Ordinal));

                            var matchingEntityProp = childEntitySymbol?.GetMembers().OfType<IPropertySymbol>()
                                .FirstOrDefault(p =>
                                    string.Equals(p.Name, entityJoinKey, StringComparison.Ordinal) &&
                                    modelKeyProp != null &&
                                    IsCompatibleType(p.Type, modelKeyProp.Type));

                            if (matchingEntityProp != null)
                            {
                                var primaryKeyField = (FieldName: modelJoinKey, EntityTypeName: link.ChildEntityName, ColumnName: entityJoinKey);
                                var targetTypeSymbol = childMapping?.ModelType ?? info.ModelType;
                                sb.AppendLine($"                            {BuildFieldAssignment(primaryKeyField, targetTypeSymbol, childEntitySymbol, camel, "compositeItem")}");
                            }
                        }

                        sb.AppendLine($"                            model.{link.NavigationName}.Add(compositeItem);");
                    }
                    sb.AppendLine("                        }");
                    sb.AppendLine("                    }");
                    sb.AppendLine("                }");
                }
                else
                {
                    sb.AppendLine($"                if ({camel}Idx >= 0 && model.{link.NavigationName} is null)");
                    sb.AppendLine("                {");
                    sb.AppendLine($"                    var {camel} = (Database.Entity.{link.ChildEntityName}?)row[{camel}Idx];");
                    if (targetMapper != null)
                    {
                        sb.AppendLine($"                    if ({camel} is not null) model.{link.NavigationName} = {targetMapper}({camel});");
                    }
                    else
                    {
                        sb.AppendLine($"                    if ({camel} is not null)");
                        sb.AppendLine("                    {");
                        sb.AppendLine($"                        model.{link.NavigationName} = new {link.ChildModelName}();");
                        var compositeFields = PlannerEmitter.ComputeFieldMappingsEagerPublic(childMapping!, composite: true)
                            .Where(f => string.Equals(f.EntityTypeName, link.ChildEntityName, System.StringComparison.Ordinal))
                            .ToList();
                        foreach (var fm in compositeFields)
                        {
                            var targetTypeSymbol = childMapping?.ModelType ?? info.ModelType;
                            sb.AppendLine($"                        {BuildFieldAssignment(fm, targetTypeSymbol, childEntitySymbol, camel, $"model.{link.NavigationName}")}");
                        }
                        sb.AppendLine("                    }");
                    }
                    sb.AppendLine("                }"); 
                }
                sb.AppendLine();
            }

            sb.AppendLine("            }");
            sb.AppendLine();
            sb.AppendLine("            return order.Select(id => byRootId[id]).ToList();");
            sb.AppendLine("        }");
            sb.AppendLine("    }");
            sb.AppendLine();
        }
        
        private static string GetChildJoinColumn(ChildLink link)
        {
            if (link.Hops.Count == 0) return "Id";
            var lastHop = link.Hops[link.Hops.Count - 1];
            return string.Equals(lastHop.ToEntityName, link.ChildEntityName, StringComparison.Ordinal)
                ? lastHop.ToColumn
                : lastHop.FromColumn;
        }
        
        private static bool IsCompatibleType(ITypeSymbol entityType, ITypeSymbol modelType)
        {
            var entityUnderlying = AdapterEmitter.UnwrapNullable(entityType);
            var modelUnderlying = AdapterEmitter.UnwrapNullable(modelType);
            return SymbolEqualityComparer.Default.Equals(entityUnderlying, modelUnderlying);
        }

        // ---------------------------------------------------------------
        // Field assignment helpers
        // ---------------------------------------------------------------
        
        internal static ITypeSymbol UnwrapCollection(ITypeSymbol type)
        {
            if (type is INamedTypeSymbol named && named.IsGenericType && named.TypeArguments.Length == 1)
            {
                if (named.Name is "List" or "ICollection" or "IEnumerable" or "IList" or "IReadOnlyList" or "IReadOnlyCollection")
                    return named.TypeArguments[0];
            }
            return type;
        }

        private static string BuildFieldAssignment(
            (string FieldName, string EntityTypeName, string ColumnName) fm,
            INamedTypeSymbol modelType,
            INamedTypeSymbol? entityType,
            string sourceVar,
            string targetVar)
        {
            var modelProp = modelType.GetMembers().OfType<IPropertySymbol>()
                .FirstOrDefault(p => string.Equals(p.Name, fm.FieldName, System.StringComparison.Ordinal));
            var entityProp = entityType?.GetMembers().OfType<IPropertySymbol>()
                .FirstOrDefault(p => string.Equals(p.Name, fm.ColumnName, System.StringComparison.Ordinal));

            if (modelProp is null || entityProp is null)
            {
                return $"// Mapping missing for fields: {fm.FieldName} -> {fm.ColumnName}";
            }

            var sourceType = entityProp.Type;
            var targetType = modelProp.Type;

            // Handle Enums between different namespaces (e.g., Database.Entity.X vs Domain.Model.X)
            var targetUnderlying = (targetType as INamedTypeSymbol)?.OriginalDefinition.SpecialType == SpecialType.System_Nullable_T
                ? (targetType as INamedTypeSymbol).TypeArguments[0]
                : targetType;

            if (targetUnderlying.TypeKind == TypeKind.Enum)
            {
                var targetTypeName = targetType.ToDisplayString(SymbolDisplayFormat.FullyQualifiedFormat)
                                               .Replace("global::", "");
                
                bool isTargetNullable = targetType.NullableAnnotation == NullableAnnotation.Annotated || 
                                       targetType.OriginalDefinition.SpecialType == SpecialType.System_Nullable_T;

                if (isTargetNullable)
                {
                    return $"{targetVar}.{modelProp.Name} = {sourceVar}.{entityProp.Name} is null ? null : ({targetTypeName}){sourceVar}.{entityProp.Name};";
                }
                
                return $"{targetVar}.{modelProp.Name} = ({targetTypeName}){sourceVar}.{entityProp.Name};";
            }

            // Fallback string conversion for Guid/Guid? or any primitive type mapping to a string property
            if (targetType.SpecialType == SpecialType.System_String && sourceType.SpecialType != SpecialType.System_String)
            {
                bool isSourceNullable = sourceType.NullableAnnotation == NullableAnnotation.Annotated || 
                                        sourceType.OriginalDefinition.SpecialType == SpecialType.System_Nullable_T;

                if (isSourceNullable)
                {
                    return $"{targetVar}.{modelProp.Name} = {sourceVar}.{entityProp.Name}?.ToString();";
                }
                return $"{targetVar}.{modelProp.Name} = {sourceVar}.{entityProp.Name}.ToString();";
            }

            // Default direct assignment
            return $"{targetVar}.{modelProp.Name} = {sourceVar}.{entityProp.Name};";
        }

        private static string ToCamel(string value)
        {
            if (string.IsNullOrEmpty(value)) return value;
            return char.ToLowerInvariant(value[0]) + value.Substring(1);
        }
    }
