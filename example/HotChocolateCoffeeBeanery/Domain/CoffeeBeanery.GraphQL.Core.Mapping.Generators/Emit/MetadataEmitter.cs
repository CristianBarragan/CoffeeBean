    private static void EmitEntitySchemaArray(
        StringBuilder sb,
        List<Microsoft.CodeAnalysis.INamedTypeSymbol> entityTypes,
        Dictionary<string, string> entitySchemaLookup,
        List<MappingClassInfo> models)
    {
        sb.AppendLine($"        /// <summary>Indexed by StorageEntityId.*</summary>");
        sb.AppendLine($"        public static readonly string[] EntitySchema = new string[{entityTypes.Count}]");
        sb.AppendLine("        {");
        foreach (var e in entityTypes)
        {
            // Look up schema from mappings that reference this entity
            var schema = entitySchemaLookup.TryGetValue(e.Name, out var s) ? s : "";

            // Also check if any model's ModelToEntity links reference this entity with a schema
            if (string.IsNullOrEmpty(schema))
            {
                foreach (var m in models)
                {
                    var link = m.ModelToEntity.FirstOrDefault(l =>
                        string.Equals(l.EntityType?.Name, e.Name, System.StringComparison.Ordinal));
                    if (link is not null && !string.IsNullOrEmpty(m.Schema))
                    {
                        schema = m.Schema;
                        break;
                    }
                }
            }

            sb.AppendLine($"            \"{schema}\",");
        }
        sb.AppendLine("        };");
        sb.AppendLine();
    }

    private static void EmitEntityTableArray(
        StringBuilder sb,
        List<Microsoft.CodeAnalysis.INamedTypeSymbol> entityTypes)
    {
        sb.AppendLine($"        /// <summary>Indexed by StorageEntityId.*</summary>");
        sb.AppendLine($"        public static readonly string[] EntityTable = new string[{entityTypes.Count}]");
        sb.AppendLine("        {");
        foreach (var e in entityTypes)
            sb.AppendLine($"            \"{e.Name}\",");
        sb.AppendLine("        };");
        sb.AppendLine();
    }

    private static void EmitEntityColumnNameArray(
        StringBuilder sb,
        List<Microsoft.CodeAnalysis.INamedTypeSymbol> entityTypes)
    {
        sb.AppendLine($"        /// <summary>Indexed by StorageEntityId.* then ColumnId.{{EntityName}}.*</summary>");
        sb.AppendLine($"        public static readonly string[][] EntityColumnName = new string[{entityTypes.Count}][]");
        sb.AppendLine("        {");
        foreach (var e in entityTypes)
        {
            var cols = IdEmitter.GetScalarProperties(e);
            sb.AppendLine($"            new string[{cols.Count}]");
            sb.AppendLine("            {");
            foreach (var c in cols)
                sb.AppendLine($"                \"{c.Name}\",");
            sb.AppendLine("            },");
        }
        sb.AppendLine("        };");
        sb.AppendLine();
    }

