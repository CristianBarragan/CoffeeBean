using System.Collections.Generic;
using System.Collections.Immutable;
using System.Linq;
using System.Text;
using CoffeeBeanery.GraphQL.Core.Mapping.Generators.Emit;
using CoffeeBeanery.GraphQL.Core.Mapping.Generators.Model;
using CoffeeBeanery.GraphQL.Core.Mapping.Generators.Passes;
using Microsoft.CodeAnalysis;

internal static class MetadataEmitter
{
    public static string Emit(
        ImmutableArray<MappingClassInfo> allMappings,
        ImmutableHashSet<INamedTypeSymbol> rootEntityTypes,
        ImmutableDictionary<(INamedTypeSymbol, string), string> fluentInverseNav)
    {
        var models = allMappings
            .Where(m => m.IsModel)
            .OrderBy(m => m.ModelType.Name)
            .ToList();

        // Populate CteUpdateMeta before any emit — required for Table, ColumnName, CteResolutions
        foreach (var m in models)
        {
            if (m.CteUpdateMeta.Count > 0) continue;

            var navResult = EntityNavigationConvention.ResolveQuietly(
                m, rootEntityTypes, fluentInverseNav);

            PopulateCteUpdateMeta(m, navResult);
        }

        // All unique storage entity types — same logic as IdEmitter
        var entityTypes = allMappings
            .SelectMany(m =>
            {
                var types = new List<Microsoft.CodeAnalysis.INamedTypeSymbol>();
                if (m.EntityType is not null) types.Add(m.EntityType);
                foreach (var link in m.ModelToEntity)
                    if (link.EntityType is not null) types.Add(link.EntityType);
                return types;
            })
            .GroupBy(e => e.Name, System.StringComparer.Ordinal)
            .Select(g => g.First())
            .OrderBy(e => e.Name, System.StringComparer.Ordinal)
            .ToList();

        // Build a schema lookup: entityTypeName → schema
        // Derived from mappings that have a matching EntityType
        var entitySchemaLookup = allMappings
            .Where(m => m.EntityType is not null && !string.IsNullOrEmpty(m.Schema))
            .GroupBy(m => m.EntityType!.Name, System.StringComparer.Ordinal)
            .ToDictionary(g => g.Key, g => g.First().Schema, System.StringComparer.Ordinal);

        var sb = new StringBuilder();
        sb.AppendLine("// <auto-generated/>");
        sb.AppendLine("#nullable enable");
        sb.AppendLine("using System;");
        sb.AppendLine();
        sb.AppendLine("namespace CoffeeBeanery.GraphQL.Core.Runtime");
        sb.AppendLine("{");
        sb.AppendLine("    public static class EntityMeta");
        sb.AppendLine("    {");

        EmitModelNameArray(sb, models);
        EmitTableArray(sb, models);
        EmitSchemaArray(sb, models);
        EmitColumnNameArray(sb, models);
        EmitFieldNameArray(sb, models);
        EmitConflictColumnsArray(sb, models);
        EmitCteResolutionsArray(sb, models);
        EmitEntitySchemaArray(sb, entityTypes, entitySchemaLookup, models);
        EmitEntityTableArray(sb, entityTypes);
        EmitEntityColumnNameArray(sb, entityTypes);

        sb.AppendLine("    }");
        sb.AppendLine("}");
        sb.AppendLine();

        EmitStorageEntityIdConstants(sb, entityTypes);
        EmitGeneratedEntityMetaProvider(sb);
        EmitGeneratedPlannerRegistry(sb);

        return sb.ToString();
    }
    
    private static void PopulateCteUpdateMeta(
        MappingClassInfo info,
        NavigationResolutionResult navResult)
    {
        var fkNavs = navResult.Navigations
            .Where(n => !n.IsCollection && !string.IsNullOrWhiteSpace(n.ForeignKeyProperty))
            .ToList();

        if (fkNavs.Count == 0) return;

        var primaryEntry = info.ModelToEntity.FirstOrDefault(k => k.IsPrimary);
        if (primaryEntry is null || string.IsNullOrWhiteSpace(primaryEntry.ToColumn)) return;

        var aliasToNaturalKey = info.ModelToEntity
            .Where(k => k.AliasProperty != null && !string.IsNullOrWhiteSpace(k.ToColumn))
            .ToDictionary(k => k.AliasProperty!, k => k);

        foreach (var nav in fkNavs)
        {
            if (!aliasToNaturalKey.TryGetValue(nav.NavigationName, out var naturalKeyInfo))
                continue;

            if (info.CteUpdateMeta.Any(c => c.NavigationAlias == nav.NavigationName))
                continue;

            info.CteUpdateMeta.Add(new CteUpdateMetaInfo
            {
                NavigationAlias          = nav.NavigationName,
                ForeignKeyColumn         = nav.ForeignKeyProperty,
                OwningPrimaryKeyColumn   = primaryEntry.ToColumn!,
                RelatedEntityTypeName    = nav.RelatedEntityType.Name,
                RelatedSurrogateIdColumn = nav.PrincipalKeyProperty,
                RelatedNaturalKeyColumn  = naturalKeyInfo.ToColumn!
            });
        }
    }
    
    private static void EmitStorageEntityIdConstants(
        StringBuilder sb,
        List<Microsoft.CodeAnalysis.INamedTypeSymbol> entityTypes)
    {
        sb.AppendLine("namespace CoffeeBeanery.GraphQL.Core.Runtime");
        sb.AppendLine("{");
        sb.AppendLine("    public static class StorageEntityId");
        sb.AppendLine("    {");

        for (int i = 0; i < entityTypes.Count; i++)
        {
            sb.AppendLine(
                $"        public const ushort {entityTypes[i].Name} = {i};");
        }

        sb.AppendLine();
        sb.AppendLine($"        public const ushort Count = {entityTypes.Count};");

        sb.AppendLine("    }");
        sb.AppendLine("}");
        sb.AppendLine();
    }

