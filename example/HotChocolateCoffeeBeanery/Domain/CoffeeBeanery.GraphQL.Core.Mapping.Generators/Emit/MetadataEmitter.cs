    private static void EmitSchemaArray(StringBuilder sb, List<MappingClassInfo> models)
    {
        sb.AppendLine($"        public static readonly string[] Schema = new string[{models.Count}]");
        sb.AppendLine("        {");
        foreach (var m in models)
            sb.AppendLine($"            \"{m.Schema ?? ""}\",");
        sb.AppendLine("        };");
        sb.AppendLine();
    }

    private static void EmitModelNameArray(StringBuilder sb, List<MappingClassInfo> models)
    {
        sb.AppendLine($"        public static readonly string[][] ModelName = new string[{models.Count}][]");
        sb.AppendLine("        {");

        foreach (var m in models)
        {
            var navAliases = m.CteUpdateMeta
                .Select(c => c.NavigationAlias)
                .Distinct()
                .ToList();

            if (navAliases.Count == 0)
                sb.AppendLine($"            new string[] {{ \"{m.ModelType.Name}\" }},");
            else
                sb.AppendLine($"            new string[] {{ \"{m.ModelType.Name}\", {string.Join(", ", navAliases.Select(a => $"\"{a}\""))} }},");
        }

        sb.AppendLine("        };");
        sb.AppendLine();
    }

    private static void EmitTableArray(StringBuilder sb, List<MappingClassInfo> models)
    {
        sb.AppendLine($"        public static readonly string[][] Table = new string[{models.Count}][]");
        sb.AppendLine("        {");

        foreach (var m in models)
        {
            string dbTable;
            if (IsComposite(m))
            {
                var primaryEntity = m.ModelToEntity.FirstOrDefault(k => k.IsPrimary);
                dbTable = primaryEntity?.EntityType.Name ?? m.ModelType.Name;
            }
            else
            {
                dbTable = m.EntityType?.Name ?? m.ModelType.Name;
            }

            var navAliases = m.CteUpdateMeta
                .Select(c => c.NavigationAlias)
                .Distinct()
                .ToList();

            if (navAliases.Count == 0)
                sb.AppendLine($"            new string[] {{ \"{dbTable}\" }},");
            else
                sb.AppendLine($"            new string[] {{ \"{dbTable}\", {string.Join(", ", navAliases.Select(a => $"\"{a}\""))} }},");
        }

        sb.AppendLine("        };");
        sb.AppendLine();
    }

    private static void EmitColumnNameArray(StringBuilder sb, List<MappingClassInfo> models)
    {
        sb.AppendLine($"        public static readonly string[][] ColumnName = new string[{models.Count}][]");
        sb.AppendLine("        {");

        foreach (var m in models)
        {
            INamedTypeSymbol typeForColumns;

            if (IsComposite(m))
            {
                var primaryEntity = m.ModelToEntity.FirstOrDefault(k => k.IsPrimary);
                typeForColumns = primaryEntity?.EntityType ?? m.ModelType;
            }
            else
            {
                typeForColumns = m.EntityType ?? m.ModelType;
            }

            var cols = IdEmitter.GetScalarProperties(typeForColumns);
            sb.AppendLine($"            new string[{cols.Count}]");
            sb.AppendLine("            {");
            foreach (var c in cols)
                sb.AppendLine($"                \"{c.Name}\",");
            sb.AppendLine("            },");
        }

        sb.AppendLine("        };");
        sb.AppendLine();
    }

    private static bool IsComposite(MappingClassInfo info) =>
        info.ModelToEntity
            .Select(k => k.EntityType.Name)
            .Distinct(System.StringComparer.Ordinal)
            .Count() > 1;

    private static void EmitFieldNameArray(StringBuilder sb, List<MappingClassInfo> models)
    {
        sb.AppendLine($"        public static readonly string[][] FieldName = new string[{models.Count}][]");
        sb.AppendLine("        {");
        foreach (var m in models)
        {
            var cols = IdEmitter.GetScalarProperties(m.ModelType);
            sb.AppendLine($"            new string[{cols.Count}]");
            sb.AppendLine("            {");
            foreach (var c in cols)
            {
                var camel = char.ToLowerInvariant(c.Name[0]) + c.Name.Substring(1);
                sb.AppendLine($"                \"{camel}\",");
            }
            sb.AppendLine("            },");
        }
        sb.AppendLine("        };");
        sb.AppendLine();
    }

    private static void EmitConflictColumnsArray(StringBuilder sb, List<MappingClassInfo> models)
    {
        sb.AppendLine($"        public static readonly string[][] ConflictColumns = new string[{models.Count}][]");
        sb.AppendLine("        {");
        foreach (var m in models)
        {
            var keys = m.UpsertKeys
                .Where(k => !string.IsNullOrWhiteSpace(k.Key))
                .Select(k => k.Key)
                .Distinct(System.StringComparer.OrdinalIgnoreCase)
                .ToList();

            if (keys.Count == 0)
            {
                keys = m.ModelToEntity
                    .Where(k => k.IsPrimary && !string.IsNullOrWhiteSpace(k.ToColumn))
                    .Select(k => k.ToColumn!)
                    .Distinct(System.StringComparer.OrdinalIgnoreCase)
                    .ToList();
            }

            if (keys.Count == 0)
                sb.AppendLine("            System.Array.Empty<string>(),");
            else
                sb.AppendLine($"            new string[] {{ {string.Join(", ", keys.Select(p => $"\"{p}\""))} }},");
        }
        sb.AppendLine("        };");
        sb.AppendLine();
    }

    private static void EmitCteResolutionsArray(StringBuilder sb, List<MappingClassInfo> models)
    {
        sb.AppendLine($"        public static readonly global::CoffeeBeanery.GraphQL.Core.Runtime.CteResolutionSpec[][] CteResolutions = new global::CoffeeBeanery.GraphQL.Core.Runtime.CteResolutionSpec[{models.Count}][]");
        sb.AppendLine("        {");
        foreach (var m in models)
        {
            if (m.CteUpdateMeta.Count == 0)
            {
                sb.AppendLine("            System.Array.Empty<global::CoffeeBeanery.GraphQL.Core.Runtime.CteResolutionSpec>(),");
                continue;
            }

            var entityCols = IdEmitter.GetScalarProperties(m.EntityType ?? m.ModelType)
                .Select((c, i) => (c.Name, Index: (ushort)i))
                .ToDictionary(x => x.Name, x => x.Index, System.StringComparer.OrdinalIgnoreCase);

            sb.AppendLine("            new global::CoffeeBeanery.GraphQL.Core.Runtime.CteResolutionSpec[]");
            sb.AppendLine("            {");
            foreach (var cte in m.CteUpdateMeta)
            {
                entityCols.TryGetValue(cte.OwningPrimaryKeyColumn, out var pkFieldId);
                var tableAlias = cte.NavigationAlias + cte.RelatedEntityTypeName;
                sb.AppendLine("                new global::CoffeeBeanery.GraphQL.Core.Runtime.CteResolutionSpec(");
                sb.AppendLine($"                    \"{cte.NavigationAlias}\",");
                sb.AppendLine($"                    \"{cte.ForeignKeyColumn}\",");
                sb.AppendLine($"                    \"{cte.OwningPrimaryKeyColumn}\",");
                sb.AppendLine($"                    {pkFieldId},");
                sb.AppendLine($"                    \"{tableAlias}\",");
                sb.AppendLine($"                    \"{cte.RelatedSurrogateIdColumn}\",");
                sb.AppendLine($"                    \"{cte.RelatedNaturalKeyColumn}\"");
                sb.AppendLine("                ),");
            }
            sb.AppendLine("            },");
        }
        sb.AppendLine("        };");
        sb.AppendLine();
    }

