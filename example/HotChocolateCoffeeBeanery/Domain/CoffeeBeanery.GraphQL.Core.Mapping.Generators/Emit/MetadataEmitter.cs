    private static void EmitGeneratedEntityMetaProvider(StringBuilder sb)
    {
        sb.AppendLine("namespace CoffeeBeanery.GraphQL.Core.Runtime");
        sb.AppendLine("{");
        sb.AppendLine("    public sealed class GeneratedEntityMetaProvider : global::CoffeeBeanery.GraphQL.Core.Runtime.IEntityMetaProvider");
        sb.AppendLine("    {");
        sb.AppendLine("        public int Count               => EntityMeta.Table.Length;");
        sb.AppendLine("        public string[][] ModelName    => EntityMeta.ModelName;");
        sb.AppendLine("        public string[][] Table        => EntityMeta.Table;");
        sb.AppendLine("        public string[] Schema         => EntityMeta.Schema;");
        sb.AppendLine("        public string[][] ColumnName   => EntityMeta.ColumnName;");
        sb.AppendLine("        public string[][] FieldName    => EntityMeta.FieldName;");
        sb.AppendLine("        public string[][] ConflictColumns   => EntityMeta.ConflictColumns;");
        sb.AppendLine("        public CteResolutionSpec[][] CteResolutions => EntityMeta.CteResolutions;");
        sb.AppendLine("        public int StorageEntityCount          => EntityMeta.EntityTable.Length;");
        sb.AppendLine("        public string[] EntitySchema           => EntityMeta.EntitySchema;");
        sb.AppendLine("        public string[] EntityTable            => EntityMeta.EntityTable;");
        sb.AppendLine("        public string[][] EntityColumnName     => EntityMeta.EntityColumnName;");
        sb.AppendLine();
        sb.AppendLine("        public bool TryGetEntityId(string modelName, out ushort entityId)");
        sb.AppendLine("        {");
        sb.AppendLine("            for (ushort i = 0; i < EntityMeta.Table.Length; i++)");
        sb.AppendLine("            {");
        sb.AppendLine("                if (global::System.StringComparer.OrdinalIgnoreCase.Equals(EntityMeta.Table[i][0], modelName))");
        sb.AppendLine("                {");
        sb.AppendLine("                    entityId = i;");
        sb.AppendLine("                    return true;");
        sb.AppendLine("                }");
        sb.AppendLine("            }");
        sb.AppendLine("            entityId = 0;");
        sb.AppendLine("            return false;");
        sb.AppendLine("        }");
        sb.AppendLine("    }");
        sb.AppendLine("}");
        sb.AppendLine();
    }

