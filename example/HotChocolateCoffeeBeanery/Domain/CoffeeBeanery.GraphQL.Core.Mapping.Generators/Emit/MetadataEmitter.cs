using System.Collections.Generic;
using System.Collections.Immutable;
using System.Linq;
using System.Text;
using CoffeeBeanery.GraphQL.Core.Mapping.Generators.Emit;
using CoffeeBeanery.GraphQL.Core.Mapping.Generators.Model;

internal static class MetadataEmitter
{
    public static string Emit(ImmutableArray<MappingClassInfo> allMappings)
    {
        var models = allMappings
            .Where(m => m.IsModel)
            .OrderBy(m => m.ModelType.Name)
            .ToList();

        var sb = new StringBuilder();

        sb.AppendLine("// <auto-generated/>");
        sb.AppendLine("#nullable enable");
        sb.AppendLine("using System;");
        sb.AppendLine();
        sb.AppendLine("namespace CoffeeBeanery.GraphQL.Core.Runtime");
        sb.AppendLine("{");
        sb.AppendLine("    public static class EntityMeta");
        sb.AppendLine("    {");

        EmitSchemaArray(sb, models);
        EmitTableArray(sb, models);
        EmitColumnNameArray(sb, models);
        EmitFieldNameArray(sb, models);

        sb.AppendLine("    }");
        sb.AppendLine("}");
        sb.AppendLine();

        EmitGeneratedEntityMetaProvider(sb);
        EmitGeneratedPlannerRegistry(sb);

        return sb.ToString();
    }

    // ---------------------------------------------------------------
    // EntityMeta arrays
    // ---------------------------------------------------------------

    private static void EmitSchemaArray(StringBuilder sb, List<MappingClassInfo> models)
    {
        sb.AppendLine($"        public static readonly string[] Schema = new string[{models.Count}]");
        sb.AppendLine("        {");
        foreach (var m in models)
            sb.AppendLine($"            \"{m.Schema ?? "public"}\",");
        sb.AppendLine("        };");
        sb.AppendLine();
    }

    private static void EmitTableArray(StringBuilder sb, List<MappingClassInfo> models)
    {
        sb.AppendLine($"        public static readonly string[] Table = new string[{models.Count}]");
        sb.AppendLine("        {");
        foreach (var m in models)
            sb.AppendLine($"            \"{m.ModelType.Name}\",");
        sb.AppendLine("        };");
        sb.AppendLine();
    }

    private static void EmitColumnNameArray(StringBuilder sb, List<MappingClassInfo> models)
    {
        sb.AppendLine($"        public static readonly string[][] ColumnName = new string[{models.Count}][]");
        sb.AppendLine("        {");
        foreach (var m in models)
        {
            var cols = IdEmitter.GetScalarProperties(m.EntityType ?? m.ModelType);
            sb.AppendLine($"            new string[{cols.Count}]");
            sb.AppendLine("            {");
            foreach (var c in cols)
                sb.AppendLine($"                \"{c.Name}\",");
            sb.AppendLine("            },");
        }
        sb.AppendLine("        };");
        sb.AppendLine();
    }

    private static void EmitFieldNameArray(StringBuilder sb, List<MappingClassInfo> models)
    {
        sb.AppendLine($"        public static readonly string[][] FieldName = new string[{models.Count}][]");
        sb.AppendLine("        {");
        foreach (var m in models)
        {
            var cols = IdEmitter.GetScalarProperties(m.ModelType);
            sb.AppendLine($"            new string[{cols.Count}]");
            sb.AppendLine("            {");
            foreach (var c in cols)
            {
                var camel = char.ToLowerInvariant(c.Name[0]) + c.Name.Substring(1);
                sb.AppendLine($"                \"{camel}\",");
            }
            sb.AppendLine("            },");
        }
        sb.AppendLine("        };");
        sb.AppendLine();
    }

    // ---------------------------------------------------------------
    // GeneratedEntityMetaProvider
    // ---------------------------------------------------------------

    private static void EmitGeneratedEntityMetaProvider(StringBuilder sb)
    {
        sb.AppendLine("namespace CoffeeBeanery.GraphQL.Core.Runtime");
        sb.AppendLine("{");
        sb.AppendLine("    public sealed class GeneratedEntityMetaProvider : global::CoffeeBeanery.GraphQL.Core.Runtime.IEntityMetaProvider");
        sb.AppendLine("    {");
        sb.AppendLine("        public int Count        => EntityMeta.Table.Length;");
        sb.AppendLine("        public string[] Table   => EntityMeta.Table;");
        sb.AppendLine("        public string[] Schema  => EntityMeta.Schema;");
        sb.AppendLine("        public string[][] ColumnName => EntityMeta.ColumnName;");
        sb.AppendLine("        public string[][] FieldName  => EntityMeta.FieldName;");
        sb.AppendLine();
        sb.AppendLine("        public bool TryGetEntityId(string modelName, out ushort entityId)");
        sb.AppendLine("        {");
        sb.AppendLine("            for (ushort i = 0; i < EntityMeta.Table.Length; i++)");
        sb.AppendLine("            {");
        sb.AppendLine("                if (global::System.StringComparer.OrdinalIgnoreCase.Equals(EntityMeta.Table[i], modelName))");
        sb.AppendLine("                {");
        sb.AppendLine("                    entityId = i;");
        sb.AppendLine("                    return true;");
        sb.AppendLine("                }");
        sb.AppendLine("            }");
        sb.AppendLine("            entityId = 0;");
        sb.AppendLine("            return false;");
        sb.AppendLine("        }");
        sb.AppendLine("    }");
        sb.AppendLine("}");
        sb.AppendLine();
    }

    // ---------------------------------------------------------------
    // GeneratedPlannerRegistry
    // ---------------------------------------------------------------

    private static void EmitGeneratedPlannerRegistry(StringBuilder sb)
    {
        sb.AppendLine("namespace CoffeeBeanery.GraphQL.Core.Runtime");
        sb.AppendLine("{");
        sb.AppendLine("    public sealed class GeneratedPlannerRegistry : global::CoffeeBeanery.GraphQL.Core.Runtime.IPlannerRegistry");
        sb.AppendLine("    {");
        sb.AppendLine("        public void Build(");
        sb.AppendLine("            ushort entityId,");
        sb.AppendLine("            in global::CoffeeBeanery.GraphQL.Core.Runtime.SelectionIR selection,");
        sb.AppendLine("            ref global::CoffeeBeanery.GraphQL.Core.Runtime.QueryPlanBuilder builder)");
        sb.AppendLine("            => PlannerRegistry.Build(entityId, selection, ref builder);");
        sb.AppendLine();
        sb.AppendLine("        public void BuildMutation(");
        sb.AppendLine("            ushort entityId,");
        sb.AppendLine("            in global::CoffeeBeanery.GraphQL.Core.Runtime.MutationIR mutation,");
        sb.AppendLine("            ref global::CoffeeBeanery.GraphQL.Core.Runtime.MutationPlanBuilder builder)");
        sb.AppendLine("            => PlannerRegistry.BuildMutation(entityId, mutation, ref builder);");
        sb.AppendLine();
        sb.AppendLine("        public bool IsValidEntity(ushort entityId)");
        sb.AppendLine("            => PlannerRegistry.IsValidEntity(entityId);");
        sb.AppendLine();
        sb.AppendLine("        public string GetEntityName(ushort entityId)");
        sb.AppendLine("            => PlannerRegistry.GetEntityName(entityId);");
        sb.AppendLine("    }");
        sb.AppendLine("}");
    }
}