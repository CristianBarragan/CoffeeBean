using System.Collections.Generic;
using System.Linq;
using System.Text;
using Microsoft.CodeAnalysis;
using Microsoft.CodeAnalysis.Text;
using CoffeeBeanery.GraphQL.Core.Mapping.Generators.Passes;

namespace CoffeeBeanery.GraphQL.Core.Mapping.Generators.Emit
{
    internal static class EntityForeignKeyAttributeEmitter
    {
        public static SourceText Emit(
            INamedTypeSymbol declaringEntityType,
            IReadOnlyList<FluentEntityNavigationConvention.DerivedForeignKey> keys)
        {
            var sb = new StringBuilder();

            sb.AppendLine("#nullable enable");
            sb.AppendLine("// <auto-generated/>");
            
            sb.AppendLine();

            sb.AppendLine(
                $"namespace {declaringEntityType.ContainingNamespace.ToDisplayString()}");

            sb.AppendLine("{");


            foreach (var key in keys)
            {
                if (!SymbolEqualityComparer.Default.Equals(
                        key.DeclaringEntityType,
                        declaringEntityType))
                {
                    continue;
                }


                var navArg = key.IsAmbiguous
                    ? $", navigationName: \"{key.NavigationName}\""
                    : string.Empty;


                sb.AppendLine(
                    $"    [global::CoffeeBeanery.GraphQL.Core.Mapping.EntityForeignKey(" +
                    $"typeof(global::{key.RelatedEntityType.ToDisplayString()}), " +
                    $"\"{key.ModelForeignKeyProperty}\", " +
                    $"\"{key.ModelPrincipalKeyProperty}\", " +
                    $"\"{key.RawForeignKeyColumn}\", " +
                    $"\"{key.RawPrincipalKeyColumn}\"" +
                    $"{navArg})]");
            }


            sb.AppendLine(
                $"    public partial class {declaringEntityType.Name}");

            sb.AppendLine("    {");
            sb.AppendLine("    }");
            sb.AppendLine("}");


            return SourceText.From(
                sb.ToString(),
                Encoding.UTF8);
        }
    }
}