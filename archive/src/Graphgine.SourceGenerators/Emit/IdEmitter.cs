namespace Graphgine.SourceGenerators.Emit;

internal static class IdEmitter
{
    public static string Emit(
        ImmutableArray<MappingClassInfo> mappings,
        List<FluentEntityNavigationConvention.EntityForeignKeyGraph.Edge> entityGraph)
    {
        var sb = new StringBuilder();

        sb.AppendLine("#nullable enable");
        sb.AppendLine("// <auto-generated/>");
        sb.AppendLine();

        sb.AppendLine("using Foundgine.Metadata;");
        sb.AppendLine();
        sb.AppendLine("namespace Foundgine");
        sb.AppendLine("{");

        EmitEntityIds(sb, mappings);
        EmitStorageEntityIds(sb, mappings);
        EmitFieldIds(sb, mappings);
        EmitColumnIds(sb, mappings, entityGraph);
        EmitMetadataRegistry(sb, mappings, entityGraph);
        EmitMetadataProvider(sb);

        sb.AppendLine("}");

        return sb.ToString();
    }

    /// <summary>
    /// Emits GeneratedMetadataProvider : IMetadataProvider, a thin instance
    /// wrapper around the static GetEntity/GetModel/GetJoin lookups above.
    /// This is the "generated code is a plug-in, not a dependency" seam:
    /// Runtime code should depend on IMetadataProvider (registered via DI
    /// as a singleton pointing at GeneratedMetadataProvider.Instance)
    /// instead of calling the static GeneratedMetadata class directly.
    /// The static class is kept as-is -- this wrapper delegates to it
    /// rather than duplicating any lookup logic, so there is still exactly
    /// one source of truth for the generated data.
    /// </summary>
    private static void EmitMetadataProvider(StringBuilder sb)
    {
        sb.AppendLine();
        sb.AppendLine("public sealed class GeneratedMetadataProvider : IMetadataProvider");
        sb.AppendLine("{");
        sb.AppendLine("    public static readonly GeneratedMetadataProvider Instance = new();");
        sb.AppendLine();
        sb.AppendLine("    public EntityMetadata GetEntity(ushort storageEntityId) => GeneratedMetadata.GetEntity(storageEntityId);");
        sb.AppendLine();
        sb.AppendLine("    public ModelMetadata GetModel(ushort modelEntityId) => GeneratedMetadata.GetModel(modelEntityId);");
        sb.AppendLine();
        sb.AppendLine("    public JoinMetadata? GetJoin(ushort fromEntityId, ushort toEntityId) => GeneratedMetadata.GetJoin(fromEntityId, toEntityId);");
        sb.AppendLine("}");
    }

    /// <summary>
    /// Builds real Foundation.Metadata.EntityMetadata/ModelMetadata instances
    /// from the same ushort ids emitted above, and registers the entity ones
    /// in a MetadataRegistry. This is what lets the planner/materializer
    /// emitters (and Graphgine (execution layer)) work with real Foundation types instead
    /// of bare ushort literals.
    /// </summary>
    private static void EmitMetadataRegistry(
        StringBuilder sb,
        ImmutableArray<MappingClassInfo> mappings,
        List<FluentEntityNavigationConvention.EntityForeignKeyGraph.Edge> entityGraph)
    {
        var distinctEntities =
            mappings
                .SelectMany(m => m.Definition.Entities)
                .Where(e => e.EntityType != null)
                .Select(e => e.EntityType!)
                .Distinct(SymbolEqualityComparer.Default)
                .Cast<INamedTypeSymbol>()
                .OrderBy(e => StripEntitySuffix(e.Name), StringComparer.Ordinal)
                .ToList();

        sb.AppendLine();
        sb.AppendLine("public static class GeneratedMetadata");
        sb.AppendLine("{");
        sb.AppendLine("    public static readonly EntityMetadata[] Entities =");
        sb.AppendLine("    {");

        foreach (var entityType in distinctEntities)
        {
            var strippedName = StripEntitySuffix(entityType.Name);

            var columns =
                GetFullColumnOrder(
                    strippedName,
                    mappings,
                    entityType,
                    entityGraph);

            sb.AppendLine("        new EntityMetadata(");
            sb.AppendLine($"            new EntityId(StorageEntityId.{strippedName}),");
            sb.AppendLine($"            \"{strippedName}\",");
            sb.AppendLine("            new ColumnMetadata[]");
            sb.AppendLine("            {");

            foreach (var column in columns)
            {
                sb.AppendLine(
                    $"                new ColumnMetadata(new ColumnId(ColumnId.{strippedName}.{column}), \"{column}\"),");
            }

            sb.AppendLine("            }),");
        }

        sb.AppendLine("    };");
        sb.AppendLine();
        sb.AppendLine("    public static EntityMetadata GetEntity(ushort storageEntityId) =>");
        sb.AppendLine($"        storageEntityId < {distinctEntities.Count} ? Entities[storageEntityId] :");
        sb.AppendLine("        throw new global::System.ArgumentOutOfRangeException(nameof(storageEntityId), storageEntityId, \"Unknown StorageEntityId.\");");

        EmitJoinGraph(sb, entityGraph, distinctEntities);
        EmitModelMetadata(sb, mappings);
        EmitGraphMetadata(sb, mappings);

        sb.AppendLine("}");
    }

    /// <summary>
    /// Emits GeneratedMetadata.GetJoin: a compile-time switch over the same
    /// foreign-key edges FluentEntityNavigationConvention already resolved.
    /// No graph object is built at startup -- this is what a generic
    /// (hand-written, not generated) selection-to-QueryNode builder would
    /// call instead of the per-model walking code PlannerEmitter currently
    /// generates.
    /// </summary>
    private static void EmitJoinGraph(
        StringBuilder sb,
        List<FluentEntityNavigationConvention.EntityForeignKeyGraph.Edge> entityGraph,
        List<INamedTypeSymbol> distinctEntities)
    {
        sb.AppendLine();
        sb.AppendLine("    public static JoinMetadata? GetJoin(ushort fromEntityId, ushort toEntityId) =>");
        sb.AppendLine("        (fromEntityId, toEntityId) switch");
        sb.AppendLine("        {");

        var entityIds = new Dictionary<string, ushort>(StringComparer.Ordinal);
        for (var i = 0; i < distinctEntities.Count; i++)
        {
            entityIds[StripEntitySuffix(distinctEntities[i].Name)] = (ushort)i;
        }

        var emittedPatterns = new HashSet<(ushort From, ushort To)>();

        foreach (var edge in entityGraph)
        {
            var dependent = StripEntitySuffix(edge.DependentEntity.Name);
            var principal = StripEntitySuffix(edge.PrincipalEntity.Name);
            var dependentId = entityIds[dependent];
            var principalId = entityIds[principal];

            if (emittedPatterns.Add((dependentId, principalId)))
            {
                EmitJoinCase(sb, dependent, principal, edge.DependentColumn, edge.PrincipalColumn, forward: true);
            }

            if (emittedPatterns.Add((principalId, dependentId)))
            {
                EmitJoinCase(sb, dependent, principal, edge.DependentColumn, edge.PrincipalColumn, forward: false);
            }
        }

        sb.AppendLine("            _ => null,");
        sb.AppendLine("        };");
    }

    private static void EmitJoinCase(
        StringBuilder sb,
        string dependent,
        string principal,
        string dependentColumn,
        string principalColumn,
        bool forward)
    {
        var (fromEntity, toEntity, fromColumn, fromEntityRef, toColumn, toEntityRef) = forward
            ? (dependent, principal, dependentColumn, dependent, principalColumn, principal)
            : (principal, dependent, principalColumn, principal, dependentColumn, dependent);

        sb.AppendLine(
            $"            (StorageEntityId.{fromEntity}, StorageEntityId.{toEntity}) => new JoinMetadata(");
        sb.AppendLine("                new JoinCondition(");
        sb.AppendLine(
            $"                    new ColumnReference(GetEntity(StorageEntityId.{fromEntityRef}), ColumnId.{fromEntityRef}.{fromColumn}),");
        sb.AppendLine(
            $"                    new ColumnReference(GetEntity(StorageEntityId.{toEntityRef}), ColumnId.{toEntityRef}.{toColumn})),");
        sb.AppendLine("                JoinKind.Left),");
    }

    private static void EmitModelEntityChain(
        StringBuilder sb,
        MappingClassInfo mapping)
    {
        var entities = mapping.ModelToEntity;

        var primary = entities.FirstOrDefault(e => e.IsPrimary) ?? entities.FirstOrDefault();
        var primaryName = primary?.EntityType is { } primaryType ? StripEntitySuffix(primaryType.Name) : "";

        sb.AppendLine("        new ModelEntityBinding[]");
        sb.AppendLine("        {");

        foreach (var entity in entities)
        {
            if (entity.EntityType is null)
                continue;

            var name = StripEntitySuffix(entity.EntityType.Name);

            if (entity.IsPrimary)
            {
                sb.AppendLine($"            new ModelEntityBinding(GetEntity(StorageEntityId.{name}), null),");
                continue;
            }

            var parentName = entity.JoinParentEntity is { } parentType
                ? StripEntitySuffix(parentType.Name)
                : primaryName;

            var fromColumn = string.IsNullOrEmpty(entity.FromColumn) ? "Id" : entity.FromColumn;
            var toColumn = string.IsNullOrEmpty(entity.ToColumn) ? "Id" : entity.ToColumn;

            sb.AppendLine($"            new ModelEntityBinding(GetEntity(StorageEntityId.{name}), new JoinCondition(");
            sb.AppendLine($"                new ColumnReference(GetEntity(StorageEntityId.{name}), ColumnId.{name}.{fromColumn}),");
            sb.AppendLine($"                new ColumnReference(GetEntity(StorageEntityId.{parentName}), ColumnId.{parentName}.{toColumn}))),");
        }

        sb.AppendLine("        },");
    }

    private static void EmitGraphMetadata(
        StringBuilder sb,
        ImmutableArray<MappingClassInfo> mappings)
    {
        var graphMappings =
            mappings
                .Where(m => m.Graph != null && !string.IsNullOrWhiteSpace(m.Graph!.GraphName) && m.EntityType != null)
                .OrderBy(m => m.ModelType?.Name ?? "", StringComparer.Ordinal)
                .ToList();

        if (graphMappings.Count == 0)
            return;

        sb.AppendLine();

        ushort graphId = 0;

        foreach (var mapping in graphMappings)
        {
            var modelName = mapping.ModelType?.Name ?? "Unknown";
            var edgeEntity = StripEntitySuffix(mapping.EntityType!.Name);
            var graph = mapping.Graph!;

            var fromLabel = graph.From?.Label ?? "";
            var toLabel = graph.To?.Label ?? "";
            var fromAlias = string.IsNullOrEmpty(graph.From?.Alias) ? fromLabel : graph.From!.Alias!;
            var toAlias = string.IsNullOrEmpty(graph.To?.Alias) ? toLabel : graph.To!.Alias!;
            var fromConnectedEntity = StripEntitySuffix(fromLabel);
            var toConnectedEntity = StripEntitySuffix(toLabel);

            sb.AppendLine($"    public static readonly GraphMetadata {modelName}Graph = new GraphMetadata(");
            sb.AppendLine($"        new GraphId({graphId}),");
            sb.AppendLine($"        \"{graph.GraphName}\",");
            sb.AppendLine($"        \"{graph.EdgeLabel}\",");
            sb.AppendLine($"        \"{graph.EdgeKey}\",");
            sb.AppendLine($"        GetEntity(StorageEntityId.{edgeEntity}),");
            sb.AppendLine($"        new VertexMetadata(\"{fromLabel}\", \"{graph.From?.GraphProperty}\", \"{graph.FromJoinColumn}\", \"{fromAlias}\", GetEntity(StorageEntityId.{fromConnectedEntity})),");
            sb.AppendLine($"        new VertexMetadata(\"{toLabel}\", \"{graph.To?.GraphProperty}\", \"{graph.ToJoinColumn}\", \"{toAlias}\", GetEntity(StorageEntityId.{toConnectedEntity})));");
            sb.AppendLine();

            graphId++;
        }
    }

    private static void EmitModelMetadata(
        StringBuilder sb,
        ImmutableArray<MappingClassInfo> mappings)
    {
        foreach (var mapping in mappings
                     .Where(x => x.ModelType != null)
                     .OrderBy(x => x.ModelType!.Name))
        {
            var modelName = mapping.ModelType!.Name;
            var fieldNames = GetResolvedFieldNames(mapping);

            sb.AppendLine();
            var typeByName = GetScalarProperties(mapping.ModelType!)
                .GroupBy(p => p.Name, StringComparer.Ordinal)
                .ToDictionary(g => g.Key, g => g.First().Type, StringComparer.Ordinal);

            // SourceName -> (stripped storage entity, column name), so each
            // field can carry a real ColumnId, not just a name. Fields with
            // no entry here (e.g. nested-entity/navigation fields like
            // Customer.Product) simply get ColumnId: null.
            var columnByFieldName =
                mapping.FieldMaps
                    .Where(f => !string.IsNullOrEmpty(f.DestinationEntity))
                    .GroupBy(f => f.SourceName, StringComparer.Ordinal)
                    .ToDictionary(
                        g => g.Key,
                        g => g.First(),
                        StringComparer.Ordinal);

            sb.AppendLine(
                $"    public static readonly ModelMetadata {modelName} = new ModelMetadata(");
            sb.AppendLine($"        new ModelId(EntityId.{modelName}),");
            sb.AppendLine($"        \"{modelName}\",");
            sb.AppendLine($"        typeof(global::{mapping.ModelType!.ToDisplayString()}),");
            sb.AppendLine("        new FieldMetadata[]");
            sb.AppendLine("        {");

            foreach (var fieldName in fieldNames)
            {
                var clrType =
                    typeByName.TryGetValue(fieldName, out var symbol)
                        ? $"typeof(global::{symbol.ToDisplayString()})"
                        : "typeof(object)";

                string columnIdArg;

                if (columnByFieldName.TryGetValue(fieldName, out var fieldMap))
                {
                    var destEntity = StripEntitySuffix(fieldMap.DestinationEntity);
                    var destColumn = fieldMap.DestinationColumn ?? fieldMap.DestinationName;
                    columnIdArg = $", new ColumnReference(GetEntity(StorageEntityId.{destEntity}), ColumnId.{destEntity}.{destColumn})";
                }
                else
                {
                    columnIdArg = "";
                }

                sb.AppendLine(
                    $"            new FieldMetadata(new FieldId(FieldId.{modelName}.{fieldName}), \"{fieldName}\", {clrType}{columnIdArg}),");
            }

            sb.AppendLine("        },");
            EmitModelEntityChain(sb, mapping);

            var primaryEntity =
                mapping.ModelToEntity.FirstOrDefault(e => e.IsPrimary)
                ?? mapping.ModelToEntity.FirstOrDefault();

            if (primaryEntity?.EntityType != null &&
                !string.IsNullOrWhiteSpace(primaryEntity.EntityKey))
            {
                var primaryStorageName =
                    StripEntitySuffix(primaryEntity.EntityType.Name);

                sb.AppendLine(
                    $"        new ColumnReference(GetEntity(StorageEntityId.{primaryStorageName}), ColumnId.{primaryStorageName}.{primaryEntity.EntityKey}));");
            }
            else
            {
                // No IsPrimary entity, or its EntityKey wasn't declared --
                // leave PrimaryKey null rather than guess. Anything that
                // needs it (currently: keyset pagination) must handle a
                // null PrimaryKey explicitly rather than assume every
                // model has one.
                sb.AppendLine("        null);");
            }
        }

        var modelNames =
            mappings
                .Where(x => x.ModelType != null)
                .Select(x => x.ModelType!.Name)
                .OrderBy(n => n, StringComparer.Ordinal)
                .ToList();

        sb.AppendLine();
        sb.AppendLine("    public static readonly ModelMetadata[] Models =");
        sb.AppendLine("    {");

        foreach (var modelName in modelNames)
        {
            sb.AppendLine($"        {modelName},");
        }

        sb.AppendLine("    };");

        sb.AppendLine();
        sb.AppendLine(
            "    public static ModelMetadata GetModel(ushort modelEntityId)");
        sb.AppendLine(
            "    {");
        sb.AppendLine(
            "        foreach (var model in Models)");
        sb.AppendLine(
            "        {");
        sb.AppendLine(
            "            if (model.Id.Value == modelEntityId)");
        sb.AppendLine(
            "                return model;");
        sb.AppendLine(
            "        }");
        sb.AppendLine();
        sb.AppendLine(
            "        throw new global::System.ArgumentOutOfRangeException(nameof(modelEntityId), modelEntityId, \"No ModelMetadata for this EntityId.\");");
        sb.AppendLine(
            "    }");
    }
    
    internal static ushort GetFieldId(
        MappingClassInfo mapping,
        string fieldName)
    {
        var fields =
            GetResolvedFieldNames(mapping);

        for (ushort i = 0; i < fields.Count; i++)
        {
            if (string.Equals(
                    fields[(int)i],
                    fieldName,
                    StringComparison.OrdinalIgnoreCase))
            {
                return i;
            }
        }

        throw new InvalidOperationException(
            $"Unable to resolve FieldId for '{fieldName}' on '{mapping.ModelType?.Name}'.");
    }
    
    internal static ushort GetColumnId(
        ImmutableArray<MappingClassInfo> mappings,
        INamedTypeSymbol entityType,
        List<FluentEntityNavigationConvention.EntityForeignKeyGraph.Edge> entityGraph,
        string columnName)
    {
        var columns =
            GetFullColumnOrder(
                StripEntitySuffix(entityType.Name),
                mappings,
                entityType,
                entityGraph);

        for (ushort i = 0; i < columns.Count; i++)
        {
            if (string.Equals(
                    columns[(int)i],
                    columnName,
                    StringComparison.OrdinalIgnoreCase))
            {
                return i;
            }
        }

        throw new InvalidOperationException(
            $"Unable to resolve ColumnId for '{columnName}' on '{entityType.Name}'.");
    }

    public static string StripEntitySuffix(string entityTypeName)
    {
        const string suffix = "Entity";

        return entityTypeName.EndsWith(
            suffix,
            StringComparison.Ordinal)
            ? entityTypeName.Substring(
                0,
                entityTypeName.Length - suffix.Length)
            : entityTypeName;
    }

    private static void EmitEntityIds(
        StringBuilder sb,
        ImmutableArray<MappingClassInfo> mappings)
    {
        var entities =
            mappings
                .Where(x => x.ModelType != null)
                .Select(x => x.ModelType!.Name)
                .Distinct(StringComparer.Ordinal)
                .OrderBy(x => x, StringComparer.Ordinal)
                .ToList();

        sb.AppendLine();
        sb.AppendLine("public static class EntityId");
        sb.AppendLine("{");

        for (ushort id = 0; id < entities.Count; id++)
        {
            sb.AppendLine(
                $"    public const ushort {entities[id]} = {id};");
        }

        sb.AppendLine("}");
    }

    internal static IReadOnlyList<IPropertySymbol> GetScalarProperties(
        INamedTypeSymbol type)
    {
        return type
            .GetMembers()
            .OfType<IPropertySymbol>()
            .Where(IsScalarProperty)
            .ToList();
    }

    internal static bool IsScalarProperty(IPropertySymbol property)
    {
        if (property.IsStatic)
            return false;

        if (property.DeclaredAccessibility != Accessibility.Public)
            return false;

        var type = property.Type;

        var namedType = type as INamedTypeSymbol;

        var underlying =
            namedType?.OriginalDefinition.SpecialType == SpecialType.System_Nullable_T
                ? namedType.TypeArguments[0]
                : type;

        if (underlying.TypeKind == TypeKind.Enum)
            return true;

        if (underlying.ToDisplayString() == "System.Guid")
            return true;

        return underlying.SpecialType switch
        {
            SpecialType.System_String => true,
            SpecialType.System_Int32 => true,
            SpecialType.System_Int64 => true,
            SpecialType.System_Double => true,
            SpecialType.System_Decimal => true,
            SpecialType.System_Boolean => true,
            SpecialType.System_DateTime => true,
            _ => false
        };
    }

    /// <summary>
    /// Returns the primary-key scalar properties for an entity — typically
    /// just the surrogate "Id" property. Used both when computing ColumnId
    /// constants and when computing the runtime EntityColumnName array, so
    /// both MUST call GetFullColumnOrder (below) rather than duplicating
    /// this insertion logic independently.
    /// </summary>
    internal static List<IPropertySymbol> GetPrimaryKeyProperties(
        INamedTypeSymbol type)
    {
        var idProp = GetScalarProperties(type)
            .FirstOrDefault(p =>
                string.Equals(p.Name, "Id", StringComparison.Ordinal));

        return idProp != null
            ? new List<IPropertySymbol> { idProp }
            : new List<IPropertySymbol>();
    }

    internal static List<string> GetOrderedColumnNames(
        string entityName,
        ImmutableArray<MappingClassInfo> mappings)
    {
        return mappings
            .SelectMany(m => m.FieldMaps)
            .Where(f => string.Equals(f.DestinationEntity, entityName, StringComparison.OrdinalIgnoreCase))
            .Select(f => f.DestinationName)
            .Distinct(StringComparer.OrdinalIgnoreCase)
            .OrderBy(n => n, StringComparer.OrdinalIgnoreCase)
            .ToList();
    }

    /// <summary>
    /// Single source of truth for an entity's full column ordering:
    /// 1. FieldMaps-derived scalar columns (alphabetical)
    /// 2. Primary key column, inserted at index 0 if not already present
    /// 3. FK columns this entity owns as the DEPENDENT side of any edge in
    ///    entityGraph, appended if not already present — these are pure
    ///    relational plumbing columns (e.g. Transaction.AccountId,
    ///    Contract.CustomerBankingRelationshipId) that are never surfaced
    ///    as a GraphQL-facing scalar field, but ARE needed as real ColumnId
    ///    constants once join emission references them directly (e.g. for
    ///    composite-entity internal join chains).
    ///
    /// EmitColumnIds (numeric ColumnId.* constants) and
    /// EmitEntityColumnNameArray (the runtime string[] indexed by those
    /// constants) MUST both call this same method — computing the ordering
    /// independently in each place is exactly what caused ColumnId
    /// constants to disagree with the runtime name array previously.
    /// </summary>
    internal static List<string> GetFullColumnOrder(
        string entityName,
        ImmutableArray<MappingClassInfo> mappings,
        INamedTypeSymbol? entityType,
        List<FluentEntityNavigationConvention.EntityForeignKeyGraph.Edge>? entityGraph = null)
    {
        var columns = GetOrderedColumnNames(entityName, mappings);

        if (entityType != null)
        {
            var primaryKeys = GetPrimaryKeyProperties(entityType)
                .Select(x => x.Name)
                .ToList();

            foreach (var pk in primaryKeys)
            {
                if (!columns.Contains(pk, StringComparer.Ordinal))
                {
                    columns.Insert(0, pk);
                }
            }

            if (entityGraph != null)
            {
                var fkColumns = entityGraph
                    .Where(e => SymbolEqualityComparer.Default.Equals(e.DependentEntity, entityType))
                    .Select(e => e.DependentColumn)
                    .Distinct(StringComparer.Ordinal);

                foreach (var fkCol in fkColumns)
                {
                    if (!columns.Contains(fkCol, StringComparer.Ordinal))
                    {
                        columns.Add(fkCol);
                    }
                }
            }
        }

        return columns;
    }

    internal static bool IsScalarProperty(
        INamedTypeSymbol type)
    {
        return GetScalarProperties(type).Count > 0;
    }

    private static void EmitStorageEntityIds(
        StringBuilder sb,
        ImmutableArray<MappingClassInfo> mappings)
    {
        var entities =
            mappings
                .SelectMany(x => x.Definition.Entities)
                .Where(x => x.EntityType != null)
                .Select(x => StripEntitySuffix(x.EntityType!.Name))
                .Distinct(StringComparer.Ordinal)
                .OrderBy(x => x, StringComparer.Ordinal)
                .ToList();

        sb.AppendLine();
        sb.AppendLine("public static class StorageEntityId");
        sb.AppendLine("{");

        for (ushort id = 0; id < entities.Count; id++)
        {
            sb.AppendLine(
                $"    public const ushort {entities[id]} = {id};");
        }

        sb.AppendLine("}");
    }

    private static void EmitFieldIds(
        StringBuilder sb,
        ImmutableArray<MappingClassInfo> mappings)
    {
        sb.AppendLine();
        sb.AppendLine("public static class FieldId");
        sb.AppendLine("{");

        foreach (var mapping in mappings
                     .Where(x => x.ModelType != null)
                     .OrderBy(x => x.ModelType!.Name))
        {
            var modelName = mapping.ModelType!.Name;

            sb.AppendLine($"    public static class {modelName}");
            sb.AppendLine("    {");

            ushort id = 0;

            foreach (var fieldName in GetResolvedFieldNames(mapping))
            {
                sb.AppendLine($"        public const ushort {fieldName} = {id};");
                id++;
            }

            sb.AppendLine("    }");
        }

        sb.AppendLine("}");
    }

    internal static IReadOnlyList<string> GetResolvedFieldNames(
        MappingClassInfo mapping)
    {
        var fields = new HashSet<string>(StringComparer.Ordinal);

        foreach (var prop in GetScalarProperties(mapping.ModelType!))
        {
            fields.Add(prop.Name);
        }

        foreach (var field in mapping.FieldMaps)
        {
            var name = FieldIdNameHelper.GetName(field);

            if (!string.IsNullOrWhiteSpace(name))
                fields.Add(name);
        }

        return fields
            .OrderBy(x => x, StringComparer.Ordinal)
            .ToList();
    }

    private static void EmitColumnIds(
        StringBuilder sb,
        ImmutableArray<MappingClassInfo> mappings,
        List<FluentEntityNavigationConvention.EntityForeignKeyGraph.Edge> entityGraph)
    {
        sb.AppendLine();
        sb.AppendLine("public static class ColumnId");
        sb.AppendLine("{");

        var distinctEntities =
            mappings
                .SelectMany(m => m.Definition.Entities)
                .Where(e => e.EntityType != null)
                .Select(e => e.EntityType!)
                .Distinct(SymbolEqualityComparer.Default)
                .Cast<INamedTypeSymbol>()
                .OrderBy(e => e.Name)
                .ToList();

        foreach (var entityType in distinctEntities)
        {
            var strippedName = StripEntitySuffix(entityType.Name);

            var columns =
                GetFullColumnOrder(
                    strippedName,
                    mappings,
                    entityType,
                    entityGraph);

            sb.AppendLine($"    public static class {strippedName}");
            sb.AppendLine("    {");

            for (ushort id = 0; id < columns.Count; id++)
            {
                sb.AppendLine($"        public const ushort {columns[(int)id]} = {id};");
            }

            sb.AppendLine("    }");
        }

        sb.AppendLine("}");
    }
