    public static string Emit(
        ImmutableArray<MappingClassInfo> mappings,
        ImmutableHashSet<INamedTypeSymbol> rootEntityTypes,
        List<FluentEntityNavigationConvention.EntityForeignKeyGraph.Edge> entityGraph)
    {
        var sb = new StringBuilder();

        sb.AppendLine("#nullable enable");
        sb.AppendLine("// <auto-generated/>");
        sb.AppendLine();
        sb.AppendLine("using System;");
        sb.AppendLine("using System.Collections.Generic;");
        sb.AppendLine("using System.Collections.Immutable;");
        sb.AppendLine();
        sb.AppendLine("using Graphgine.Execution;");
        sb.AppendLine("using Foundgine;");
        sb.AppendLine("using Foundgine.Metadata;");
        sb.AppendLine("using Foundgine.Builders;");
        sb.AppendLine();
        sb.AppendLine("namespace Graphgine.Execution;");
        sb.AppendLine();

        sb.AppendLine("public static partial class GeneratedPlanners");
        sb.AppendLine("{");
        sb.AppendLine();

        var models =
            mappings
                .Where(x => x.ModelType != null)
                .GroupBy(
                    x => x.ModelType!.Name,
                    StringComparer.OrdinalIgnoreCase)
                .Select(g => g.First())
                .OrderBy(x => x.ModelType!.Name)
                .ToList();

        foreach (var mapping in models)
        {
            EmitPlanner(
                sb,
                mapping,
                mappings,
                rootEntityTypes,
                entityGraph);

            sb.AppendLine();
        }

        EmitRegistry(sb, models);

        sb.AppendLine("}");

        return sb.ToString();
    }
    
    private static void EmitPlanner(
        StringBuilder sb,
        MappingClassInfo info,
        ImmutableArray<MappingClassInfo> allMappings,
        ImmutableHashSet<INamedTypeSymbol> rootEntityTypes,
        List<FluentEntityNavigationConvention.EntityForeignKeyGraph.Edge> entityGraph)
    {
        if (info.ModelType == null)
            return;

        var name = info.ModelType.Name;

        sb.AppendLine($"    public static class {name}Planner");
        sb.AppendLine("    {");

        EmitBuild(
            sb,
            info,
            allMappings,
            rootEntityTypes,
            entityGraph);

        sb.AppendLine();

        EmitBuildQueryNode(
            sb,
            info,
            allMappings,
            rootEntityTypes,
            entityGraph);

        sb.AppendLine("    }");
    }

    // -----------------------------------------------------------------
    // BuildQueryNode: additive, new-architecture counterpart to Build.
    // Returns a Foundation.QueryPlan.QueryNode tree instead of driving
    // QueryPlanBuilder imperatively. Nothing about the existing Build
    // method above (or its callers) changes -- this is a second, parallel
    // entry point so callers can migrate one at a time.
    //
    // Unlike Build, this does not re-derive FK/column resolution itself:
    // composite-entity scans come from GeneratedMetadata.{Model}.Entities
    // (a ready ModelEntityBinding chain -- see QueryNodeBuilder.ScanComposite),
    // and navigation/graph joins come from GeneratedMetadata.GetJoin(...),
    // both already emitted by IdEmitter from the same FK graph.
    //
    // Graph-vertex children now wire into GraphEdgeNode too (see
    // EmitChildSelectionQueryNode), matched by vertex alias-or-label
    // against each child's OutputAlias, mirroring the convention already
    // established in the old pipeline's EmitGraphVertexResultJoins.
    // -----------------------------------------------------------------
    private static void EmitBuildQueryNode(
        StringBuilder sb,
        MappingClassInfo info,
        ImmutableArray<MappingClassInfo> allMappings,
        ImmutableHashSet<INamedTypeSymbol> rootEntityTypes,
        List<FluentEntityNavigationConvention.EntityForeignKeyGraph.Edge> entityGraph)
    {
        if (info.ModelType == null || info.EntityType == null)
            return;

        var modelName = info.ModelType.Name;
        var primaryStorage = IdEmitter.StripEntitySuffix(info.EntityType.Name);

        sb.AppendLine(
            "        public static QueryNode BuildQueryNode(in SelectionIR node, bool isRoot)");
        sb.AppendLine("        {");

        sb.AppendLine(
            $"            QueryNode __plan = isRoot");
        sb.AppendLine(
            $"                ? QueryNodeBuilder.ScanComposite(GeneratedMetadata.{modelName})");
        sb.AppendLine(
            $"                : new ScanNode(GeneratedMetadata.GetEntity(StorageEntityId.{primaryStorage}));");

        EmitScalarSelectionQueryNode(
            sb,
            info,
            allMappings,
            entityGraph);

        EmitChildSelectionQueryNode(
            sb,
            info,
            allMappings,
            rootEntityTypes,
            entityGraph);

        sb.AppendLine();
        sb.AppendLine(
            $"            return new MaterializeNode(__plan, GeneratedMetadata.{modelName});");
        sb.AppendLine("        }");
    }

    private static void EmitBuild(
        StringBuilder sb,
        MappingClassInfo info,
        ImmutableArray<MappingClassInfo> allMappings,
        ImmutableHashSet<INamedTypeSymbol> rootEntityTypes,
        List<FluentEntityNavigationConvention.EntityForeignKeyGraph.Edge> entityGraph)
    {
        sb.AppendLine(
            "        public static void Build(in SelectionIR node, ref QueryPlanBuilder builder, bool isRoot)");

        sb.AppendLine("        {");

        sb.AppendLine("            if (isRoot)");
        sb.AppendLine("            {");

        var runtimeEntityId =
            ResolveRuntimeEntityId(
                info.EntityType!,
                allMappings);

        sb.AppendLine(
            "                builder.BeginCompositeChain(" +
            $"EntityId.{runtimeEntityId}, " +
            $"\"{info.ModelType!.Name}\");");
        
        if (info.CompositeStorageJoinInfo.Count > 0)
        {
            EmitCompositeStorageJoins(
                sb,
                info,
                allMappings,
                entityGraph);
        }

        sb.AppendLine("            }");

        EmitScalarSelection(
            sb,
            info,
            allMappings,
            entityGraph);

        EmitChildSelection(
            sb,
            info,
            allMappings,
            rootEntityTypes,
            entityGraph);

        sb.AppendLine("        }");
    }
    
    private static void EmitRegistryHelpers(
        StringBuilder sb,
        List<MappingClassInfo> models)
    {
        sb.AppendLine();

        sb.AppendLine(
            "    public static bool IsValidEntity(ushort entityId)");

        sb.AppendLine(
            "        => entityId < (ushort)PlannerCount;");


        sb.AppendLine();


        sb.AppendLine(
            "    public static string GetEntityName(ushort entityId)");

        sb.AppendLine(
            "    {");


        sb.AppendLine(
            "        switch (entityId)");

        sb.AppendLine(
            "        {");


        foreach (var model in models)
        {
            if (model.ModelType == null)
                continue;


            var name =
                model.ModelType.Name;


            sb.AppendLine(
                $"            case EntityId.{name}:");


            sb.AppendLine(
                $"                return \"{name}\";");
        }


        sb.AppendLine(
            "            default:");

        sb.AppendLine(
            "                ThrowUnknownEntity(entityId);");

        sb.AppendLine(
            "                return string.Empty;");


        sb.AppendLine(
            "        }");


        sb.AppendLine(
            "    }");


        sb.AppendLine();


        sb.AppendLine(
            "    private static void ThrowUnknownEntity(ushort entityId)");

        sb.AppendLine(
            "        => throw new ArgumentException($\"Unknown entity runtime ID: {entityId}\");");
    }
    
    private static void EmitChildSelection(
        StringBuilder sb,
        MappingClassInfo info,
        ImmutableArray<MappingClassInfo> allMappings,
        ImmutableHashSet<INamedTypeSymbol> rootEntityTypes,
        List<FluentEntityNavigationConvention.EntityForeignKeyGraph.Edge> entityGraph)
    {
        var navResult =
            EntityNavigationConvention.Resolve(
                info,
                allMappings,
                entityGraph,
                rootEntityTypes);


        var hasNavigations =
            navResult != null &&
            navResult.Navigations.Count > 0;


        var hasGraph =
            info.Graph != null &&
            !string.IsNullOrWhiteSpace(
                info.Graph.GraphName);


        if (!hasNavigations &&
            !hasGraph)
        {
            return;
        }


        sb.AppendLine();


        // ---------------------------------------------------------------
        // FIXED: this used to call EmitCompositeChildAttachmentJoins,
        // driven off info.AutoChildAttachments (single parent/child
        // column pair, resolved by name-matching convention). That method
        // was an unfinished stub — its `if (...) { }` block never actually
        // emitted a builder.AddJoin(...) call, so no parent-to-composite-
        // child join was EVER generated for any model. Meanwhile navResult
        // (the graph-based, multi-hop, any-source-entity join paths from
        // EntityNavigationConvention) was computed above just to check
        // hasNavigations, then discarded.
        //
        // This now actually emits real builder.AddJoin(...) calls from
        // navResult, which is the correct, FK-graph-derived source of
        // truth — not the name-matching convention.
        // ---------------------------------------------------------------
        if (hasNavigations)
        {
            EmitNavigationJoins(
                sb,
                info,
                allMappings,
                navResult!,
                entityGraph);
        }


        if (hasGraph)
        {
            EmitGraphVertexResultJoins(
                sb,
                info,
                allMappings,
                entityGraph);
        }


        sb.AppendLine(
            "            foreach (var child in node.Children)");

        sb.AppendLine(
            "            {");


        sb.AppendLine(
            "                PlannerRegistry.Build(child.EntityId, child, ref builder, isRoot: false);");


        sb.AppendLine(
            "            }");
    }

    /// <summary>
    /// BuildQueryNode counterpart to EmitChildSelection. Unlike the old
    /// method, this does NOT need a separate "walk every child" loop at
    /// the end: recursing into GeneratedPlanners.BuildQueryNode(child) for
    /// each resolved navigation already returns that child's full subtree
    /// (its own columns and further nested children included), so a
    /// single JoinNode per navigation is enough.
    ///
    /// Graph-vertex children are matched by vertex alias-or-label against
    /// each child's OutputAlias, then wrapped into one GraphEdgeNode over
    /// __plan (both sides accumulated first so a query selecting both
    /// vertices doesn't produce two separate graph joins).
    /// </summary>
    private static void EmitChildSelectionQueryNode(
        StringBuilder sb,
        MappingClassInfo info,
        ImmutableArray<MappingClassInfo> allMappings,
        ImmutableHashSet<INamedTypeSymbol> rootEntityTypes,
        List<FluentEntityNavigationConvention.EntityForeignKeyGraph.Edge> entityGraph)
    {
        var navResult =
            EntityNavigationConvention.Resolve(
                info,
                allMappings,
                entityGraph,
                rootEntityTypes);

        var hasNavigations =
            navResult != null &&
            navResult.Navigations.Count > 0;

        var hasGraph =
            info.Graph != null &&
            !string.IsNullOrWhiteSpace(
                info.Graph.GraphName);

        if (!hasNavigations && !hasGraph)
            return;

        sb.AppendLine();

        if (hasNavigations)
        {
            EmitNavigationJoinsQueryNode(
                sb,
                info,
                allMappings,
                navResult!,
                entityGraph);
        }

        if (hasGraph)
        {
            var graph = info.Graph!;
            var fromAlias = string.IsNullOrEmpty(graph.From?.Alias) ? graph.From?.Label ?? "" : graph.From!.Alias!;
            var toAlias = string.IsNullOrEmpty(graph.To?.Alias) ? graph.To?.Label ?? "" : graph.To!.Alias!;

            sb.AppendLine("            QueryNode? __graphFrom = null;");
            sb.AppendLine("            QueryNode? __graphTo = null;");
            sb.AppendLine();
            sb.AppendLine("            foreach (var gc in node.Children)");
            sb.AppendLine("            {");
            sb.AppendLine($"                if (string.Equals(gc.OutputAlias, \"{fromAlias}\", System.StringComparison.OrdinalIgnoreCase))");
            sb.AppendLine("                    __graphFrom = GeneratedPlanners.BuildQueryNode(gc.EntityId, gc, isRoot: false);");
            sb.AppendLine($"                else if (string.Equals(gc.OutputAlias, \"{toAlias}\", System.StringComparison.OrdinalIgnoreCase))");
            sb.AppendLine("                    __graphTo = GeneratedPlanners.BuildQueryNode(gc.EntityId, gc, isRoot: false);");
            sb.AppendLine("            }");
            sb.AppendLine();
            sb.AppendLine("            if (__graphFrom != null || __graphTo != null)");
            sb.AppendLine($"                __plan = new GraphEdgeNode(__plan, GeneratedMetadata.{info.ModelType!.Name}Graph, __graphFrom, __graphTo);");
        }
    }

    private static void EmitNavigationJoins(
    StringBuilder sb,
    MappingClassInfo info,
    ImmutableArray<MappingClassInfo> allMappings,
    NavigationResolutionResult navResult,
    List<FluentEntityNavigationConvention.EntityForeignKeyGraph.Edge> entityGraph)
{
    foreach (var navigation in navResult.Navigations)
    {
        var joinPath =
            navigation.JoinPaths
                .Where(p => p.Hops.Count > 0)
                .OrderBy(p => p.Hops.Count)
                .FirstOrDefault();

        if (joinPath == null)
            continue;

        var navigationRequested =
            $"__hasChild_{navigation.NavigationName}";

        var navigationChildAlias =
            $"__childAlias_{navigation.NavigationName}";

        sb.AppendLine(
            $"            var {navigationRequested} = false;");

        sb.AppendLine(
            $"            string? {navigationChildAlias} = null;");

        sb.AppendLine(
            "            foreach (var __navChild in node.Children)");

        sb.AppendLine(
            "            {");

        sb.AppendLine(
            $"                if (string.Equals(__navChild.OutputAlias, \"{navigation.NavigationName}\", System.StringComparison.OrdinalIgnoreCase))");

        sb.AppendLine(
            "                {");

        sb.AppendLine(
            $"                    {navigationRequested} = true;");

        sb.AppendLine(
            $"                    {navigationChildAlias} = __navChild.OutputAlias;");

        sb.AppendLine(
            "                    break;");

        sb.AppendLine(
            "                }");

        sb.AppendLine(
            "            }");

        sb.AppendLine();

        sb.AppendLine(
            $"            if ({navigationRequested})");

        sb.AppendLine(
            "            {");

        var aliasByEntity =
            new Dictionary<INamedTypeSymbol, string>(
                SymbolEqualityComparer.Default);

        var firstHop = joinPath.Hops[0];

        var parentSeedEntity =
            info.Definition.Entities
                .FirstOrDefault(e =>
                    e.EntityType != null &&
                    (SymbolEqualityComparer.Default.Equals(
                         e.EntityType, firstHop.DependentEntity) ||
                     SymbolEqualityComparer.Default.Equals(
                         e.EntityType, firstHop.PrincipalEntity)))
                ?.EntityType;

        if (parentSeedEntity == null && info.EntityType != null &&
            (SymbolEqualityComparer.Default.Equals(info.EntityType, firstHop.DependentEntity) ||
             SymbolEqualityComparer.Default.Equals(info.EntityType, firstHop.PrincipalEntity)))
        {
            parentSeedEntity = info.EntityType;
        }

        if (parentSeedEntity != null)
        {
            aliasByEntity[parentSeedEntity] = "node.OutputAlias";
        }

        var index = 0;
        var lastHopIndex = joinPath.Hops.Count - 1;

        foreach (var edge in joinPath.Hops)
        {
            var fromIsDependent =
                aliasByEntity.ContainsKey(edge.DependentEntity);

            var fromEntity =
                fromIsDependent
                    ? edge.DependentEntity
                    : edge.PrincipalEntity;

            var toEntity =
                fromIsDependent
                    ? edge.PrincipalEntity
                    : edge.DependentEntity;

            var fromColumn =
                fromIsDependent
                    ? edge.DependentColumn
                    : edge.PrincipalColumn;

            var toColumn =
                fromIsDependent
                    ? edge.PrincipalColumn
                    : edge.DependentColumn;

            if (!aliasByEntity.TryGetValue(fromEntity, out var fromAlias))
            {
                throw new InvalidOperationException(
                    $"Navigation '{navigation.NavigationName}' on " +
                    $"'{info.ModelType!.Name}' has a disconnected join " +
                    $"path: no known alias for '{fromEntity.Name}' when " +
                    $"processing hop -> '{toEntity.Name}'.");
            }

            var fromStorageEntity =
                ResolveStorageEntityOrThrow(fromEntity, allMappings);

            var toStorageEntity =
                ResolveStorageEntityOrThrow(toEntity, allMappings);

            var fromStorageName =
                IdEmitter.StripEntitySuffix(fromStorageEntity.Name);

            var toStorageName =
                IdEmitter.StripEntitySuffix(toStorageEntity.Name);

            var resolvedFromColumn =
                ResolveStorageColumnName(fromStorageEntity, fromColumn);

            var resolvedToColumn =
                ResolveStorageColumnName(toStorageEntity, toColumn);

            var fromColumnId =
                ResolveStorageColumnId(
                    fromEntity, fromStorageName, resolvedFromColumn, allMappings, entityGraph);

            var toColumnId =
                ResolveStorageColumnId(
                    toEntity, toStorageName, resolvedToColumn, allMappings, entityGraph);
            
            bool isLastHop =
                index == lastHopIndex;

            string toAliasExpression;
            string toAliasForDictionary;

            if (isLastHop)
            {
                toAliasExpression =
                    navigationChildAlias!;

                toAliasForDictionary =
                    navigationChildAlias!;
            }
            else
            {
                var literalAlias =
                    $"{info.ModelType!.Name}_{navigation.NavigationName}_{toStorageName}_{index}";

                toAliasExpression =
                    $"\"{literalAlias}\"";

                toAliasForDictionary =
                    literalAlias;
            }

            aliasByEntity[toEntity] = toAliasForDictionary;

            sb.AppendLine(
                "            builder.AddJoin(");

            sb.AppendLine(
                fromAlias == "node.OutputAlias"
                    ? "                node.OutputAlias,"
                    : $"                \"{fromAlias}\",");

            sb.AppendLine(
                isLastHop
                    ? $"                {toAliasExpression}!,"
                    : $"                {toAliasExpression},");

            sb.AppendLine(
                $"                EntityId.{ResolveRuntimeEntityId(fromEntity, allMappings)},");

            sb.AppendLine(
                $"                StorageEntityId.{fromStorageName},");

            sb.AppendLine(
                $"                {fromColumnId},");

            sb.AppendLine(
                $"                EntityId.{ResolveRuntimeEntityId(toEntity, allMappings)},");

            sb.AppendLine(
                $"                StorageEntityId.{toStorageName},");

            sb.AppendLine(
                $"                {toColumnId},");

            sb.AppendLine(
                "                JoinKind.Left);");

            sb.AppendLine();

            index++;
        }

        sb.AppendLine(
            "            }");
    }
}

    /// <summary>
    /// BuildQueryNode counterpart to EmitNavigationJoins. Same hop
    /// resolution (same from/to orientation per hop, seeded the same way
    /// from parentSeedEntity), but instead of resolving columns itself and
    /// calling builder.AddJoin, it looks the join up via
    /// GeneratedMetadata.GetJoin(fromStorageId, toStorageId) -- already
    /// generated by IdEmitter from this same entityGraph edge set -- and
    /// nests it as a JoinNode. Intermediate hops get a bare ScanNode; the
    /// last hop joins against the child's own recursively-built subtree so
    /// the child's columns/further children come along in one call.
    /// </summary>
    private static void EmitNavigationJoinsQueryNode(
    StringBuilder sb,
    MappingClassInfo info,
    ImmutableArray<MappingClassInfo> allMappings,
    NavigationResolutionResult navResult,
    List<FluentEntityNavigationConvention.EntityForeignKeyGraph.Edge> entityGraph)
{
    foreach (var navigation in navResult.Navigations)
    {
        var joinPath =
            navigation.JoinPaths
                .Where(p => p.Hops.Count > 0)
                .OrderBy(p => p.Hops.Count)
                .FirstOrDefault();

        if (joinPath == null)
            continue;

        var childVar =
            $"__navChild_{navigation.NavigationName}";

        var childPlanVar =
            $"__childPlan_{navigation.NavigationName}";

        sb.AppendLine(
            $"            foreach (var {childVar} in node.Children)");
        sb.AppendLine(
            "            {");
        sb.AppendLine(
            $"                if (!string.Equals({childVar}.OutputAlias, \"{navigation.NavigationName}\", System.StringComparison.OrdinalIgnoreCase))");
        sb.AppendLine(
            "                    continue;");
        sb.AppendLine();
        sb.AppendLine(
            $"                var {childPlanVar} = GeneratedPlanners.BuildQueryNode({childVar}.EntityId, {childVar}, isRoot: false);");
        sb.AppendLine();

        var seenEntities =
            new Dictionary<INamedTypeSymbol, bool>(
                SymbolEqualityComparer.Default);

        var firstHop = joinPath.Hops[0];

        var parentSeedEntity =
            info.Definition.Entities
                .FirstOrDefault(e =>
                    e.EntityType != null &&
                    (SymbolEqualityComparer.Default.Equals(
                         e.EntityType, firstHop.DependentEntity) ||
                     SymbolEqualityComparer.Default.Equals(
                         e.EntityType, firstHop.PrincipalEntity)))
                ?.EntityType;

        if (parentSeedEntity == null && info.EntityType != null &&
            (SymbolEqualityComparer.Default.Equals(info.EntityType, firstHop.DependentEntity) ||
             SymbolEqualityComparer.Default.Equals(info.EntityType, firstHop.PrincipalEntity)))
        {
            parentSeedEntity = info.EntityType;
        }

        if (parentSeedEntity != null)
        {
            seenEntities[parentSeedEntity] = true;
        }

        var index = 0;
        var lastHopIndex = joinPath.Hops.Count - 1;

        foreach (var edge in joinPath.Hops)
        {
            var fromIsDependent =
                seenEntities.ContainsKey(edge.DependentEntity);

            var fromEntity =
                fromIsDependent
                    ? edge.DependentEntity
                    : edge.PrincipalEntity;

            var toEntity =
                fromIsDependent
                    ? edge.PrincipalEntity
                    : edge.DependentEntity;

            if (!seenEntities.ContainsKey(fromEntity))
            {
                throw new InvalidOperationException(
                    $"Navigation '{navigation.NavigationName}' on " +
                    $"'{info.ModelType!.Name}' has a disconnected join " +
                    $"path: '{fromEntity.Name}' was not seen before " +
                    $"processing hop -> '{toEntity.Name}'.");
            }

            var fromStorageEntity =
                ResolveStorageEntityOrThrow(fromEntity, allMappings);

            var toStorageEntity =
                ResolveStorageEntityOrThrow(toEntity, allMappings);

            var fromStorageName =
                IdEmitter.StripEntitySuffix(fromStorageEntity.Name);

            var toStorageName =
                IdEmitter.StripEntitySuffix(toStorageEntity.Name);

            bool isLastHop =
                index == lastHopIndex;

            seenEntities[toEntity] = true;

            sb.AppendLine(
                isLastHop
                    ? $"                __plan = new JoinNode(__plan, {childPlanVar}, GeneratedMetadata.GetJoin(StorageEntityId.{fromStorageName}, StorageEntityId.{toStorageName})!);"
                    : $"                __plan = new JoinNode(__plan, new ScanNode(GeneratedMetadata.GetEntity(StorageEntityId.{toStorageName})), GeneratedMetadata.GetJoin(StorageEntityId.{fromStorageName}, StorageEntityId.{toStorageName})!);");

            index++;
        }

        sb.AppendLine(
            "                break;");
        sb.AppendLine(
            "            }");
    }
}

    private static void EmitGraphVertexResultJoins(
    StringBuilder sb,
    MappingClassInfo info,
    ImmutableArray<MappingClassInfo> allMappings,
    List<FluentEntityNavigationConvention.EntityForeignKeyGraph.Edge> entityGraph)
{
    var g = info.Graph!;


    var graphAlias =
        $"{info.EntityType!.Name}_{g.EdgeLabel}_graph";


    sb.AppendLine(
        "            builder.AddGraphJoin(");


    sb.AppendLine(
        $"                EntityId.{ResolveRuntimeEntityId(info.EntityType, allMappings)},");


    sb.AppendLine(
        $"                StorageEntityId.{IdEmitter.StripEntitySuffix(info.EntityType.Name)},");


    sb.AppendLine(
        $"                \"{g.GraphName}\",");

    sb.AppendLine(
        $"                \"{g.EdgeLabel}\",");

    sb.AppendLine(
        $"                \"{g.EdgeKey}\",");

    sb.AppendLine(
        $"                \"{g.From.Label}\",");

    sb.AppendLine(
        $"                \"{g.From.GraphProperty}\",");

    sb.AppendLine(
        $"                \"{g.From.Alias ?? g.From.Label}\",");

    sb.AppendLine(
        $"                \"{g.FromJoinColumn}\",");

    sb.AppendLine(
        $"                \"{g.To.Label}\",");

    sb.AppendLine(
        $"                \"{g.To.GraphProperty}\",");

    sb.AppendLine(
        $"                \"{g.To.Alias ?? g.To.Label}\",");

    sb.AppendLine(
        $"                \"{g.ToJoinColumn}\",");

    sb.AppendLine(
        $"                \"{graphAlias}\");");


    foreach (var (vertex, isFrom) in new[]
    {
        (g.From, true),
        (g.To, false)
    })
    {
        var alias =
            vertex.Alias ?? vertex.Label;


        var relatedModel =
            allMappings.FirstOrDefault(m =>
                m.EntityType != null &&
                string.Equals(
                    IdEmitter.StripEntitySuffix(m.EntityType.Name),
                    IdEmitter.StripEntitySuffix(vertex.Label),
                    StringComparison.OrdinalIgnoreCase));


        if (relatedModel?.EntityType == null)
            continue;


        var joinColumn =
            isFrom
                ? g.FromJoinColumn
                : g.ToJoinColumn;


        var storageEntityName =
            IdEmitter.StripEntitySuffix(
                relatedModel.EntityType.Name);


        var graphColumnAlias =
            alias + joinColumn;


        var columnExpression =
            ColumnIdResolver.Resolve(
                relatedModel.EntityType,
                joinColumn,
                allMappings,
                entityGraph);


        var runtimeEntityId =
            ResolveRuntimeEntityId(
                relatedModel.EntityType,
                allMappings);


        sb.AppendLine(
            "            foreach (var gc in node.Children)");

        sb.AppendLine(
            "            {");


        sb.AppendLine(
            $"                if (string.Equals(gc.OutputAlias, \"{alias}\", System.StringComparison.OrdinalIgnoreCase))");

        sb.AppendLine(
            "                {");


        sb.AppendLine(
            "                    builder.AddGraphResultJoin(");


        sb.AppendLine(
            $"                        \"{graphAlias}\",");


        sb.AppendLine(
            $"                        \"{graphColumnAlias}\",");


        sb.AppendLine(
            $"                        EntityId.{runtimeEntityId},");


        sb.AppendLine(
            $"                        StorageEntityId.{storageEntityName},");


        sb.AppendLine(
            $"                        {columnExpression},");


        sb.AppendLine(
            "                        JoinKind.Left,");


        sb.AppendLine(
            "                        gc.OutputAlias);");


        sb.AppendLine(
            "                }");


        sb.AppendLine(
            "            }");
    }
}
    
    private static void EmitScalarSelection(
    StringBuilder sb,
    MappingClassInfo info,
    ImmutableArray<MappingClassInfo> allMappings,
    List<FluentEntityNavigationConvention.EntityForeignKeyGraph.Edge> entityGraph)
{
    var fields =
        ComputeFieldMappingsEagerPublic(
            info,
            info.IsComposite);


    if (fields.Count == 0)
        return;


    sb.AppendLine();
    sb.AppendLine(
        "            foreach (var scalar in node.Scalars)");

    sb.AppendLine(
        "            {");

    sb.AppendLine(
        "                switch (scalar.FieldId)");

    sb.AppendLine(
        "                {");


    foreach (var group in fields.GroupBy(
                 x => x.FieldName,
                 StringComparer.Ordinal))
    {
        sb.AppendLine(
            $"                    case FieldId.{info.ModelType!.Name}.{group.Key}:");

        sb.AppendLine(
            "                    {");


        foreach (var field in group)
        {
            var entity =
                info.Definition.Entities
                    .FirstOrDefault(e =>
                        e.EntityType != null &&
                        string.Equals(
                            IdEmitter.StripEntitySuffix(e.EntityType.Name),
                            IdEmitter.StripEntitySuffix(field.EntityTypeName),
                            StringComparison.OrdinalIgnoreCase))
                    ?.EntityType;


            if (entity == null)
            {
                throw new InvalidOperationException(
                    $"Cannot resolve entity '{field.EntityTypeName}' for field '{field.FieldName}'.");
            }


            var storageName =
                IdEmitter.StripEntitySuffix(entity.Name);


            var column =
                ColumnIdResolver.Resolve(
                    entity,
                    field.ColumnName,
                    allMappings,
                    entityGraph);


            var runtimeEntityId =
                ResolveRuntimeEntityId(
                    entity,
                    allMappings);


            sb.AppendLine(
                "                        builder.AddColumn(");


            sb.AppendLine(
                $"                            EntityId.{runtimeEntityId},");


            sb.AppendLine(
                $"                            StorageEntityId.{storageName},");


            sb.AppendLine(
                $"                            {column},");


            sb.AppendLine(
                "                            node.OutputAlias,");


            sb.AppendLine(
                "                            scalar.OutputAlias);");
        }


        sb.AppendLine(
            "                        break;");


        sb.AppendLine(
            "                    }");
    }


    sb.AppendLine(
        "                }");


    sb.AppendLine(
        "            }");
}

    /// <summary>
    /// BuildQueryNode counterpart to EmitScalarSelection: same FieldId
    /// switch (so it stays valid whatever the client actually selected),
    /// but each case appends a FieldBinding instead of calling
    /// builder.AddColumn. TargetFieldId carries the generated FieldId --
    /// materialization resolves the wire alias later via SelectionIR,
    /// it is deliberately not baked into the logical plan.
    /// </summary>
    private static void EmitScalarSelectionQueryNode(
        StringBuilder sb,
        MappingClassInfo info,
        ImmutableArray<MappingClassInfo> allMappings,
        List<FluentEntityNavigationConvention.EntityForeignKeyGraph.Edge> entityGraph)
    {
        var fields =
            ComputeFieldMappingsEagerPublic(
                info,
                info.IsComposite);

        if (fields.Count == 0)
            return;

        sb.AppendLine();
        sb.AppendLine(
            "            var __fields = new List<FieldBinding>();");
        sb.AppendLine(
            "            foreach (var scalar in node.Scalars)");
        sb.AppendLine(
            "            {");
        sb.AppendLine(
            "                switch (scalar.FieldId)");
        sb.AppendLine(
            "                {");

        foreach (var group in fields.GroupBy(
                     x => x.FieldName,
                     StringComparer.Ordinal))
        {
            sb.AppendLine(
                $"                    case FieldId.{info.ModelType!.Name}.{group.Key}:");
            sb.AppendLine(
                "                    {");

            foreach (var field in group)
            {
                var entity =
                    info.Definition.Entities
                        .FirstOrDefault(e =>
                            e.EntityType != null &&
                            string.Equals(
                                IdEmitter.StripEntitySuffix(e.EntityType.Name),
                                IdEmitter.StripEntitySuffix(field.EntityTypeName),
                                StringComparison.OrdinalIgnoreCase))
                        ?.EntityType;

                if (entity == null)
                {
                    throw new InvalidOperationException(
                        $"Cannot resolve entity '{field.EntityTypeName}' for field '{field.FieldName}'.");
                }

                var storageName =
                    IdEmitter.StripEntitySuffix(entity.Name);

                var column =
                    ColumnIdResolver.Resolve(
                        entity,
                        field.ColumnName,
                        allMappings,
                        entityGraph);

                sb.AppendLine(
                    "                        __fields.Add(new FieldBinding(" +
                    $"new ColumnReference(GeneratedMetadata.GetEntity(StorageEntityId.{storageName}), {column}), " +
                    "scalar.FieldId));");
            }

            sb.AppendLine(
                "                        break;");
            sb.AppendLine(
                "                    }");
        }

        sb.AppendLine(
            "                }");
        sb.AppendLine(
            "            }");
        sb.AppendLine();
        sb.AppendLine(
            "            if (__fields.Count > 0)");
        sb.AppendLine(
            "                __plan = new ProjectionNode(__plan, __fields);");
    }

    private static string ResolveCompositeAlias(
        MappingClassInfo info,
        INamedTypeSymbol entity,
        string nodeOutputAlias)
    {
        if (SymbolEqualityComparer.Default.Equals(
                info.EntityType,
                entity))
        {
            return nodeOutputAlias;
        }

        return $"\"{info.ModelType!.Name}_{IdEmitter.StripEntitySuffix(entity.Name)}\"";
    }
    
    internal static List<ChildLinkInfo> ComputeChildLinks(
        MappingClassInfo parent,
        ImmutableArray<MappingClassInfo> mappings,
        Dictionary<string, NavigationResolutionResult?> navResults,
        List<FluentEntityNavigationConvention.EntityForeignKeyGraph.Edge> entityGraph)
    {
        var result =
            new List<ChildLinkInfo>();


        if (parent.ModelType == null)
            return result;


        if (!navResults.TryGetValue(
                parent.ModelType.Name,
                out var nav) ||
            nav == null)
        {
            return result;
        }


        foreach (var navigation in nav.Navigations)
        {
            var child =
                mappings.FirstOrDefault(x =>
                    x.ModelType != null &&
                    string.Equals(
                        x.ModelType.Name,
                        navigation.TargetModel.Name,
                        StringComparison.OrdinalIgnoreCase));


            if (child == null)
                continue;


            var entity =
                child.EntityType ??
                child.Definition.Entities
                    .FirstOrDefault(x => x.IsPrimary)
                    ?.EntityType;


            if (entity == null)
                continue;


            var property =
                parent.ModelType
                    .GetMembers()
                    .OfType<IPropertySymbol>()
                    .FirstOrDefault(p =>
                        string.Equals(
                            p.Name,
                            navigation.NavigationName,
                            StringComparison.Ordinal));


            var isCollection =
                property?.Type is INamedTypeSymbol named &&
                named.IsGenericType;



            result.Add(
                new ChildLinkInfo(
                    navigation.NavigationName,
                    child.ModelType.Name,
                    entity.Name,
                    isCollection));
        }


        return result
            .Distinct()
            .ToList();
    }

    private static void EmitRegistry(
        StringBuilder sb,
        List<MappingClassInfo> models)
    {
        sb.AppendLine(
            "public static class PlannerRegistry");

        sb.AppendLine("{");

        sb.AppendLine(
            $"    public const ushort PlannerCount = {models.Count};");

        EmitRegistryQuery(sb, models);

        EmitRegistryHelpers(sb, models);

        sb.AppendLine("}");
    }
    
    private static void EmitRegistryQuery(
        StringBuilder sb,
        List<MappingClassInfo> models)
    {
        sb.AppendLine(
            "    public static void Build(");

        sb.AppendLine(
            "        ushort entityId,");

        sb.AppendLine(
            "        in SelectionIR selection,");

        sb.AppendLine(
            "        ref QueryPlanBuilder builder,");

        sb.AppendLine(
            "        bool isRoot)");

        sb.AppendLine(
            "    {");


        sb.AppendLine(
            "        switch (entityId)");

        sb.AppendLine(
            "        {");


        foreach (var model in models)
        {
            if (model.ModelType == null)
                continue;


            sb.AppendLine(
                $"            case EntityId.{model.ModelType.Name}:");

            sb.AppendLine(
                $"                {model.ModelType.Name}Planner.Build(selection, ref builder, isRoot);");

            sb.AppendLine(
                "                return;");
        }


        sb.AppendLine(
            "            default:");

        sb.AppendLine(
            "                ThrowUnknownEntity(entityId);");

        sb.AppendLine(
            "                return;");


        sb.AppendLine(
            "        }");


        sb.AppendLine(
            "    }");

        sb.AppendLine();

        sb.AppendLine(
            "    public static QueryNode BuildQueryNode(");

        sb.AppendLine(
            "        ushort entityId,");

        sb.AppendLine(
            "        in SelectionIR selection,");

        sb.AppendLine(
            "        bool isRoot)");

        sb.AppendLine(
            "    {");

        sb.AppendLine(
            "        switch (entityId)");

        sb.AppendLine(
            "        {");

        foreach (var model in models)
        {
            if (model.ModelType == null)
                continue;

            sb.AppendLine(
                $"            case EntityId.{model.ModelType.Name}:");

            sb.AppendLine(
                $"                return {model.ModelType.Name}Planner.BuildQueryNode(selection, isRoot);");
        }

        sb.AppendLine(
            "            default:");

        sb.AppendLine(
            "                ThrowUnknownEntity(entityId);");

        sb.AppendLine(
            "                return default!;");

        sb.AppendLine(
            "        }");

        sb.AppendLine(
            "    }");
    }

